//     另加**档 12 = 亮度灰阶**（画面直接换成 8 位灰度 Y，一眼看亮度分布）。
//
// M2 · 运动门 第 4 轮（2026-10-16，用户上板读数："档 14 都是红色和青色、档 13 都是青色和绿色、
//   档 14 杂码还是有点多"）：
