// recog_top —— 识别支路容器（VIDEO_TAP 插座的消费者，CSI 域）
//
// 取点位置：isp_top 内部、RAW/EDGE MUX **之前**——RAW 是 AWB 输出的彩色流，
// EDGE 是 edge_detect_96 的梯度流。EDGE 模式下彩色流依然存在，所以肤色/运动
// 掩码两种模式都能用（这是把取点放在 MUX 之前的原因）。
//
// M0 内容（只有地基，没有识别算法）：
//   * tap 监视：数每一帧的 tap 字数（像素数 = 字数×4），帧首锁存成 >>10 的输出，
//     1280x720 期望 0x0384 —— 用来证明抽头接的是完整的一帧；
//   * 掩码统计：掩码源先固定为"边缘非零"（M1 再接肤色/运动/融合），实例化
//     mask_stats，输出像素数 >>4 与包围盒（16 像素粒度）；
//   * CTRL_SYNC 上行端点：M0 把收到的下行字原样回传（往返自检），M1 换成真实
//     识别结果（质心/手型/事件）。
//
// M1 Step 1 内容（2026-09-20，肤色掩码）：
//   * 在 tap 点取 RAW（AWB 彩色流）重算一份 Y = R/4+G/2+B/4（不动已验证的
//     edge_win_3x3_96），逐像素做 (B−Y)/(R−Y) 双区间判定 → 4 bit 肤色掩码；
//   * 掩码源用编译期参数 MASK_SRC 选：2 = 融合（肤色 ∩ 运动，Step 2 默认）、
//     1 = 只看肤色、0 = M0 的"边缘非零"自检源（回归用）。源选在综合时是常量，
//     不生成 mux，也**不生成用不到的那条支路**（运动支路在 generate 里）；
//   * 接的还是同一个 mask_stats，所以 DBG 的 P/Q/R 直接变成肤色像素数与包围盒，
//     不需要 C 加新字段；
//   * 阈值是模块参数（D1_*/D2_*，见下面注释），现场标定改这里 —— 在线调参要等 C
//     把 A 段 0x40~0x7F 的寄存器经一条 ctrl_sync 送进 CSI 域（A 的待提需求）。
//
// M1 Step 2 内容（2026-09-20，运动掩码 + 融合）：
//   * 背景帧 80x45：块 = 16x16 像素（x[10:4], y[9:4]），每块一个 8 bit 灰度参考值，
//     线性地址 = y[9:4]*80 + x[10:4]，共 3600 块 → 2 块 ERAM（eram_spram 2048x8 x2）；
//   * 运动掩码 = |当前像素灰度 − 本块背景灰度| > MOTION_TH，与肤色掩码按位与出融合掩码；
//   * 背景更新 = quiet 门控 + 限速蠕变：只有 |样本 − 背景| < QUIET_TH（且 QUIET_TH <
//     MOTION_TH，形成滞回）的块才动，且每块每 2^6=64 帧最多动 1 个 LSB；
//   * **上电自举**：复位后前 BOOT_FRAMES 帧把每块直接装载成样本值（否则背景全是 0，
//     运动掩码会恒 1、融合退化成纯肤色）。规划里的"KEY4 长按手动采样"要等 C 把
//     teach_req 送进 CSI 域，见 Step 4；在那之前**开机时画面里别放手**。
//
// 几何提醒：肤色源用的是 RAW 的字几何（字内 [95:72] 是最左像素），而 mask_stats
// 的列号按"列 4k-1..4k+2"（边缘流那套，边缘图整体比 RAW 左移 1 像素）算，所以
// 肤色掩码的列号整体偏左 1 像素 —— Q 是 16 像素粒度，看不出来；M2 做指尖坐标
// 对齐时按任务清单 §4 处理。
//
// M1 Step 3/4/5 内容（2026-09-20 起，见下面各段的段落注释）：
//   * Step 3：ROI 门控（锁定后只在上一帧包围盒 ±ROI_MARGIN 内统计）+ α-β 平滑
//     （α = 1/2^ALPHA_SHIFT、β = 1/2^BETA_SHIFT，全移位、不做除法）+ 丢失保持
//     HOLD_FRAMES / 重锁 LOCK_FRAMES；
//   * Step 4：调试图叠加（掩码红、准星黄）、水平 3 点开运算去毛刺、目标尺寸/长宽比
//     门控（挡唇膏、笔这类小细物体）；
//   * Step 5（收尾）：准星观测从"包围盒中心"换成**掩码质心**（Σ列/Σ行 ÷ 像素数，
//     每帧一次串行除法）。参数 USE_CENTROID=0 可切回旧的包围盒中心做同板 A/B。
//
// M1 收尾 · 一键示教（2026-09-29，第 1~3 轮）：
//   * 第 1 轮：皮肤窗口 [d1,d2] 从编译期常量改成 **4 个运行时寄存器**（复位值 = 交付默认）；
//   * 第 2 轮：提交字 bit[19:16] teach_cnt 的事件检测搬到模块级（SKIN_ONLY=1 时也在）；
//   * 第 3 轮：一次事件 = 一个 60 帧采样窗 —— 把**固定中央区**里通过**宽松前置门**的像素
//     并成 (d1,d2) 包络，窗末判定（样本 ≥2000 且 d2 跨度 ≥10）通过就外扩 ≈14% 写进
//     窗口寄存器；判定不通过就一个数都不写。TEACH_EN=0 可把整段关掉（回到第 1 轮行为）。
//     （2026-09-29 压缩：采样密度改成"每 4 列取 1 列"——一拍只并 1 个像素、用 4 级延迟线错开，
//      省掉 4 像素 min/max 树；门限仍按真实像素数解释。见 g_teach 里的"采样密度"一段。）
//   * 第 4 轮：窗末起把 O_teach_flash 拉高 ~120 帧（≈2 s）——**不论判定过不过**（同板行为：
//     "没看到手点亮 = 没采到，重来"）；isp_top 把它并进叠加使能，示教完立刻能看手亮不亮。
//     平时恒 0，开机画面不受影响。第 5 轮才上板验收。
//   * 2026-09-30 上板回归（"手完全拿开、只对着桌面，示教后屏幕照样大片变红"）：
//     ① 前置门收窄到 d1∈[−115,−2]、d2∈[2,80]（原来 [−128,0]×[0,127] 背景就能填满）；
//     ② 写回时钳在安全带 d1∈[−120,0]、d2∈[0,90]；
//     ③ 自保：包络只要贴到前置门边（= 背景把框填满）→ 直接拒绝、不写窗口；
//     ④ **块级帧差门**（真解法）：中央区 40×23 = 920 块用 1 块 ERAM 存上一帧块样本，只有
//        "这块在动"的像素才进包络 → 静态背景一个块都不动、样本数不够 → 直接拒绝。
//        ⚠ 代价：示教时**手要动起来**（静止的手和不动的背景一样，进不了包络）。
//
// M2.1 内容（2026-10-11，挥手方向）：
//   * 复用 M1 的质心（不新增像素级统计）：质心延迟线 → 窗口净位移 Δx/Δy → 门限 + 轴占优
//     + 前半段同向 → 左挥/右挥/下劈事件脉冲（事件后装载延迟线 + ~300 ms 冷却）。
//   * 结果先用 DBG 的 P/Q/R 观测（GEST_DBG=1 的定标版；编码见下面 g_gest 段落注释）；
//     交付口径（GEST_DBG=0）P/Q/R 一字不动，挥手逻辑整段被综合裁掉 —— 真正的外送通道
//     要等 M2.3 找 C 要（CTRL_SYNC 上行按模式复用，或加第二个 26 位字）。
//
// 延迟：肤色判定与统计都是 0 拍组合计入（纯组合掩码 + 帧锁存输出），锁存发生在
//       所选用掩码源的 tuser 上；运动掩码同样是 0 拍组合（背景值在每块开始时就已经
//       预取到手，见下），所以融合掩码相对像素流不产生额外延迟；CTRL_SYNC 回传是
//       组合直连；质心的除法器在帧首后一拍启动、27 拍后出结果并保持整帧，不占
//       像素通路。
// 时钟域：CSI 域单时钟，不跨域（到像素域的同步在 design_top_wrapper 里做）。
// 资源：M0 地基约 150 FF + 100 LUT；肤色判定 ≈150~250 LUT6（4 像素并行，每像素
//       3 个移位加法 + 2 个 9 位减法 + 4 个比较）；运动支路 2 块 ERAM +
//       ≈60 FF + ≈150~250 LUT6（4 路 9 位减法/比较 + 块地址 + 更新控制）；跟踪 +
//       开运算 + 叠加选择 ≈120~180 LUT6 + ≈90 FF；质心除法器 ≈70 LUT6 + ≈130 FF。
//       合计 0 ERAM（运动支路那 2 块除外）/ 0 DSP。
// ============================================================================
module recog_top #(
    // ---- M1 Step 1 / Step 2：掩码源与阈值 ------------------------------------
    // 掩码源：0 = 边缘非零自检源（M0 行为，回归用）；1 = 肤色掩码；
    //         2 = 融合掩码（肤色 ∩ 运动，Step 2 默认）。
    parameter integer MASK_SRC = 2,

    // 肤色区间（9 位有符号，范围 −255..255）。**按 Y = R/4+G/2+B/4 标定，不要抄
    // 教科书的 Cb/Cr 数值**：第一版按《Step 1 开工包》取**偏宽**的区间，只作为上板
    // 标定的起点、不是结论（教科书 Cb∈[77,127] / Cr∈[133,173] 换算过来是
    // d1∈[−90,−2] / d2∈[7,63]，比这组窄）。
    parameter signed [8:0] D1_MIN = -9'sd100,   // d1 = B−Y 下限
    parameter signed [8:0] D1_MAX =  -9'sd5,    // d1 = B−Y 上限
    parameter signed [8:0] D2_MIN =   9'sd0,    // d2 = R−Y 下限
    parameter signed [8:0] D2_MAX =  9'sd70,    // d2 = R−Y 上限

    // ---- 交付判据（2026-09-27 实测定标）----------------------------------------
    // d2 = R−Y 的下限，**交付档用它**（= 上板验证过的"档 14"判据）。3 是"桌面杂色可接受、手尽量多"的定标点。
    parameter signed [8:0] D2_MIN_DELIV = 9'sd3,
    // SKIN_ONLY=1：掩码与软权重**只认肤色**，把运动/锁存门整体旁路。
    //   为什么（2026-09-27 实测）：那道门**既挡不住**灯照亮的暖色桌面（交付档桌面仍有色），
    //   **又拖累**准星 —— 锁存是 16×16 块级、断续的，会把软权重的支撑打成一片一片，
    //   Σw 忽高忽低 → 命中/丢失反复切换 → 准星一顿一顿。设回 0 可恢复"肤色∧锁存"的旧行为。
    // ⚠ 2026-10-11（方案 A）：这里原来是 1（交付档）——**它把运动掩码短路成全 1**
    //   （见 `assign S_motion_mask = S_skin_only ? 4'b1111 : ...`），于是
    //   `S_fusion_mask = 肤色 ∧ 运动` 退化成"只看肤色"，静止的暖桌面照样全过 →
    //   "桌面高亮 + 准星被桌面拽"就是这么来的。
    //   置 0 后：硬掩码 = 肤色 ∩ **这一块最近动过**（背景帧 + 块级活动锁存，M1 现成的，
    //   2 块 ERAM 本来就在），软权重也恢复成 min(肤色分, 运动分) → 静止桌面两条路都不认。
    //   代价（M1 记录过）：手**停住**超过背景自愈时间会掉掩码 → 靠 HOLD/LOCK 兜；
    //   若"手一停准星就丢"影响体验，把它改回 1（= 只对掩码加运动门、权重仍只看肤色）。
    // ⚠ 2026-10-11（重要教训）：上一版把它置 0 打开融合，上板结果很差——**掩码几乎不出来、
    //   出来也只闪一下**。原因：背景帧是在开机前 32 帧自举的，而测试时**手正好在画面里**，
    //   于是"手"被当成了背景 → 手和背景一样 → 运动分恒 0 → 融合掩码恒 0（闪一下 = 手快速
    //   移动时偶尔超过差分门限）。M1 的注释其实写着前提："**开机时画面里别放手**"。
    //   → 现已改回 1（只看肤色），改用滑窗多数投票（VOTE_*）去桌面斑点，**不依赖背景帧、
    //   也不依赖开机姿态**。若以后要用融合：必须"手拿开再上电/复位"，或手拿开时长按 KEY4
    //   重新基线化（REBASE_ON_TEACH=1）。
    parameter integer SKIN_ONLY = 1,

    // ---- 档 19/20 的**亮度上限**（2026-09-27）--------------------------------
    // 档 10 之所以能挡住"灯照亮的桌面"，本质是"过亮的像素落不进那个窗口"（旧 Y 下 k=2 的像素
    // 永远过不了）。这两档把这个效果**显式化**：只有 Y ≤ Y_CAP 的像素才算肤色，两个值同板对比。
    parameter [7:0] Y_CAP_A = 8'd200,
    parameter [7:0] Y_CAP_B = 8'd176,

    // 运动阈值：|当前灰度 − 背景灰度| 大于它才算"这个像素在动"。
    parameter signed [8:0] MOTION_TH = 9'sd8,
    // quiet 阈值：块背景允许蠕变的"死区"，必须 < MOTION_TH（滞回）：
    // 样本与背景差得少才认为这块是静背景、可以慢慢跟；差得多说明有前景，不许动。
    parameter signed [8:0] QUIET_TH  = 9'sd4,
    // 块内用哪一行做背景采样（16 行里的第几行，取中间行）。
    parameter [3:0] BG_SAMPLE_ROW = 4'd7,
    // ---- 2026-09-26 第二步：治"灯照亮的桌面一片在动" ---------------------------
    // MOTION_REL=1：运动门限随**该块自己的背景亮度**缩放（(|d|<<3) > bg，即相对差 12.5%）。
    //   亮度变化是**乘性**的，而 GLB_COMP 只按整帧均值做**加法**补偿 —— 同样的 5% 变化，
    //   均值 60 的块只变 +3，亮块 200 变 +10，补完还留 +7 残差，全堆在最亮的区域。
    parameter integer MOTION_REL = 1,
    // BG_HEAL=1：背景"自愈"——拆掉旧的 quiet 单向棘轮（只有 |diff|<4 才允许蠕变，
    //   误差 >=4 的块永远冻结，而出错的恰恰是这些块）。自愈：每块每 16 帧一次机会，
    //   步长 = |diff|>>3 钳在 1..8。
    parameter integer BG_HEAL = 1,
    // 只自愈 |diff| <= 这个值的块。默认 255 = 全都自愈；调小可防"静止的手被吸进背景"
    // （例如 64：光照漂移式残差会自愈，手这种大反差不动）。
    parameter [8:0]   HEAL_MAX = 9'sd255,
    // BG_SAMPLE2=1：背景采样用**两个**采样行（16 像素，6.25%）。原来只采一行前 8 像素（3%）。
    parameter integer BG_SAMPLE2 = 1,
    parameter [3:0]   BG_SAMPLE_ROW2 = 4'd15,
    // ---- 2026-09-26 第三步：运动门改成"帧差 + 块级锁存"（治"亮区一片在动"的**结构**改法）----
    // LATCH_MODE=1 时，运动门不再拿"和背景比"：
    //   ① 块采样均值相对**上一帧**变化 → 这块"在动"（帧差：静态场景结构上就是 0，
    //      跟纹理、光照、块大小全都无关）；
    //   ② 块级锁存计数器：动过置满，之后每 4 帧减 1（LATCH_MAX=15 → 约 1.0 s）；
    //   ③ 掩码 = 肤色 ∧ 锁存 → 手整体高亮（肤色给面积），静止的桌面没有锁存 → 0 误报。
    // 为什么必须换：16x16 一个背景值，块内本来就有反差，背景收敛到"块内均值"之后，
    // 块内比均值亮/暗超过门限的像素**永远**是"在动"——这是模型的分辨率下限，调阈值/加自愈都治不了。
    parameter integer LATCH_MODE = 1,
    parameter [3:0]   LATCH_MAX  = 4'd15,
    // REBASE_ON_TEACH=1：提交字 bit[19:16]（teach_cnt）一变就重新自举背景（长按 KEY4 触发）。
    parameter integer REBASE_ON_TEACH = 1,
    // 上电自举帧数：这几帧里每块无条件装载样本值（之后转为 quiet 蠕变）。
    // 取 32（≈0.5 s）是故意留出 AWB 收敛时间——AWB 是自适应的，开机头几帧的颜色
    // 还没稳，拿那时的灰度当背景会得到一个整体偏色的参考值，而 quiet 门控又不会
    // 自己爬回来，现象就是"开机后满屏都在动"。最后一次写入生效，所以窗口越长越稳。
    parameter [5:0] BOOT_FRAMES = 6'd32,

    // ---- M1 Step 3：ROI 门控 / α-β 平滑 / 丢失保持 ---------------------------
    // 命中阈值：一帧的掩码像素数低于它就当作"没看到目标"（2000 px ≈ 45x45）。
    parameter [19:0] MIN_CNT = 20'd4000,
    // ---- 准星稳定性（治"静止时乱动"）----------------------------------------
    // 死区：观测与当前位置差小于它就当没看见（噪声级抖动不再推准星）。
    parameter signed [12:0] DEADBAND = 13'sd2,
    // 最大包围盒：超过它就认为是"全屏散布的噪声点"而不是目标（手最大也就 1/3 画面 ≈ 400px）。
    parameter [10:0] MAX_W = 11'd720,
    parameter [10:0] MAX_H = 11'd720,

    // ---- 软权重跟踪（2026-09-26）---------------------------------------------
    // **交付行为（2026-09-27 定为 1）**：1 = 观测用"软权重"：每像素 w = min(皮肤分 0~2, 运动分 0~2)，质心 = Σ(w·列)/Σw。
    //     **治"不灵敏"的关键**：硬 AND 只有两个门都过才有观测（暗环境里时通时断 → 准星一顿
    //     一顿）；软权重只要有一点点证据就有票 → 观测几乎每帧都有，准星能连续跟；而噪声/
    //     光照边缘的权重低，拉不走准星。
    parameter integer SOFT_TRACK = 1,
    parameter [20:0] MIN_WSUM = 21'd2000,   // Σw 的命中下限（≈ w=1 的像素数）
    parameter [20:0] MIN_WSUM_HOLD = 21'd1200,  // S3：已锁定时"保持命中"的更低门限（滞回，防反复丢锁）
    // ROI 外扩余量（像素）：锁定后只在"上一帧包围盒 ± 这个余量"内统计，
    // 窗口外的干扰被物理隔离。
    // ROI 余量：手快速移动时也要留在窗口里（太小会"滑出窗口 → 判丢失 → 准星停住"）。
    parameter [10:0] ROI_MARGIN = 11'd160,
    // 连续几帧命中才认为重新锁定（验收：回画 3 帧内重锁）。
    parameter [3:0]  LOCK_FRAMES = 4'd3,
    // 连续几帧打不中才认为丢失（验收：出画 5 帧内丢失）。
    parameter [3:0]  HOLD_FRAMES = 4'd5,
    // ---- Step 4 调优：准星尺寸 / 目标形状门控 -------------------------------
    parameter [10:0] CROSS_LEN = 11'd10,   // 准星半臂长（像素）
    parameter [10:0] CROSS_TH  = 11'd1,    // 准星线宽（±CROSS_TH，即 3 像素宽）
