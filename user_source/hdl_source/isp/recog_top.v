//             用 M1 档 10 那句老话："过亮的像素落不进窗口"。
//   定标配方写在 g_obs 的段落注释里（只对反光读一次、只对手读一次，取中间值）。
//
// M2 · 运动门 第 3 轮（2026-10-16，用户上板读数："档 13 全绿、档 14 杂码没了但手也很少、
//   档 4 什么都没有"）：
