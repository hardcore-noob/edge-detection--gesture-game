    wire [23:0] S_raw_pix0 = I_raw_tdata[95:72];   // 字内最左像素
    wire [23:0] S_raw_pix1 = I_raw_tdata[71:48];
    wire [23:0] S_raw_pix2 = I_raw_tdata[47:24];
    wire [23:0] S_raw_pix3 = I_raw_tdata[23:0];

