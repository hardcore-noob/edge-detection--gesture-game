    wire [7:0] S_gray2 = {2'b0, S_raw_pix2[23:18]} + {1'b0, S_raw_pix2[15:9]} + {2'b0, S_raw_pix2[7:2]};
    wire [7:0] S_gray3 = {2'b0, S_raw_pix3[23:18]} + {1'b0, S_raw_pix3[15:9]} + {2'b0, S_raw_pix3[7:2]};

