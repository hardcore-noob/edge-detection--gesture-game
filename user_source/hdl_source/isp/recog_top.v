    wire [7:0] S_ynew1 = S_ysum1[9:2];
    wire [7:0] S_ynew2 = S_ysum2[9:2];
    wire [7:0] S_ynew3 = S_ysum3[9:2];
    wire [7:0] S_y0 = S_y_new ? S_ynew0 : S_gray0;
    wire [7:0] S_y1 = S_y_new ? S_ynew1 : S_gray1;
    wire [7:0] S_y2 = S_y_new ? S_ynew2 : S_gray2;
    wire [7:0] S_y3 = S_y_new ? S_ynew3 : S_gray3;

    // 每像素两个色差（9 位有符号）：d1 = B−Y、d2 = R−Y。判据 v1/v2 与诊断上报共用。
    wire signed [8:0] S_d1_0 = {1'b0, S_raw_pix0[7:0]} - {1'b0, S_y0};
    wire signed [8:0] S_d1_1 = {1'b0, S_raw_pix1[7:0]} - {1'b0, S_y1};
    wire signed [8:0] S_d1_2 = {1'b0, S_raw_pix2[7:0]} - {1'b0, S_y2};
    wire signed [8:0] S_d1_3 = {1'b0, S_raw_pix3[7:0]} - {1'b0, S_y3};
    wire signed [8:0] S_d2_0 = {1'b0, S_raw_pix0[23:16]} - {1'b0, S_y0};
    wire signed [8:0] S_d2_1 = {1'b0, S_raw_pix1[23:16]} - {1'b0, S_y1};
    wire signed [8:0] S_d2_2 = {1'b0, S_raw_pix2[23:16]} - {1'b0, S_y2};
    wire signed [8:0] S_d2_3 = {1'b0, S_raw_pix3[23:16]} - {1'b0, S_y3};

    // 判据 v1：(B−Y)/(R−Y) 矩形。Y 由档位决定（旧 S_gray / 新 S_ynew）。
    // ---- 【第 1 轮】皮肤窗口 = 运行时寄存器 ---------------------------------
    // 复位值 = 交付默认（d1∈[D1_MIN,D1_MAX]、d2∈[D2_MIN_DELIV,D2_MAX]）。
    // 第 3 轮的"一键示教"只往这 4 个寄存器写数 —— 判据路径从此不再被后续改动触碰。
    // 档 8（旧 Y 全宽松）与档 9（d2≥5 标定参照）仍走编译期常量/固定值，与示教解耦。
    reg signed [8:0] S_win_d1_lo, S_win_d1_hi, S_win_d2_lo, S_win_d2_hi;
    always @(posedge I_clk or negedge I_rst_n) begin
        if(!I_rst_n) begin
            S_win_d1_lo <= D1_MIN;        S_win_d1_hi <= D1_MAX;
            S_win_d2_lo <= D2_MIN_DELIV;  S_win_d2_hi <= D2_MAX;
        end
        // 【第 3 轮】一键示教：窗末判定通过的那一拍，把包络写进这 4 个寄存器。
        // **只有这一处**写它们（判定不通过就一个数都不写，保持原窗口）。
        else if(S_teach_apply) begin
            S_win_d1_lo <= S_teach_d1_lo;
            S_win_d1_hi <= S_teach_d1_hi;
            S_win_d2_lo <= S_teach_d2_lo;
            S_win_d2_hi <= S_teach_d2_hi;
        end
    end

    // ========================================================================
    // 【第 3 轮】一键示教：采样窗状态机 + (d1,d2) 包络 + 窗末判定与写入
    //
    // 一次示教 = 一个 60 帧（≈1 s）的采样窗：
    //   * 窗内每一拍把**固定中央区**（x∈[TEACH_X0,TEACH_X1]、y∈[TEACH_Y0,TEACH_Y1]）里
    //     通过**宽松前置门**（d1∈[−128,0] ∧ d2∈[0,127]）的像素并进包络：d1/d2 各记
    //     min/max，同时数像素个数；
    //   * 窗末（第 60 帧的帧首）判一次：样本数 ≥ TEACH_MIN_PIX **且** d2 跨度 ≥
    //     TEACH_MIN_D2SPAN → 包络上下限各自按**自身跨度**外扩 (span>>3)+(span>>6)
    //     （≈14%，lo 向下、hi 向上）后**一次**写进 4 个运行时窗口寄存器；否则什么都不写。
    // 为什么采样区是固定中央区：ROI 的边界跟着跟踪状态走（锁定/丢失会跳），拿它当采样区会
    //   让"同样的手"示教出不同的窗口。
    // 为什么用 min/max 包络而不是均值±方差：方差要累加平方（成本高、现场难解释）；包络只要
    //   比较 + 选择，而且上下限能**分别**外扩（肤色分布本来就不对称）。
    // 资源：≈200 LUT6 / ≈75 FF / 0 ERAM / 0 DSP；TEACH_EN=0 时整段不综合（回到第 1 轮行为）。
    // ========================================================================
    wire              S_teach_apply;         // 窗末判定通过（1 拍脉冲）
    wire signed [8:0] S_teach_d1_lo, S_teach_d1_hi;
    wire signed [8:0] S_teach_d2_lo, S_teach_d2_hi;

    generate
    if (TEACH_EN != 0) begin : g_teach

        // ---- 采样区判据：按"字号"判一次即可 ----------------------------------
        // 中央区左右边界都落在 4 像素字边界上（320 = 4×80、959 = 4×239+3），所以按字号判
        // 一次就够（每个字号只取它最后那一个像素，见下面"采样密度"）。
        wire [10:0] S_t_xg0 = TEACH_X0 >> 2;
        wire [10:0] S_t_xg1 = TEACH_X1 >> 2;
        wire        S_t_zone = (S_y_pos >= TEACH_Y0) && (S_y_pos <= TEACH_Y1) &&
                               (S_x_grp >= S_t_xg0) && (S_x_grp <= S_t_xg1);

        // ---- 宽松前置门 ------------------------------------------------------
        function F_teach_pre;
            input signed [8:0] I_d1, I_d2;
            begin
                F_teach_pre = (I_d1 >= TEACH_PRE_D1_LO) && (I_d1 <= TEACH_PRE_D1_HI) &&
                              (I_d2 >= TEACH_PRE_D2_LO) && (I_d2 <= TEACH_PRE_D2_HI);
            end
        endfunction

        // 4 级延迟线（skew buffer）：一拍进一个采样像素，末级就是"4 个有效拍之前"那个。
        // 只在 I_raw_tvalid 拍推进、也只在 tvalid 拍合并 → 每个**被采样的**像素恰好并一次，
        // 不需要相位计数器 / FSM（它只是把"比较"和"并进包络"错开 4 拍，不改变吞进去的样本）。
        reg signed [8:0] S_k1_d1, S_k2_d1, S_k3_d1, S_k4_d1;
        reg signed [8:0] S_k1_d2, S_k2_d2, S_k3_d2, S_k4_d2;
        reg              S_k1_ok, S_k2_ok, S_k3_ok, S_k4_ok;
        reg              S_k1_mv, S_k2_mv, S_k3_mv, S_k4_mv;   // "这个像素所在块在动"跟数据一起延
        reg              S_blk_mv;                             // 本块"在动"（样本拍刷新，本块共用）

        reg               S_t_win;                       // 采样窗开着
        reg [7:0]         S_t_frm;                       // 窗内已经采到的帧数
        reg signed [8:0]  S_t_d1lo, S_t_d1hi;
        reg signed [8:0]  S_t_d2lo, S_t_d2hi;
        reg [11:0]        S_t_cnt;                       // 进包络的**样本**数（12 位饱和）
        reg [7:0]         S_t_flash;                     // 窗末起的"闪叠加"倒计时（帧）

        // ======================================================================
        // 采样密度（2026-09-29 压缩；上板验收之前做的）：**每 4 列取 1 列** —— 取字号里最后一个像素
        // （列 = 4·x_grp+3，即列 3、7、…、959）。
        //
        // 为什么：一拍 4 个像素的 min/max 树 ≈110 LUT6，是这一整块最大的一笔；改成"一拍只并
        // 一个像素"后，每拍只要 1 组比较/选择（≈20 LUT6 + 76 FF 的延迟线）。
        //
        // ⚠ **不是"语义不变"**（我们的抽样点是 4 像素/拍，所以一拍只并 1 个 = 每 4 列取 1），
        //   差两处，写清楚免得误读：
        //   ① 密度：每帧只统计 160 列 × 360 行 = 5.76 万样本（原来 23 万）。门限仍按"真实
        //      像素"解释 —— 比较用 TEACH_MIN_PIX>>2，所以 2000 还是"2000 个真实像素"的意思
        //      （内部计数是样本数，约 1/4）。包络只会差"相邻列那几个 LSB"。
        //   ② 窗边界最多差 4 个像素：开窗那一拍延迟线里还残留开窗前的 4 个像素（会被并进新
        //      包络，无害）；窗末那一拍还有 4 个像素没来得及并（判定少看这 4 个）。
        //      相对 60 帧 × 5.76 万样本，是 1e-7 量级。
        // ======================================================================
        // 喂进延迟线的那一个像素：在中央区 ∧ 过宽松前置门 才算"算数"（标志跟着数据一起延）
        wire S_t_in_ok = S_t_zone && F_teach_pre(S_d1_3, S_d2_3);

        // ---- 块级帧差门：只让"在动"的像素进包络（2026-09-30，方案 B）----------------
        // 为什么：上板实测"手完全拿开、只对着桌面"也能学出一大片红 —— 前置门里全是背景像素。
        //   示教时手在动、背景不动，所以再叠一道"这块相对上一帧变过"的门：静态背景一个块都不动
        //   → 一个样本都进不来 → 样本数不够 → 直接拒绝（根本学不到背景）。
        // 结构：中央区按 16×16 分块 = 40×23 = **920 块 → 1 块 ERAM**（1024×8）。每块每帧只采一个
        //   样本像素（就是本模块用的那个：列 4·x_grp+3、块内第一行），存进 ERAM；下一帧同位置比较，
        //   差 > TEACH_MOT_TH 就认为"这块在动"，本块其余像素共用这个结论。
        // 时序：地址用"**下一个**采样列所在的块"→ **样本拍的前一拍**读出的正好是上一帧的块样本
        //   （eram_spram 读延迟 1 拍）；写只在样本拍 → 同一地址不会同拍既读又写（它的硬性要求）。
        wire [10:0] S_col4   = {S_x_grp, 2'b00} + 11'd7;      // 采样列 + 4 = 4·x_grp + 7
        wire [6:0]  S_bc4    = S_col4[10:4] - 7'd20;          // 块列 0..39（区外会取值越界，只用不写）
        wire [5:0]  S_br     = S_y_pos[9:4] - 6'd11;          // 块行 0..22（区外回绕，无害）
        wire [10:0] S_bsum   = {S_br, 5'b0} + {S_br, 3'b0};   // 块行 × 40
        wire [10:0] S_baddr  = S_bsum + {4'b0, S_bc4};
        wire [7:0]  S_bq;                                      // ERAM 读出的"上一帧块样本"
        // 采样行 = 块内第一行（中央区首行 180 不是 16 的倍数，所以单独放行一次）
        wire S_smp_row = (S_y_pos[3:0] == 4'd0) || (S_y_pos == TEACH_Y0);
        // 样本拍：在中央区、采样行、块内第一个采样列（列 ≡ 3 mod 16）——每块每帧正好一次
        wire S_blk_smp = I_raw_tvalid && S_t_zone && S_smp_row && (S_x_grp[1:0] == 2'd0);
        wire [7:0] S_bd = (S_y3 >= S_bq) ? (S_y3 - S_bq) : (S_bq - S_y3);
        wire       S_blk_mv_now = (S_bd > TEACH_MOT_TH);
        // 样本拍用"刚算出来"的结论；本块其余像素用锁存（S_blk_mv）的那个结论
        wire       S_px_mv = S_blk_smp ? S_blk_mv_now : S_blk_mv;

        eram_spram #(.DATA_WIDTH(8), .ADDR_WIDTH(10)) u_teach_blk (
            .I_clk  (I_clk),
            .I_we   (S_blk_smp),                  // 只在样本拍写（地址当拍正好是"下一个采样列所在块"=本块）
            .I_addr (S_baddr[9:0]),               // 920 块 < 1024，够；区外的越界值只读不写
            .I_wdata(S_y3),
            .O_rdata(S_bq)
        );

        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n) begin
                S_t_win  <= 1'b0;     S_t_frm  <= 8'd0;
                S_t_d1lo <= 9'sd0;    S_t_d1hi <= 9'sd0;
                S_t_d2lo <= 9'sd0;    S_t_d2hi <= 9'sd0;
                S_t_cnt  <= 12'd0;
                S_t_flash <= 8'd0;
                S_k1_d1 <= 9'sd0;  S_k2_d1 <= 9'sd0;  S_k3_d1 <= 9'sd0;  S_k4_d1 <= 9'sd0;
                S_k1_d2 <= 9'sd0;  S_k2_d2 <= 9'sd0;  S_k3_d2 <= 9'sd0;  S_k4_d2 <= 9'sd0;
                S_k1_ok <= 1'b0;   S_k2_ok <= 1'b0;   S_k3_ok <= 1'b0;   S_k4_ok <= 1'b0;
                S_k1_mv <= 1'b0;   S_k2_mv <= 1'b0;   S_k3_mv <= 1'b0;   S_k4_mv <= 1'b0;
                S_blk_mv <= 1'b0;                      // 复位后先按"没动"处理（保守：不并）
            end
            // 帧边界收到请求 → 开（或重开）采样窗：清包络（min 置 +255 / max 置 −256）
            else if(I_raw_tuser && S_teach_req) begin
                S_t_win  <= 1'b1;     S_t_frm  <= 8'd0;
                S_t_d1lo <= 9'h0FF;   S_t_d1hi <= 9'h100;
                S_t_d2lo <= 9'h0FF;   S_t_d2hi <= 9'h100;
                S_t_cnt  <= 12'd0;
                S_t_flash <= 8'd0;                        // 新一轮采样期间不闪
            end
            else begin
                // (1) 延迟线：每个有效拍推进一级（与窗口无关 —— 窗末停在线上的那 4 个就不并了）
                if(I_raw_tvalid) begin
                    S_k1_d1 <= S_d1_3;     S_k1_d2 <= S_d2_3;     S_k1_ok <= S_t_in_ok;  S_k1_mv <= S_px_mv;
                    S_k2_d1 <= S_k1_d1;    S_k2_d2 <= S_k1_d2;    S_k2_ok <= S_k1_ok;    S_k2_mv <= S_k1_mv;
                    S_k3_d1 <= S_k2_d1;    S_k3_d2 <= S_k2_d2;    S_k3_ok <= S_k2_ok;    S_k3_mv <= S_k2_mv;
                    S_k4_d1 <= S_k3_d1;    S_k4_d2 <= S_k3_d2;    S_k4_ok <= S_k3_ok;    S_k4_mv <= S_k3_mv;
                    // 块级帧差：样本拍刷新本块结论（ERAM 的写在 u_teach_blk 那一拍完成）
                    if(S_blk_smp) S_blk_mv <= S_blk_mv_now;
                end
                // (2) 包络合并：窗内 + 末级样本算数 + **本块在动** → 一拍一次 min/max
                //     用 tvalid 一起闸住是为了**行间空隙不重复并同一个像素**（否则计数会虚高）
                if(S_t_win && I_raw_tvalid && S_k4_ok && S_k4_mv) begin
                    S_t_d1lo <= (S_k4_d1 < S_t_d1lo) ? S_k4_d1 : S_t_d1lo;
                    S_t_d1hi <= (S_k4_d1 > S_t_d1hi) ? S_k4_d1 : S_t_d1hi;
                    S_t_d2lo <= (S_k4_d2 < S_t_d2lo) ? S_k4_d2 : S_t_d2lo;
                    S_t_d2hi <= (S_k4_d2 > S_t_d2hi) ? S_k4_d2 : S_t_d2hi;
                    if(S_t_cnt != 12'hFFF) S_t_cnt <= S_t_cnt + 12'd1;
                end
                // (3) 帧计数：采够 TEACH_WIN_FRAMES 帧就关窗（窗末判定见下面的 S_t_last）
                if(I_raw_tuser && S_t_win) begin
                    if((S_t_frm + 8'd1) >= TEACH_WIN_FRAMES) S_t_win <= 1'b0;
                    else                                     S_t_frm <= S_t_frm + 8'd1;
                end
                // (4) 【第 4 轮】闪叠加：窗末那一拍点亮 TEACH_FLASH_FRAMES 帧，到点自己灭。
                // 条件与上面的关窗**同一个**（都用旧值判断），所以判定过不过都会闪 2 s。
                if(I_raw_tuser) begin
                    if(S_t_win && ((S_t_frm + 8'd1) >= TEACH_WIN_FRAMES))
                        S_t_flash <= TEACH_FLASH_FRAMES;
                    else if(S_t_flash != 8'd0)
                        S_t_flash <= S_t_flash - 8'd1;
                end
            end
        end

        // ---- 窗末判定 --------------------------------------------------------
        // 包络非空时 span = hi − lo ≥ 0；空包络（一个样本都没进）时这两个数没意义，
        // 但那时样本数门限必然不通过。
        wire [9:0] S_t_d1span = {S_t_d1hi[8], S_t_d1hi} - {S_t_d1lo[8], S_t_d1lo};
        wire [9:0] S_t_d2span = {S_t_d2hi[8], S_t_d2hi} - {S_t_d2lo[8], S_t_d2lo};
        // 外扩量 = (span>>3)+(span>>6) ≈ 14%；span ≤ 511 → 外扩量 ≤ 70，7 位够
        wire [6:0] S_t_exp1 = {1'b0, S_t_d1span[8:3]} + {4'b0, S_t_d1span[8:6]};
        wire [6:0] S_t_exp2 = {1'b0, S_t_d2span[8:3]} + {4'b0, S_t_d2span[8:6]};

        // 外扩（9 位有符号不会溢出：前置门已把包络限在 d1∈[−115,−2]、d2∈[2,80]，外扩量足够小）
        // + **安全带**（2026-09-30 上板实测"手拿开也学会背景"之后加的）：教出来的 4 个数钳在
        // [TEACH_CLP_*] 里 —— 比前置门宽一点，但不允许跑到离谱的地方。
        wire signed [8:0] S_x1_lo = S_t_d1lo - {2'b0, S_t_exp1};
        wire signed [8:0] S_x1_hi = S_t_d1hi + {2'b0, S_t_exp1};
        wire signed [8:0] S_x2_lo = S_t_d2lo - {2'b0, S_t_exp2};
        wire signed [8:0] S_x2_hi = S_t_d2hi + {2'b0, S_t_exp2};
        assign S_teach_d1_lo = (S_x1_lo < TEACH_CLP_D1_LO) ? TEACH_CLP_D1_LO : S_x1_lo;
        assign S_teach_d1_hi = (S_x1_hi > TEACH_CLP_D1_HI) ? TEACH_CLP_D1_HI : S_x1_hi;
        assign S_teach_d2_lo = (S_x2_lo < TEACH_CLP_D2_LO) ? TEACH_CLP_D2_LO : S_x2_lo;
        assign S_teach_d2_hi = (S_x2_hi > TEACH_CLP_D2_HI) ? TEACH_CLP_D2_HI : S_x2_hi;

        // 样本门限：计数口径是"每 4 列取 1 列"，所以拿 TEACH_MIN_PIX>>2 去比 —— TEACH_MIN_PIX
        // 仍按**真实像素数**解释（2000 → 500 个样本）。取 [13:2] 是 >>2 且不产生位宽截断告警
        // （要求 TEACH_MIN_PIX < 16384）。
        wire [11:0] S_t_min = TEACH_MIN_PIX[13:2];

        // 窗末那一拍（＝第 60 帧的帧首）：样本够 + d2 跨度够 才写。
        // 同一拍又来了新请求就先满足新请求（不写旧结果，直接重开窗）。
        wire S_t_last = S_t_win && ((S_t_frm + 8'd1) >= TEACH_WIN_FRAMES);
        // 自保（2026-09-30）：包络只要**贴着前置门的边**（= 背景把整个框填满了）→ 直接拒绝、不写窗口
        wire S_t_edge = (S_t_d1lo == TEACH_PRE_D1_LO) || (S_t_d1hi == TEACH_PRE_D1_HI) ||
                        (S_t_d2lo == TEACH_PRE_D2_LO) || (S_t_d2hi == TEACH_PRE_D2_HI);
        wire S_t_ok   = (S_t_cnt >= S_t_min) && (S_t_d2span >= TEACH_MIN_D2SPAN) && !S_t_edge;
        assign S_teach_apply = I_raw_tuser && S_t_last && S_t_ok && !S_teach_req;
        // 闪叠加指示灯：窗末起（含"新请求抢在窗末同一拍"的情况）高 ~2 s，给 isp_top 用
        assign O_teach_flash = (S_t_flash != 8'd0);

    end
    else begin : g_teach_off
        // TEACH_EN=0：窗口寄存器只剩复位值（= 交付默认），采样/判定逻辑一个门都不占
        // （上面那几拍事件检测仍然在，代价约 6 FF）
        assign S_teach_apply = 1'b0;
        assign O_teach_flash = 1'b0;
        assign S_teach_d1_lo = 9'sd0;   assign S_teach_d1_hi = 9'sd0;
        assign S_teach_d2_lo = 9'sd0;   assign S_teach_d2_hi = 9'sd0;
    end
    endgenerate
    // 判据实际用的 4 个边界（档 8/9 走常量，其余走运行时寄存器）
    wire signed [8:0] S_f_d1_lo = (S_cfg == 4'd8) ? D1_MIN : S_win_d1_lo;
    wire signed [8:0] S_f_d1_hi = (S_cfg == 4'd8) ? D1_MAX : S_win_d1_hi;
    wire signed [8:0] S_f_d2_lo = (S_cfg == 4'd8) ? D2_MIN :
                                 ((S_cfg == 4'd9) ? 9'sd5 : S_win_d2_lo);
    wire signed [8:0] S_f_d2_hi = (S_cfg == 4'd8) ? D2_MAX : S_win_d2_hi;

    // 判据 v1：d1/d2 矩形（Y 由档位决定：档 8 用旧 S_gray，其余用真 luma）。
    function F_skin_px;
        input signed [8:0] I_d1, I_d2;   // d1 = B−Y、d2 = R−Y
        begin
            F_skin_px = (I_d1 >= S_f_d1_lo) && (I_d1 <= S_f_d1_hi) &&
                        (I_d2 >= S_f_d2_lo) && (I_d2 <= S_f_d2_hi);
        end
    endfunction

    // 判据 v2（打磨②）：饱和度门 + 亮度窗 + 暖色差（与 Y 的绝对值无关）
    function F_skin2_px;
        input [7:0] I_r, I_g, I_b, I_y;
        reg [7:0] S_hi, S_lo, S_rg, S_rb;
        begin
            S_hi = (I_r >= I_g) ? ((I_r >= I_b) ? I_r : I_b) : ((I_g >= I_b) ? I_g : I_b);
            S_lo = (I_r <= I_g) ? ((I_r <= I_b) ? I_r : I_b) : ((I_g <= I_b) ? I_g : I_b);
            // 差值必须先判大小再减，否则 8 位减法会回绕成一个大正数
            S_rg = (I_r >= I_g) ? (I_r - I_g) : 8'd0;
            S_rb = (I_r >= I_b) ? (I_r - I_b) : 8'd0;
            F_skin2_px = ((S_hi - S_lo) >= SAT_MIN) && (I_y >= Y_MIN) && (I_y <= Y_MAX) &&
                         (S_rg >= RG_MIN) && (S_rb >= RB_MIN);
        end
    endfunction

    // 判据 v3（M2.2 修正，用户提议）：**按亮度归一化**的肤色判据 —— 用比例代替绝对值窗。
    //   d2/Y ∈ [2^-NORM_LO_SH, 2^-NORM_HI_SH]、|d1|/Y 同区间。边界由 Y 右移得到，不用乘除。
    //   注意 d2 必须为正（皮肤是 R > Y）：负 d2 零扩展后是个大正数，会被上界自然挡掉。
    function F_skin_norm_px;
        input signed [8:0] I_d1, I_d2;   // d1 = B−Y、d2 = R−Y
        input [7:0]        I_y;          // 真 luma
        reg [8:0] S_l, S_h, S_a1;
        begin
            // 下界 ≈ (Y>>4) − (Y>>6) ≈ Y/21.3（不用乘法）；再钳到 ≥1 防极暗退化
            S_l  = {5'b0, I_y[7 : NORM_LO_SH]} - {7'b0, I_y[7 : NORM_LO_SUB]};
            S_l  = (S_l <= 9'd1) ? 9'd1 : S_l;
            S_h  = {1'b0, I_y[7 : NORM_HI_SH]};                   // Y >> NORM_HI_SH（默认 Y/4）
            S_a1 = I_d1[8] ? (~I_d1 + 9'd1) : I_d1;               // |d1|
            // ★ 2026-10-11 补的关键条件：d1 = B−Y **必须为负**（皮肤比 Y 更暖，B 小于 Y）。
            //   第一版漏了它、只比 |d1| 的幅度 → 偏冷/中性的表面也满足比例窗 → **整屏变红**。
            //   注意 d2 的正负不用单独判：d2 < 0 时零扩展是个大正数，必然超过上界 S_h。
            // 上界再加 M1 的老硬帽（min(Y/4, 硬帽)）：比例界挡"亮暖桌面"，硬帽挡"特别亮的杂光"。
            F_skin_norm_px = I_d1[8] &&                       // d1 < 0（B < Y）
                             (S_a1 >= S_l) && (S_a1 <= S_h) &&
                             (S_a1 <= NORM_D1_HARD) &&
                             ({1'b0, I_d2} >= S_l) && ({1'b0, I_d2} <= S_h) &&
                             ({1'b0, I_d2} <= NORM_D2_HARD);
        end
    endfunction

    // 掩码 bit 序与 S_edge_mask 一致：bit0 = 字内最左像素 [95:72]。
    wire [3:0] S_skin_mask = {F_skin_px(S_d1_3, S_d2_3),
                              F_skin_px(S_d1_2, S_d2_2),
                              F_skin_px(S_d1_1, S_d2_1),
                              F_skin_px(S_d1_0, S_d2_0)};

    wire [3:0] S_skin_norm_mask = {F_skin_norm_px(S_d1_3, S_d2_3, S_gray3),
                                   F_skin_norm_px(S_d1_2, S_d2_2, S_gray2),
                                   F_skin_norm_px(S_d1_1, S_d2_1, S_gray1),
                                   F_skin_norm_px(S_d1_0, S_d2_0, S_gray0)};

    wire [3:0] S_skin2_mask = {F_skin2_px(S_raw_pix3[23:16], S_raw_pix3[15:8], S_raw_pix3[7:0], S_gray3),
                               F_skin2_px(S_raw_pix2[23:16], S_raw_pix2[15:8], S_raw_pix2[7:0], S_gray2),
                               F_skin2_px(S_raw_pix1[23:16], S_raw_pix1[15:8], S_raw_pix1[7:0], S_gray1),
                               F_skin2_px(S_raw_pix0[23:16], S_raw_pix0[15:8], S_raw_pix0[7:0], S_gray0)};

    // ========================================================================
    // 【2026-10-16 ②】亮度上限 + 饱和度下限（8 位比较，0 DSP）
    //   sat = max(R,G,B) − min(R,G,B)：金属高光偏白（sat 小），皮肤/木头偏色（sat 大）。
    //   只作用在**归一化肤色掩码**上，由运行时**档 14** 打开（档 13 = 关的观测档）。
    // 成本：4 像素 ×（3 路 max/min 树 + 2 个比较）≈ 90 LUT6。
    // ========================================================================
    function [7:0] F_max3;
        input [7:0] I_a, I_b, I_c;
        begin
            F_max3 = (I_a >= I_b) ? ((I_a >= I_c) ? I_a : I_c)
                                  : ((I_b >= I_c) ? I_b : I_c);
        end
    endfunction
    function [7:0] F_min3;
        input [7:0] I_a, I_b, I_c;
        begin
            F_min3 = (I_a <= I_b) ? ((I_a <= I_c) ? I_a : I_c)
                                  : ((I_b <= I_c) ? I_b : I_c);
        end
    endfunction
    wire [7:0] S_sat0 = F_max3(S_raw_pix0[23:16], S_raw_pix0[15:8], S_raw_pix0[7:0]) -
                        F_min3(S_raw_pix0[23:16], S_raw_pix0[15:8], S_raw_pix0[7:0]);
    wire [7:0] S_sat1 = F_max3(S_raw_pix1[23:16], S_raw_pix1[15:8], S_raw_pix1[7:0]) -
                        F_min3(S_raw_pix1[23:16], S_raw_pix1[15:8], S_raw_pix1[7:0]);
    wire [7:0] S_sat2 = F_max3(S_raw_pix2[23:16], S_raw_pix2[15:8], S_raw_pix2[7:0]) -
                        F_min3(S_raw_pix2[23:16], S_raw_pix2[15:8], S_raw_pix2[7:0]);
    wire [7:0] S_sat3 = F_max3(S_raw_pix3[23:16], S_raw_pix3[15:8], S_raw_pix3[7:0]) -
                        F_min3(S_raw_pix3[23:16], S_raw_pix3[15:8], S_raw_pix3[7:0]);
    // 饱和门 = **比例 + 绝对下限**：`sat ≥ (Y >> SKIN_SAT_SH)` 且 `sat ≥ SKIN_SAT_MIN`
    // （两条 AND 等价于 `sat ≥ max(Y/8, 8)`，省掉求 max 的硬件）。Y 用与肤色判据
    // 同一份灰度（S_gray）。
    wire [3:0] S_cappx = { (S_gray3 >= SKIN_Y_MIN) && (S_gray3 <= SKIN_Y_CAP) &&
                           (S_sat3 >= {5'b0, S_gray3[7:SKIN_SAT_SH]}) && (S_sat3 >= SKIN_SAT_MIN),
                           (S_gray2 >= SKIN_Y_MIN) && (S_gray2 <= SKIN_Y_CAP) &&
                           (S_sat2 >= {5'b0, S_gray2[7:SKIN_SAT_SH]}) && (S_sat2 >= SKIN_SAT_MIN),
                           (S_gray1 >= SKIN_Y_MIN) && (S_gray1 <= SKIN_Y_CAP) &&
                           (S_sat1 >= {5'b0, S_gray1[7:SKIN_SAT_SH]}) && (S_sat1 >= SKIN_SAT_MIN),
                           (S_gray0 >= SKIN_Y_MIN) && (S_gray0 <= SKIN_Y_CAP) &&
                           (S_sat0 >= {5'b0, S_gray0[7:SKIN_SAT_SH]}) && (S_sat0 >= SKIN_SAT_MIN) };
    wire [3:0] S_skin_cap_mask = S_skin_norm_mask & S_cappx;
    // ========================================================================
    // 【2026-10-17 v2 架构，档 15】① "颜色从门降级为分数"
    //   旧：肤色硬窗 ∧ 运动硬门 —— 两个门**不是独立证据**（暖铁皮既"暖"又被灯照得在闪），
    //       一起失效。
    //   新：**运动给候选区，颜色只在候选区内当分数** —— 颜色不再需要和全世界竞争，
    //       只要在"手大概在哪"的范围里分辨手指与背景。所以这里把窄比例窗**放开**，
    //       只留"暖色方向 + Y/饱和合理性"（②的门），窗口判据只给非 v2 档用。
    //   "暖"= B<Y 且 R>Y（d1<0、d2>0）；② 的 Y 上下限与饱和下限仍然保留（挡近黑与发白）。
    // ========================================================================
    function F_skin_warm_px;
        input signed [8:0] I_d1, I_d2;
        input [7:0]        I_y, I_sat;
        begin
            F_skin_warm_px = I_d1[8] && (I_d2 > 9'sd0) &&
                             (I_y >= SKIN_Y_MIN) && (I_y <= SKIN_Y_CAP) &&
                             (I_sat >= SKIN_SAT_MIN) &&
                             (I_sat >= (I_y >> SKIN_SAT_SH));
        end
    endfunction
    wire [3:0] S_skin_warm_mask = { F_skin_warm_px(S_d1_3, S_d2_3, S_gray3, S_sat3),
                                    F_skin_warm_px(S_d1_2, S_d2_2, S_gray2, S_sat2),
                                    F_skin_warm_px(S_d1_1, S_d2_1, S_gray1, S_sat1),
                                    F_skin_warm_px(S_d1_0, S_d2_0, S_gray0, S_sat0) };
    // 档 15 = **v2 架构**；档 14 = 旧"② 硬门 + 运动门"（A/B 对照）；档 13 = 观测档
    wire       S_v2      = (S_cfg == 4'd15);
    wire       S_cap_on  = (S_cfg == 4'd14);
        // 【2026-10-18】档 1（交付视图）也接入块级运动门：肤色 ∩ 块运动。
        // 档 3 仍是"运动门关"的对照组，档 2/14/15 语义不变。
        wire       S_mot_on  = (S_cfg == 4'd1) || (S_cfg == 4'd2) ||
                               (S_cfg == 4'd14) || (S_cfg == 4'd15);
    wire       S_occ_act = 1'b0;               // ① 块级占比门已退休（v2 用运动候选区代替）

    // 最终使用的肤色掩码（编译期常量选择，没选中的判据会被综合裁掉）
    wire [3:0] S_skin_use = (SKIN_RULE2 != 0) ? S_skin2_mask :
                            (S_v2      ? S_skin_warm_mask :
                             (S_cap_on ? S_skin_cap_mask :
                              ((SKIN_NORM != 0)  ? S_skin_norm_mask : S_skin_mask)));

    // ========================================================================
    // 【2026-10-16 ⑤：观测档】肤色掩码内 Y / 饱和度的**帧内最小、最大值**
    //   为什么要它：用户明说了"我们盲调的现状，别再靠猜"。M1 的每个阈值都是这么读回来的。
    //   现场定标配方（档 13 打开，画面里只对一个东西）：
    //     ① 只对着**铁皮反光** → 读 P/Q = 反光的 Y 区间 / sat 区间
    //     ② 只对着**手**       → 读 P/Q = 手的 Y 区间 / sat 区间
    //     ③ `SKIN_Y_MIN` ≤ 手 minY；`SKIN_Y_CAP` 取在手 maxY 与反光 minY 之间；
    //        比例饱和 `SKIN_SAT_SH` 取在"手 minSat/手 maxY"与"反光 maxSat/反光 minY"之间
    //        （先试默认 Y/8；手被杀了就改成 4 = Y/16）
    //     ④ 切档 14（② 生效）看红色是否只剩手
    //   P(16) = { 掩码内 minY, 掩码内 maxY }
    //   Q(14) = { 掩码内 minSat[6:0], 掩码内 maxSat[6:0] }（sat 饱和到 127）
    //   R(12) = M1 语义（包围盒 y）不变 —— 顺手盯掩码健康
    //   采样密度：每拍只并**像素 3**（= 每 4 列取 1 列，与示教那套同一招）→ 极值统计
    //   仍然够用（反光/手的面积远大于 4 像素），而成本降到 1/4（≈60 LUT6）。
    //   只在档 13/14 借 P/Q；其余档位 P/Q/R 一字不动。
    // ========================================================================
    wire S_obs_on = (S_cfg == 4'd13) || (S_cfg == 4'd14) || (S_cfg == 4'd15);
    reg [7:0] a_obs_ymin, a_obs_ymax, a_obs_smin, a_obs_smax;
    reg [7:0] h_obs_ymin, h_obs_ymax, h_obs_smin, h_obs_smax;
    // 饱和先钳到 127（Q 只有 7 位给它）：皮肤/反光的 sat 都远小于 127，钳位不影响判读
    wire [7:0] S_sat3_c = (S_sat3 > 8'd127) ? 8'd127 : S_sat3;
    wire [7:0] S_obs_ymin_in = S_skin_use[3] ? S_gray3 : 8'hFF;
    wire [7:0] S_obs_ymax_in = S_skin_use[3] ? S_gray3 : 8'h00;
    wire [7:0] S_obs_smin_in = S_skin_use[3] ? S_sat3_c : 8'h7F;
    wire [7:0] S_obs_smax_in = S_skin_use[3] ? S_sat3_c : 8'h00;
    always @(posedge I_clk or negedge I_rst_n) begin
        if(!I_rst_n) begin
            a_obs_ymin <= 8'hFF;  a_obs_ymax <= 8'h00;
            a_obs_smin <= 8'h7F;  a_obs_smax <= 8'h00;
            h_obs_ymin <= 8'hFF;  h_obs_ymax <= 8'h00;
            h_obs_smin <= 8'h7F;  h_obs_smax <= 8'h00;
        end
        else if(I_raw_tuser) begin
            // 帧首：把上一帧的极值锁存出去，累加器重置成"空集"的初值
            h_obs_ymin <= a_obs_ymin;  h_obs_ymax <= a_obs_ymax;
            h_obs_smin <= a_obs_smin;  h_obs_smax <= a_obs_smax;
            a_obs_ymin <= 8'hFF;       a_obs_ymax <= 8'h00;
            a_obs_smin <= 8'h7F;       a_obs_smax <= 8'h00;
        end
        else if(I_raw_tvalid) begin
            if(S_obs_ymin_in < a_obs_ymin) a_obs_ymin <= S_obs_ymin_in;
            if(S_obs_ymax_in > a_obs_ymax) a_obs_ymax <= S_obs_ymax_in;
            if(S_obs_smin_in < a_obs_smin) a_obs_smin <= S_obs_smin_in;
            if(S_obs_smax_in > a_obs_smax) a_obs_smax <= S_obs_smax_in;
        end
    end

    // ========================================================================
    // M1 Step 2：背景帧（80x45 灰度）+ 运动掩码 → 融合掩码 = 肤色 ∩ 运动
    //
    // 为什么要背景差分而不是帧间差分：帧间差分只能发现"这一帧和上一帧不一样"，
    // 手停住就不动了；背景差分是"和背景不一样"，静止的手照样是前景。前提是背景
    // 更新必须带 quiet 门控（见下），否则静止的手会慢慢被吸进背景。
    //
    // 几何：块 = 16x16 像素，80x45 = 3600 块，每块 1 字节灰度参考值。
    //   块列 = x[10:4] = 行内字号 >> 2（一拍 4 像素不跨 16 像素边界），
    //   块行 = y[9:4]，地址 = 块行*80 + 块列（80 = 64+16，纯移位加法）；
    //   → 每块每行只读一次背景，同一块内 4 拍的像素共用这个值。
    //
    // 采样（背景更新的依据，**2026-10-16 从新实现**）：**采样行轮转** —— 本帧用
    //   frame_cnt[3:0] 选块内哪一行，一行 **16 像素**（= 块内 4 拍累加，phase 3 取和 >>4），
    //   16 帧覆盖整块 16 行 → 采样密度 6.25% → **100%**（老版只采 8 像素 = 3%，
    //   灯斑/反光取不到亮处，那部分就"永久在动"）。
    //
    // ERAM 读写时序（eram_spram = 单口 + 1 拍读延迟，同一拍不能既读又写）：
    //   phase 0/1：地址 = 本块，读（phase==0 直接用预取回来的数据，phase 1~3 用寄存副本）
    //   phase 2  ：地址 = **上一块**，we = 上一块的更新决策（这一拍是"只写"）
    //   phase 3  ：地址 = **下一块**（地址预取），读 → 数据正好在下一块 phase==0 有效
    //   行尾（块列 79）的下一块是本块行第 0 列（下一行的同一个块行），地址要回卷；
    //   写回地址 = 扫描顺序的上一个块（S_addr_cur − 1，跨行/跨帧都一样）。
    //
    // 背景更新（**quiet 门控 + 带系数的蠕变**，2026-10-16 从新实现，见下面的 Step A/C）：
    //   * 允许蠕变：块内活动像素数 ≤ BG_QUIET_PX（整块安静），或"16 像素齐步同向变且
    //     幅度 ≤ BG_UNIF_MAX"（均匀光照漂移）→ 手在块里就冻结，静止的手不会被吸进背景；
    //   * 步长 = clamp(|行均值 − 背景| >>> BG_K, 1..BG_STEP_MAX)，每块每 16 帧一次机会
    //     （采样行轮转天然把写入摊开）→ 时间常数 ≈ 2^BG_K × 16 帧 ≈ 2 s；
    //   * 复位后前 BOOT_FRAMES 帧例外：每块无条件装载行均值（自举）；切到档 2 也重建一次。
    //
    // 延迟：0 拍（背景值在每块第一拍就已经拿到，与像素同拍比较）。跨域：不跨。
    //       SDC：不需要额外约束（ERAM 与像素流同一时钟域）。
    // 资源：2 块 ERAM + ≈60 FF + ≈150~250 LUT6，0 DSP。
    // ========================================================================
    wire [3:0] S_motion_mask;
    // 【2026-10-18】该块均值差超过 3×阈值（手覆盖比例高）→ 整块填满，灭手掌内部空洞
    wire       S_mot_fill;

    // 当前像素所在块的背景灰度（g_motion 里赋值；调试图与 DIAG_CHROMA 统计共用）
    wire [7:0] S_bg_cur;
    // 背景帧是否已建好（自举/重建窗口内为 0）：没建好时运动门不生效（退回只认肤色）。
    // g_motion 里由 S_bg_ready 驱动，g_nomotion（MASK_SRC≠2）恒 1。
    wire       S_bg_rdy;
    // 【v2 ③】上一帧是否判为"全局光照事件"（在动的块占比超阈值）：整帧冻结背景 + 压掉掩码。
    wire       S_glb_evt;
    // 光照事件已持续 ≥30 帧（≈0.5 s）⇒ 不是"灯闪一下"，而是光照基线变了 → 强制重建背景。
    wire       S_evt_long;
    // 运动门归因（视图 4 用）：每像素 2 bit，见 g_motion 里的 F_mot_lv。
    wire [7:0] S_mot_lv;

    generate
    if (MASK_SRC == 2 && (SKIN_ONLY == 0)) begin : g_motion

        // 行内字号 S_x_grp / 行号 S_y_pos 现在在模块顶部统一维护（ROI/准星也要用）
        wire [1:0] S_phase = S_x_grp[1:0];          // 块内第几拍（0..3）
        // 【2026-10-18】块列 = x_grp[8:2]（0..79）。原来写的是 [6:2]（只有 5 位、
        // 0..31），右 2/3 的块全部复用左边 32 个地址，背景/块均值一直是混的。
        wire [6:0] S_blk_x = S_x_grp[8:2];          // 行内块列 0..79
        wire [5:0] S_band  = S_y_pos[9:4];          // 块行 0..44
        // ---- 帧计数：给"采样行轮转"用（低 4 位 = 本帧的块内采样行号）----------------
        reg [7:0] S_frame_cnt;
        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n)         S_frame_cnt <= 8'd0;
            else if(I_raw_tuser) S_frame_cnt <= S_frame_cnt + 8'd1;
        end
        // **Step A**：本帧只更新"块内第 frame_cnt[3:0] 行"的那些块 → 16 帧把整块 16 行全采
        //   一遍（采样密度 6.25% → **100%**），而写入天然被摊到 16 帧里，所以旧的
        //   "按块地址低位挑帧"那套逻辑（还有那个"低 6 位 ≥16 的块永远轮不到"的 bug）整段删掉。
        wire S_sample_row = (S_y_pos[3:0] == S_frame_cnt[3:0]);

        wire [11:0] S_row_base  = {S_band, 6'b0} + {S_band, 4'b0};   // 块行*80
        wire [11:0] S_addr_cur  = S_row_base + {{5{1'b0}}, S_blk_x};
        // 预取地址 = **扫描顺序的下一个块**（不是"本行首块"）。原来的写法在每块行最后一个块上
        // 回卷到本行首块，于是"每块行的第一个块（图像最左 16 像素）"用的是上一行首块的背景
        // → 最左边一条 16 像素宽的永久竖线（很可能就是用户 2026-09-25 看到的"两条竖线"里的一条）。
        wire [11:0] S_addr_next = (S_addr_cur == 12'd3599) ? 12'd0 : (S_addr_cur + 12'd1);
        // 写回地址 = **扫描顺序的上一个块**：决策在上一块的 phase 3 产生、写发生在这一块的
        // phase 2（见下面的 S_pend_*）。跨行/跨帧回卷都靠这一个减法自动对上。
        wire [11:0] S_addr_prev = (S_addr_cur == 12'd0) ? 12'd3599 : (S_addr_cur - 12'd1);

        // ---- 背景帧存储：2 块 ERAM（各 2048x8，够放 3600 个块）------------------
        // 单口 + 1 拍读延迟。4 拍里的两个"访问槽"（2026-10-16 改）：
        //   phase 2 → **写回上一块**（地址 S_addr_prev、数据 S_pend_*）
        //   phase 3 → **预取下一块**（地址 S_addr_next）→ 本块数据在下一块 phase==0 有效
        // 为什么要改：新判决（Step A/B）要等**整行 16 像素**累加完（phase 3）才能定背景值，
        // 而 phase 3 是预取读槽、phase 2 是写槽 —— 于是把"写"错开到下一块的 phase 2，
        // 读/写永远各占各的槽，既不同拍撞车也不需要场消隐期的额外地址生成器。
        // 地址 bit11 选片子；读出数据的片选要用**上一拍**的地址位，所以打一拍。
        wire [11:0] S_bg_addr;
        wire        S_bg_we;
        wire [7:0]  S_bg_wdata;
        reg  [11:0] S_bg_addr_d1;
        wire [7:0]  S_bg_q0, S_bg_q1;
        wire [7:0]  S_bg_rdata = S_bg_addr_d1[11] ? S_bg_q1 : S_bg_q0;

        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n) S_bg_addr_d1 <= 12'd0;
            else         S_bg_addr_d1 <= S_bg_addr;
        end

        eram_spram #(.DATA_WIDTH(8), .ADDR_WIDTH(11)) u_bg_mem0 (
            .I_clk  (I_clk),
            .I_we   (S_bg_we & ~S_bg_addr[11]),
            .I_addr (S_bg_addr[10:0]),
            .I_wdata(S_bg_wdata),
            .O_rdata(S_bg_q0)
        );

        eram_spram #(.DATA_WIDTH(8), .ADDR_WIDTH(11)) u_bg_mem1 (
            .I_clk  (I_clk),
            .I_we   (S_bg_we &  S_bg_addr[11]),
            .I_addr (S_bg_addr[10:0]),
            .I_wdata(S_bg_wdata),
            .O_rdata(S_bg_q1)
        );

        // ---- 背景自举 / 重建窗口 -------------------------------------------------
        // 窗口内每块**无条件**装载样本值（否则背景全是未初始化内容，运动掩码恒 1、
        // 融合退化成纯肤色）。窗口取 BOOT_FRAMES（≈0.5 s）：故意留出 AWB 收敛时间
        // （AWB 是自适应的，开机头几帧颜色还没稳）。**开机时画面里别放手**。
        wire S_boot = (S_frame_cnt < BOOT_FRAMES);
        // ---- 手动重建背景（两个入口）---------------------------------------------
        //   ① 提交字 bit[19:16]（teach_cnt）一变（长按 KEY4 / 串口 `W 03 0001`）→ 重建；
        //   ② **切到档 2（运动门开）那一拍** → 重建（现场"手拿开 → W 08 0002"即重新采样）。
        // 两者都等效于重开机那 32 帧，是"背景错了"时最靠得住的兜底。
        reg [5:0] S_reboot;
        reg       S_rebase_req;      // 档 2 的手动重建请求（帧边界消费）
        reg [3:0] S_teach_seen;
        reg [3:0] S_cfg2_seen;
        wire      S_teach_evt = (S_mode_word[19:16] != S_teach_seen);
        wire      S_cfg2_now  = (S_cfg == 4'd2);
        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n) S_cfg2_seen <= 4'd0;
            else         S_cfg2_seen <= {3'b0, S_cfg2_now};
        end
        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n)                                 S_rebase_req <= 1'b0;
            else if(S_cfg2_now && (S_cfg2_seen == 4'd0)) S_rebase_req <= 1'b1;
            else if(I_raw_tuser)                         S_rebase_req <= 1'b0;
        end
        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n) begin
                S_reboot     <= 6'd0;
                S_teach_seen <= 4'd0;
            end
            else if(I_raw_tuser) begin
                // 【2026-10-18】全屏 80% 以上同时判成在动 → 只可能是背景模型坏了
                // （手不可能盖住 80%），强制重建，避免错误背景把更新门锁死。
                if(((REBASE_ON_TEACH != 0) && S_teach_evt) || S_rebase_req ||
                   S_evt_long || S_badbg_evt) begin
                    S_reboot     <= BOOT_FRAMES;
                    S_teach_seen <= S_mode_word[19:16];
                end
                else if(S_reboot != 6'd0) begin
                    S_reboot <= S_reboot - 6'd1;
                end
            end
        end
        wire S_boot_eff = S_boot || (S_reboot != 6'd0);

        // 自举完成标志：自举期内（含"重建背景"窗口）运动门**不生效**（退回只认肤色），
        // 免得拿一堆未初始化的 ERAM 内容当参考值。
        reg S_bg_ready;
        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n)         S_bg_ready <= 1'b0;
            else if(I_raw_tuser) S_bg_ready <= ~S_boot_eff;
        end
        assign S_bg_rdy = S_bg_ready;

        // ---- Step A：整行 16 像素均值（块参考值的采样）----------------------------
        // 一拍 4 像素 → 一行 16 像素正好是块内 4 拍：phase 0 装入、1/2 累加，
        // phase 3 得到整行和（≤ 16×255 = 4080 < 4096，12 位够）→ >>4 得行均值。
        // 为什么是"整行"：老版只采 8 个像素（3%），灯斑/反光在块内本来就不均匀，块背景取不到
        //   亮处 → 亮的那部分**永久**和"块背景"差十几二十，一直判成"在动"。一行 16 像素 +
        //   16 帧轮转 = 整块 256 像素全采到（100%）。
        // 成本：12 位累加器 + 一个加法器 ≈ 20 LUT / 12 FF / 0 ERAM / 0 DSP。
        wire [9:0] S_sum4 = {2'b0, S_gray0} + {2'b0, S_gray1} +
                            {2'b0, S_gray2} + {2'b0, S_gray3};      // 0..1020
        reg [11:0] S_row_acc;
        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n)          S_row_acc <= 12'd0;
            else if(I_raw_tvalid) S_row_acc <= (S_phase == 2'd0) ? {2'b0, S_sum4}
                                                                 : (S_row_acc + {2'b0, S_sum4});
        end
        // phase==3 当拍：S_row_acc 里是前 3 拍的和，加上本拍 = 本行 16 像素和
        wire [11:0] S_row_sum  = S_row_acc + {2'b0, S_sum4};
        wire [7:0]  S_row_mean = S_row_sum[11:4];       // 行均值

        // ---- 背景读数据：phase==0 用直通（预取刚回来），其余用寄存副本 ----------
        reg [7:0] S_bg_reg;
        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n) S_bg_reg <= 8'd0;
            // phase==3 那拍数据来自"phase==2 的写访问"，对单口 RAM 没有意义，不能收
            else if(I_raw_tvalid && (S_phase != 2'd3)) S_bg_reg <= S_bg_rdata;
        end
        wire [7:0] S_bg_use = (S_phase == 2'd0) ? S_bg_rdata : S_bg_reg;
        assign S_bg_cur = S_bg_use;     // 调试图出口

        // ---- 【2026-10-18】块级运动门：16×16 块均值 vs 背景块均值 -----------------
        // 逐像素 vs 块均值等于纹理检测（木纹/铁皮静止也永远差 20%+）。这里改为块均值
        // 时间差分：一个 16×16 块只有一个"在动/不动"判决，手形仍由像素级肤色决定。
        // 块均值 = 16 行 × 16 像素；每行 phase 3 累加本行和 S_row_sum（12 位）。
        // 80 个块各存一个 16 位行和。横扫描下**不能**用一个全局寄存器：
        // 一行会依次经过 80 个块，每个块的 phase 3 都会把本行和加进同一个寄存器。
        // phase 2 发地址、phase 3 读回 + 加本行 + 写回；行 0 直接覆盖（天然清零）。
        wire [6:0]  S_blk_acc_addr = S_blk_x[6:0];
        wire [15:0] S_blk_acc_q;
        wire        S_blk_acc_we = I_raw_tvalid && (S_phase == 2'd3);
        wire [16:0] S_blk_sum = ((S_y_pos[3:0] == 4'd0) ? 17'd0 : {1'b0, S_blk_acc_q}) +
                                {5'b0, S_row_sum};
        wire [7:0]  S_blk_mean = S_blk_sum[15:8];

        eram_spram #(.DATA_WIDTH(16), .ADDR_WIDTH(7)) u_blk_acc (
            .I_clk  (I_clk),
            .I_we   (S_blk_acc_we),
            .I_addr (S_blk_acc_addr),
            .I_wdata(S_blk_sum[15:0]),
            .O_rdata(S_blk_acc_q)
        );

        wire signed [8:0] S_blk_d   = {1'b0, S_blk_mean} - {1'b0, S_bg_use};
        wire [8:0]        S_blk_abs = S_blk_d[8] ? (~S_blk_d + 9'd1) : S_blk_d;
        wire S_mot_blk_new = S_bg_rdy && (S_blk_abs > BLK_MOTION_TH);
        wire S_mot_blk_we  = I_raw_tvalid && (S_phase == 2'd3) &&
                             (S_y_pos[3:0] == 4'd15);

        // 1-bit 块图（8 位宽只用 bit0）。读写槽与背景 RAM 完全一致：
        //   phase 2 写上一块、phase 3 预取下一块、块首用直通读出值。
        // 因此运动判决是"上一帧的块状态"，允许 1 帧延迟。
        wire [11:0] S_mot_addr;
        wire [7:0]  S_mot_q;
        reg  [1:0]  S_mot_reg;
        reg         S_mot_pend_we;
        reg  [1:0]  S_mot_pend_data;
        wire        S_mot_we = (S_phase == 2'd2) && S_mot_pend_we;
        assign S_mot_addr = (S_phase == 2'd3) ? S_addr_next :
                            (S_phase == 2'd2) ? S_addr_prev : S_addr_cur;
        // 【2026-10-18】两帧确认用 **2 位饱和计数**，不能直接把"稳定标志"写回：
        // 那样上一帧稳定=0 会把计数永久锁死。raw new=1 时 +1、new=0 清零，
        // 计数 ≥2 才算稳定在动；单帧纹理闪烁/噪点最多到 1，不会显示。
        wire [1:0] S_mot_cnt = (S_phase == 2'd0) ? S_mot_q[1:0] : S_mot_reg;
        // 【2026-10-18】把"强块填充"编进 2 位计数的第 3 个状态，避免独立位被 TD 当死逻辑裁掉：
        //   0 = 静止
        //   1 = 在动 1 帧（未确认）
        //   2 = 连续 2 帧在动（弱块，肤色收边）
        //   3 = 块均值差 ≥16（强块，整块填满）
        // new=0 清零；new=1 且强块直接到 3；弱块 1→2 饱和。
        wire [1:0] S_mot_cnt_new = !S_mot_blk_new ? 2'd0 :
                                   (|S_blk_abs[8:4]) ? 2'd3 :
                                   ((S_mot_cnt >= 2'd2) ? 2'd2 : (S_mot_cnt + 2'd1));
        wire S_mot_px = (S_mot_cnt >= 2'd2);
        assign S_mot_fill = (S_mot_cnt == 2'd3);
        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n) begin
                S_mot_reg       <= 2'd0;
                S_mot_pend_we   <= 1'b0;
                S_mot_pend_data <= 2'd0;
            end
            else if(I_raw_tvalid) begin
                if(S_phase != 2'd3)
                    S_mot_reg <= S_mot_q[1:0];
                if(S_phase == 2'd3) begin
                    S_mot_pend_we   <= S_mot_blk_we;
                    S_mot_pend_data <= S_mot_cnt_new;
                end
                else if(S_phase == 2'd2) begin
                    S_mot_pend_we <= 1'b0;
                end
            end
        end
        eram_spram #(.DATA_WIDTH(8), .ADDR_WIDTH(12)) u_mot_map (
            .I_clk  (I_clk),
            .I_we   (S_mot_we),
            .I_addr (S_mot_addr),
            .I_wdata({6'b0, S_mot_pend_data}),
            .O_rdata(S_mot_q)
        );
        // ---- 打磨③：帧粗均值 → 全局漂移检测（GLB_COMP=1 时生效）--------------
        // Σgray 用 28 位：921600 × 253 = 2.33e8 < 2^28 ✓。粗均值取 Σ>>20（≈真实均值
        // ×0.879，做相对比较够用，省掉除法器）。
        // 资源：≈28 FF + ≈80 LUT，0 ERAM / 0 DSP；GLB_COMP=0 时整段被综合裁掉。
        wire [9:0] S_beat_sum = {2'b0, S_gray0} + {2'b0, S_gray1} +
                                {2'b0, S_gray2} + {2'b0, S_gray3};
        reg  [27:0] a_gsum;
        reg  [7:0]  S_mean_ref;
        reg  signed [8:0] S_glb_delta;
        reg         S_glb_upd;
        reg         S_glb_shift;     // 整帧有效的全局平移标志（块末消费）

        // 刚结束这一帧的粗均值与基准之差（9 位有符号：−255..255）
        wire signed [8:0] S_mean_last = {1'b0, a_gsum[27:20]} - {1'b0, S_mean_ref};
        wire S_glb_need = (GLB_COMP != 0) &&
                          ((S_mean_last > GLOBAL_TH) || (S_mean_last < -GLOBAL_TH));

        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n) begin
                a_gsum      <= 28'd0;
                S_mean_ref  <= 8'd0;
                S_glb_delta <= 9'sd0;
                S_glb_upd   <= 1'b0;
                S_glb_shift <= 1'b0;
            end
            else if(I_raw_tuser) begin
                S_glb_delta <= S_mean_last;      // 下一帧按这个差值整体平移
                S_glb_upd   <= S_glb_need;
                S_glb_shift <= S_glb_need;
                if(S_glb_need) S_mean_ref <= a_gsum[27:20];
                a_gsum      <= 28'd0;
            end
            else if(I_raw_tvalid) begin
                a_gsum <= a_gsum + {18'b0, S_beat_sum};
            end
        end

        // 整块平移：bg + delta，钳到 0..255（用 10 位补码位型相加，避开混合符号的坑）
        function [7:0] F_shift8;
            input [7:0] I_bg;
            input signed [8:0] I_d;
            reg [9:0] S_t;
            begin
                S_t = {2'b0, I_bg} + {I_d[8], I_d};
                F_shift8 = (S_t[9:8] == 2'b00)  ? S_t[7:0] :      // 0..255 正常
                           (S_t[9]    ? 8'd0 : 8'd255);           // 负数→0，>255→255
            end
        endfunction

        // ======================================================================
        // Step B：运动门 = **块级时间差分**（16×16 块均值 vs 背景块均值）
        //   旧版逐像素 vs 块均值在数学上是纹理检测：木纹/铁皮的单像素天然偏离块均值
        //   20%+，静止也永远过门。现在每个块只有一个判决，整块同动/同静；手形仍由
        //   像素级肤色决定。判决来自上一帧的 1-bit 块图 u_mot_map（1 帧延迟）。
        // ======================================================================
        // bit0 = 字内最左像素，与肤色掩码同一 bit 序（否则融合会错位）
        assign S_motion_mask = {4{S_mot_px}};
        // 视图 4：3 = 该块在动（红），0 = 静止；块级判决不再区分绝对/相对门。
        assign S_mot_lv = { {2{S_mot_px}}, {2{S_mot_px}},
                            {2{S_mot_px}}, {2{S_mot_px}} };

        // ---- 块内活动像素数（0..16）：Step C 的 quiet 门的依据 -------------------
        // 块级信息现在**只剩一个用途**：背景更新的许可（另一个可选用途 = 块内占比门）。
        wire [2:0] S_act_pop = {2'b0, S_motion_mask[0]} + {2'b0, S_motion_mask[1]} +
                               {2'b0, S_motion_mask[2]} + {2'b0, S_motion_mask[3]};
        reg  [4:0] S_act_cnt;
        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n)          S_act_cnt <= 5'd0;
            else if(I_raw_tvalid) S_act_cnt <= (S_phase == 2'd0) ? {2'b0, S_act_pop}
                                                                 : (S_act_cnt + {2'b0, S_act_pop});
        end
        // 判决在 phase==3 那一拍做，而 S_act_cnt 寄存器里是"前 3 拍"的数，所以要加上本拍
        // （否则每个块内最后 4 个像素的"在动"会被漏掉）。
        wire [4:0] S_act_all = S_act_cnt + {2'b0, S_act_pop};

        // ---- Step C：quiet 门（判决"这一块现在是不是纯背景"）--------------------
        //   ① cnt ≤ BG_QUIET_PX：整块安静（背景 / 缓慢漂移）→ 允许蠕变；
        //   ② cnt == 16 且 |整块均值偏差| ≤ BG_UNIF_MAX：16 像素齐步同向变 = 均匀光照漂移
        //      → 也允许蠕变（否则灯一变，亮区残差就永远修不回来 —— 旧 quiet 单向棘轮的坑）；
        //   ③ 其余（手在块里：只有一部分像素在动）→ **冻结**。
        //   ③ 就是"静止的手不掉掩码"的机制（**不靠锁存**）。
        wire signed [8:0] S_row_diff = {1'b0, S_row_mean} - {1'b0, S_bg_use};
        wire [8:0]        S_row_abs  = S_row_diff[8] ? (~S_row_diff + 9'd1) : S_row_diff;
        // 【2026-10-18】背景更新许可 = 上一帧该块"不动"。静止的手块均值持续偏离
        // 背景 → 块标志一直为 1 → 手永远不会被吸进背景；手离开后自动恢复更新。
        wire S_quiet_blk = !S_mot_px;

        // ---- 【v2 ③】"全局 vs 局部"：数本帧有多少块在动 ---------------------------
        // 铁皮反光的闪来自灯/AWB 的**全局**变化，手是**局部**的 —— 这一点几乎免费：
        // 每块 16×16 的活动像素数（S_act_all）已经数出来了，只要再数"有多少块在动"。
        //   h_mvblk ≥ GLOBAL_BLK_TH（默认 900/3600 = 25%）⇒ 判为**光照事件**：
        //     本帧不更新背景（冻结）、掩码压掉一帧、跟踪 coast（不更新位置）。
        // ⚠ 2026-10-17 修正（用户指出）：原来只在 phase==3 判、**每个块每帧会数 16 次**
        //   （3600 块 × 16 行 = 57600，12 位立刻饱和）⇒ S_glb_evt 恒为 1 ⇒ **档 15 掩码全被压掉**。
        //   现在只在**每个 16×16 块的最后一行**（y[3:0]==15）数一次，上限才是 3600。
        //   另外加一道保险：事件要求**连续 2 帧**成立（暗场噪声偶尔一帧超阈值不触发）。
        reg [11:0] a_mvblk, h_mvblk, h_mvblk_p;
        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n) begin
                a_mvblk <= 12'd0;
                h_mvblk <= 12'd0;
                h_mvblk_p <= 12'd0;
            end
            else if(I_raw_tuser) begin
                h_mvblk_p <= h_mvblk;
                h_mvblk   <= a_mvblk;
                a_mvblk   <= 12'd0;
            end
            else if(I_raw_tvalid && (S_phase == 2'd3) && (S_y_pos[3:0] == 4'd15) &&
                    (S_act_all >= 5'd4) &&
                    (a_mvblk != 12'hFFF)) begin
                a_mvblk <= a_mvblk + 12'd1;
            end
        end
        assign S_glb_evt = (h_mvblk >= GLOBAL_BLK_TH) && (h_mvblk_p >= GLOBAL_BLK_TH);
        // 背景模型坏掉的保险：80% 以上块同时判成在动（3600 × 0.8 = 2880）。
        assign S_badbg_evt = (h_mvblk >= 12'd2880) && (h_mvblk_p >= 12'd2880);
        // 【保险 2】事件持续 >30 帧（≈0.5 s）就一定不是"灯闪一下"，而是**光照基线变了**：
        //   继续冻背景会永远卡在"全屏在动"（掩码永远被压掉）。这时强制重建背景（复用 S_reboot），
        //   让基线跟上新灯；重建收敛后事件自然解除。
        reg [7:0] S_evt_cnt;
        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n)         S_evt_cnt <= 8'd0;
            else if(I_raw_tuser) begin
                if(S_glb_evt)    S_evt_cnt <= (S_evt_cnt >= 8'd30) ? 8'd30 : (S_evt_cnt + 8'd1);
                else             S_evt_cnt <= 8'd0;
            end
        end
        assign S_evt_long = (S_evt_cnt >= 8'd30);

        // ---- Step A：更新律 = 带系数的蠕变 --------------------------------------
        // 步长 = clamp(|d| >>> BG_K, 1..BG_STEP_MAX)。钳到 ≥1 是**必须**的：纯移位在
        // |d| < 2^BG_K 时截成 0，小残差永远修不回来（旧代码同样把它钳在 1..8）。
        // 【2026-10-18】步长改用**块均值差**（与运动门同一个量），不再用行均值。
        wire [4:0] S_step_raw = S_blk_abs[7:3];   // |d| >> BG_K（BG_K=3；|d| ≤ 255 → ≤ 31）
        // 【v2】背景**允许快速吸手**：步长改成 |d|>>1（钳 1..15）。理由（用户 ②）：
        //   静止的手不靠背景模型保命 —— 跟踪器用**颜色质心**继续跟，背景爱上手就让它上，
        //   这样 quiet 门/区间记忆/自愈一大半都不需要了。
        wire [4:0] S_step_raw2 = S_blk_abs[7:1];  // |d| >> 1（≤ 127）
        wire [3:0] S_step     = S_v2
                              ? ((S_step_raw2 == 5'd0) ? 4'd1
                                                       : ((S_step_raw2 > 5'd15) ? 4'd15
                                                                                : S_step_raw2[3:0]))
                              : ((S_step_raw == 5'd0) ? 4'd1
                                                      : ((S_step_raw > {1'b0, BG_STEP_MAX}) ? BG_STEP_MAX
                                                                                           : S_step_raw[3:0]));
        wire [8:0] S_bg_p = {1'b0, S_bg_use} + {5'b0, S_step};
        wire [8:0] S_bg_m = {1'b0, S_bg_use} - {5'b0, S_step};
        wire [7:0] S_up_v = (S_bg_p > 9'd255) ? 8'd255 : S_bg_p[7:0];
        wire [7:0] S_dn_v = S_bg_m[8] ? 8'd0 : S_bg_m[7:0];

        // 【2026-10-18】三种写入时机全部只在**块末**产生一次写请求：
        //   ① 自举/重建 ② 全局平移 ③ 块均值蠕变。
        // 旧版在每一行的 phase 3 都写，自举时同一个块被写 16 次，最后一行胜出；
        // 背景存的是行均值、运动门比的是块均值，纹理背景上必然全屏判成在动。
        // v2 不看块标志（背景可以快速吸手），非 v2 在动的块冻结。
        // 背景更新用**当前帧 raw 判决**冻结：手第一帧就能保护，不需要等两帧确认；
        // 单帧噪点最多让背景冻结一帧，代价可以忽略。
        wire S_upd_ok   = S_v2 ? 1'b1 : !S_mot_blk_new;
        wire S_need_upd = S_mot_blk_we &&
                          (S_boot_eff || S_glb_shift ||
                           (S_upd_ok && !(S_v2 && S_glb_evt) && (S_blk_abs != 9'd0)));
        wire [7:0] S_new = S_boot_eff ? S_blk_mean
                         : S_glb_shift ? F_shift8(S_bg_use, S_glb_delta)
                                       : (S_blk_d[8] ? S_dn_v : S_up_v);

        // ---- 写回：决策在 phase==3 产生（整行和、活动计数都齐了），写发生在**下一块的
        //      phase==2**（地址 = S_addr_prev）→ 与 phase 3 的预取读各占一个槽，不会撞车。
        //      3 拍延迟用"一对寄存器 + 消费后清零"实现（同一块只写一次）。
        reg       S_pend_we;
        reg [7:0] S_pend_data;
        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n) begin
                S_pend_we   <= 1'b0;
                S_pend_data <= 8'd0;
            end
            else if(S_phase == 2'd3) begin
                S_pend_we   <= S_need_upd;
                S_pend_data <= S_new;
            end
            else if(S_phase == 2'd2) begin
                S_pend_we   <= 1'b0;
            end
        end

        assign S_bg_addr  = (S_phase == 2'd3) ? S_addr_next
                          : (S_phase == 2'd2) ? S_addr_prev
                                              : S_addr_cur;
        assign S_bg_we    = (S_phase == 2'd2) && S_pend_we;
        assign S_bg_wdata = S_pend_data;

    end
    else begin : g_nomotion
        // 不建运动支路时（MASK_SRC = 0/1，或 SKIN_ONLY=1）：融合掩码退化成肤色掩码，
        // 且 0 资源开销
        assign S_motion_mask = 4'b1111;
        assign S_mot_fill    = 1'b0;
        assign S_mot_lv      = 8'd0;
        assign S_bg_cur      = 8'd0;
        assign S_bg_rdy      = 1'b1;
        assign S_glb_evt     = 1'b0;
        assign S_evt_long    = 1'b0;
    end
    endgenerate

    // ---- 运动门：**运行时档位开关**（2026-10-16）---------------------------------
    //   档 2 = 运动门**开**（融合 = 肤色 ∩ 运动），档 3 = **关**（对照，= 只看肤色）。
    //   其余档位（含交付档 0/1）一律**关** → 与 M1 上板定标的那一版行为一字不变。
    //   背景还没建好（自举/重建窗口，S_bg_rdy=0）时也不生效：拿未初始化的 ERAM 内容当参考
    //   只会乱报，退回"只看肤色"更安全。
    //   一版 bit 现场 A/B：`W 08 0002`（开）/ `W 08 0003`（关），画面里掩码 + 准星都在
    //   （isp_top 的 S_dbg_ovl 把 2/3/13/14 也并进叠加使能了）。
    //   ⚠ `S_mot_on` 在**肤色那一段**就定义了（档 2 或档 14）—— 因为档 14 = ② + 运动门
    //     同时开的"最终候选配置"。
    wire S_mot_use = S_mot_on && S_bg_rdy;
    // 【2026-10-18】强运动块整块填满（灭手掌内部空洞）；弱运动块仍用像素级肤色收边。
    // 注意填充必须**绕过肤色**：写在 S_skin_use & 里面时两个分支都是 skin，填充是空操作
    // （TD 会直接把它当死逻辑裁掉）。
    wire [3:0] S_fusion_mask = S_mot_use ?
        (S_mot_fill ? 4'b1111 : (S_skin_use & S_motion_mask)) :
        S_skin_use;

    // ========================================================================
    // 【2026-10-16 ①：块级占比门】32×32 块"过判据像素占比 ≥ N 才保留"
    //   数据结构：每块 1 字节 = {上一帧达标标志, 本帧累计合格像素数(7bit)}
    //   地址：行 = y[9:5]（0..22）、列 = x_grp[7:3]（0..39）→ addr = 行×40 + 列（≤919）
    //   读到字节后：用 bit7 当本块**所有像素**的门；本行 8 拍的合格像素数累加进低 7 位。
    //   写回：访问槽照搬背景 RAM 那套 —— beat7 发下一块的地址（预取），beat0 写**上一块**
    //   （把刚才算完的那一字节落盘）→ 两个槽不同拍，不撞车。
    //   清零：块的最后一行（y[4:0]==31）写回 {达标标志, 0}，顺带把计数器复位，
    //   所以不需要额外的清屏扫描。
    // ========================================================================
    wire S_occ_keep;      // 1 = 这一块的像素保留（门开着 / 这一块是"实的"）
    generate
    if ((MASK_SRC != 0) && (OCC_EN != 0)) begin : g_occ

        wire [2:0] S_obeat = S_x_grp[2:0];              // 块内第几拍（8 拍 = 32 像素）
        wire [5:0] S_ocol  = S_x_grp[7:3];              // 块列 0..39
        wire [4:0] S_orow  = S_y_pos[9:5];              // 块行 0..22
        wire [9:0] S_obase = {S_orow, 5'b0} + {S_orow, 3'b0};   // 行 × 40（32 + 8）
        wire [9:0] S_ocur  = S_obase + {4'b0, S_ocol};
        wire [9:0] S_onext = (S_ocur == 10'd919) ? 10'd0 : (S_ocur + 10'd1);
        wire [9:0] S_oprev = (S_ocur == 10'd0)   ? 10'd919 : (S_ocur - 10'd1);

        wire S_osmp  = (S_y_pos[2:0] == 3'd0);          // 采样行：块内每 8 行采 1 行
        // 块的最后一行 → 结算。⚠ 最底下那一块行只有 16 行（720 = 22×32 + 16），
        // 永远等不到 y[4:0]==31，所以**帧的最后一行**也当结算点。
        wire S_olast = (S_y_pos[4:0] == 5'd31) || (S_y_pos == 10'd719);

        wire [9:0] S_oaddr;
        wire       S_owe;
        wire [7:0] S_owdata;
        wire [7:0] S_ordata;

        eram_spram #(.DATA_WIDTH(8), .ADDR_WIDTH(10)) u_occ_mem (
            .I_clk  (I_clk),
            .I_we   (S_owe),
            .I_addr (S_oaddr),
            .I_wdata(S_owdata),
            .O_rdata(S_ordata)
        );

        assign S_oaddr = (S_obeat == 3'd7) ? S_onext
                       : (S_obeat == 3'd0) ? S_oprev
                                           : S_ocur;

        // 本块这一行的字节（beat0 抓到预取回来的值，整块 8 拍都有效）
        reg [7:0] S_obyte;
        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n) S_obyte <= 8'd0;
            else if(I_raw_tvalid && (S_obeat == 3'd0)) S_obyte <= S_ordata;
        end

        // 本拍 4 个像素里"过最终肤色判据"的个数（0..4）
        wire [2:0] S_ocnt_beat = {2'b0, S_skin_use[0]} + {2'b0, S_skin_use[1]} +
                                 {2'b0, S_skin_use[2]} + {2'b0, S_skin_use[3]};
        // 饱和累加（饱和到 127）：beat0 载入"存量 + 本拍"，其余拍"累加 + 本拍"
        reg  [6:0] S_oacc;
        wire [7:0] S_osum_a = {1'b0, S_obyte[6:0]} + {5'b0, S_ocnt_beat};
        wire [7:0] S_osum_b = {1'b0, S_oacc}       + {5'b0, S_ocnt_beat};
        wire [6:0] S_ocnt_a = (S_osum_a > 8'd127) ? 7'd127 : S_osum_a[6:0];
        wire [6:0] S_ocnt_b = (S_osum_b > 8'd127) ? 7'd127 : S_osum_b[6:0];
        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n) S_oacc <= 7'd0;
            else if(I_raw_tvalid && S_osmp) begin
                if(S_obeat == 3'd0) S_oacc <= S_ocnt_a;
                else                S_oacc <= S_ocnt_b;
            end
        end

        // 结算与写回：beat7 时本行的累计值就是 S_ocnt_b（含本拍）
        wire S_owin = (S_obyte[6:0] >= OCC_MIN);        // 最后一行用字节里的总计数判决
        reg       S_opend_we;
        reg [7:0] S_opend_data;
        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n) begin
                S_opend_we   <= 1'b0;
                S_opend_data <= 8'd0;
            end
            else if(S_obeat == 3'd7) begin
                S_opend_we   <= S_osmp || S_olast;
                S_opend_data <= S_olast ? {S_owin, 7'd0}
                                        : {S_obyte[7], S_ocnt_b};
            end
            else if(S_obeat == 3'd0) begin
                S_opend_we   <= 1'b0;
            end
        end
        assign S_owe    = (S_obeat == 3'd0) && S_opend_we;
        assign S_owdata = S_opend_data;

        // 上电头几帧 ERAM 内容未定义 → 强制放行（过了 4 帧才开始按标志门控）
        reg [2:0] S_ofrm;
        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n)                      S_ofrm <= 3'd0;
            else if(I_raw_tuser && !(&S_ofrm)) S_ofrm <= S_ofrm + 3'd1;
        end
        assign S_occ_keep = !S_occ_act ||
                            ((&S_ofrm) && S_obyte[7]);

    end
    else begin : g_occ_off
        // 关掉时（MASK_SRC=0 或 OCC_EN=0）门恒开，0 资源
        assign S_occ_keep = 1'b1;
    end
    endgenerate

    // ---- 掩码源选择（编译期常量 → 综合后没有 mux，也没有多余负载）------------
    // 【v2，档 15】**统计/跟踪走颜色，显示/指尖走运动候选区**（见 g_track 里的 S_mask_disp）：
    //   颜色负责"手大概在哪"（静止的手也能算质心，靠跟踪器保命），
    //   运动负责"画面上哪块在动"（叠加/指尖只看候选区，桌面和铁皮不会涂红）。
    // 非 v2 档维持旧的"肤色 ∧ 运动"硬融合。
    // 全局光照事件（③）期间整帧压掉掩码（否则会"突然糊一片红"）。
    wire [3:0] S_mask_sel_raw = (MASK_SRC == 2) ? (S_v2 ? S_skin_use : S_fusion_mask) :
                                (MASK_SRC == 1) ? S_skin_mask   : S_edge_mask;
    wire [3:0] S_mask_sel = (S_occ_keep && !(S_v2 && S_glb_evt)) ? S_mask_sel_raw : 4'b0000;

    // ---- mask_stats 的输出（Step 3 要用"上一帧"的包围盒/计数，先声明）---------
    wire [19:0] S_mcnt;
    wire [10:0] S_xmin, S_xmax, S_ymin, S_ymax;
    wire [30:0] S_sumx;
    wire [29:0] S_sumy;
    wire        S_empty;

    // ---- 质心（M1 收尾）-----------------------------------------------------
    // 由下面的 g_cent 产生：S_cent_x/S_cent_y = 上一帧掩码质心（列/行），
    // S_cent_valid = 这一帧质心可信。MASK_SRC=0（边缘自检回归）或 USE_CENTROID=0
    // 时走 g_cent_off，直接给常量 → 除法器整段不综合。
    wire [10:0] S_cent_x;
    wire [9:0]  S_cent_y;
    wire        S_cent_valid;
    wire [20:0] S_wsum_h;     // 上一帧 Σ权重（SOFT_TRACK=1 时用它判"命中"）
    // ROI 窗口边界（g_track 里维护，导出来给软权重"只在窗口内投票"用）
    wire [10:0] S_roi_x0_w, S_roi_x1_w;
    wire [9:0]  S_roi_y0_w, S_roi_y1_w;

    // ========================================================================
    // M1 收尾：质心 = Σ列 / Σ行 ÷ 掩码像素数（每帧一次串行除法）
    //
    // 为什么串行除法：A 线 DSP 配额是 0，组合除法器又会吃掉一整条关键路径；质心每帧
    // 只要一个值（60 Hz），27 拍 ≈ 0.46 µs @59 MHz，帧内绰绰有余。
    //
    // 被除数 = mask_stats 的 Σ列 / Σ行（各 >>4），除数 = 掩码像素数（>>4）：两边同移
    // 4 位商不变，除数缩到 16 位、迭代位也少 4 个。恢复余数法：R = R<<1 | A[i]，
    // R ≥ B 就减 B 并把该商位置 1。商寄存器只有 11/10 位——商一定 < 2048 (列) /
    // < 1024 (行)，27 次移入后高位的零自然移出，留下的就是有效商。
    //
    // **相位对齐（关键）**：除法启动在 tuser 的**下一拍**——tuser 当拍 mask_stats 刚
    // 把上一帧的 Σ 锁存进输出寄存器；跟踪器在下一次 tuser 读到的仍是这批 Σ 与包围盒，
    // 所以质心与包围盒来自**同一帧**，不引入额外滞后。（观测整体滞后 1~2 帧是
    // mask_stats"帧首锁存 + 帧首读取"的固有相位，两条路一致。）
    //
    // 几何修正：mask_stats 的列号按边缘流几何（列 4k−1..4k+2）算，而我们喂进去的是
    // RAW 几何（4k..4k+3）→ 算出来的列号比真实像素列小 1，所以结果 +1。
    //
    // 资源：≈70 LUT6 + ≈130 FF，0 ERAM / 0 DSP。
    // 注意：**不能**把 generate 嵌在 g_track 里（TD 报 "Verilog 2000 keyword
    // 'generate' used in incorrect context"），所以这一段放在模块级。
    // ========================================================================
    generate
    if ((MASK_SRC != 0) && (USE_CENTROID != 0)) begin : g_cent

        reg [10:0] S_cx_hold;      // 上一帧质心列（已做 +1 几何修正并钳范围）
        reg [9:0]  S_cy_hold;      // 上一帧质心行
        reg        S_cv_valid;     // 上一帧质心可信（像素数 ≥ MIN_CNT）

