    wire [9:0] S_ysum2 = {1'b0, S_raw_pix2[23:16]} + {S_raw_pix2[15:8], 1'b0} + {1'b0, S_raw_pix2[7:0]};
    wire [9:0] S_ysum3 = {1'b0, S_raw_pix3[23:16]} + {S_raw_pix3[15:8], 1'b0} + {1'b0, S_raw_pix3[7:0]};
    wire [7:0] S_ynew0 = S_ysum0[9:2];
    wire [7:0] S_ynew1 = S_ysum1[9:2];
    wire [7:0] S_ynew2 = S_ysum2[9:2];
    wire [7:0] S_ynew3 = S_ysum3[9:2];
    wire [7:0] S_y0 = S_y_new ? S_ynew0 : S_gray0;
    wire [7:0] S_y1 = S_y_new ? S_ynew1 : S_gray1;
    wire [7:0] S_y2 = S_y_new ? S_ynew2 : S_gray2;
    wire [7:0] S_y3 = S_y_new ? S_ynew3 : S_gray3;

    // 每像素两个色差（9 位有符号）：d1 = B−Y、d2 = R−Y。判据 v1/v2 与诊断上报共用。
    wire signed [8:0] S_d1_0 = {1'b0, S_raw_pix0[7:0]} - {1'b0, S_y0};
    wire signed [8:0] S_d1_1 = {1'b0, S_raw_pix1[7:0]} - {1'b0, S_y1};
    wire signed [8:0] S_d1_2 = {1'b0, S_raw_pix2[7:0]} - {1'b0, S_y2};
    wire signed [8:0] S_d1_3 = {1'b0, S_raw_pix3[7:0]} - {1'b0, S_y3};
    wire signed [8:0] S_d2_0 = {1'b0, S_raw_pix0[23:16]} - {1'b0, S_y0};
    wire signed [8:0] S_d2_1 = {1'b0, S_raw_pix1[23:16]} - {1'b0, S_y1};
    wire signed [8:0] S_d2_2 = {1'b0, S_raw_pix2[23:16]} - {1'b0, S_y2};
    wire signed [8:0] S_d2_3 = {1'b0, S_raw_pix3[23:16]} - {1'b0, S_y3};

    // 判据 v1：(B−Y)/(R−Y) 矩形。Y 由档位决定（旧 S_gray / 新 S_ynew）。
    // ---- 【第 1 轮】皮肤窗口 = 运行时寄存器 ---------------------------------
    // 复位值 = 交付默认（d1∈[D1_MIN,D1_MAX]、d2∈[D2_MIN_DELIV,D2_MAX]）。
    // 第 3 轮的"一键示教"只往这 4 个寄存器写数 —— 判据路径从此不再被后续改动触碰。
    // 档 8（旧 Y 全宽松）与档 9（d2≥5 标定参照）仍走编译期常量/固定值，与示教解耦。
    reg signed [8:0] S_win_d1_lo, S_win_d1_hi, S_win_d2_lo, S_win_d2_hi;
    always @(posedge I_clk or negedge I_rst_n) begin
        if(!I_rst_n) begin
            S_win_d1_lo <= D1_MIN;        S_win_d1_hi <= D1_MAX;
            S_win_d2_lo <= D2_MIN_DELIV;  S_win_d2_hi <= D2_MAX;
        end
        // 【第 3 轮】一键示教：窗末判定通过的那一拍，把包络写进这 4 个寄存器。
        // **只有这一处**写它们（判定不通过就一个数都不写，保持原窗口）。
        else if(S_teach_apply) begin
            S_win_d1_lo <= S_teach_d1_lo;
            S_win_d1_hi <= S_teach_d1_hi;
            S_win_d2_lo <= S_teach_d2_lo;
            S_win_d2_hi <= S_teach_d2_hi;
        end
    end

    // ========================================================================
    // 【第 3 轮】一键示教：采样窗状态机 + (d1,d2) 包络 + 窗末判定与写入
    //
    // 一次示教 = 一个 60 帧（≈1 s）的采样窗：
    //   * 窗内每一拍把**固定中央区**（x∈[TEACH_X0,TEACH_X1]、y∈[TEACH_Y0,TEACH_Y1]）里
    //     通过**宽松前置门**（d1∈[−128,0] ∧ d2∈[0,127]）的像素并进包络：d1/d2 各记
    //     min/max，同时数像素个数；
    //   * 窗末（第 60 帧的帧首）判一次：样本数 ≥ TEACH_MIN_PIX **且** d2 跨度 ≥
    //     TEACH_MIN_D2SPAN → 包络上下限各自按**自身跨度**外扩 (span>>3)+(span>>6)
    //     （≈14%，lo 向下、hi 向上）后**一次**写进 4 个运行时窗口寄存器；否则什么都不写。
    // 为什么采样区是固定中央区：ROI 的边界跟着跟踪状态走（锁定/丢失会跳），拿它当采样区会
    //   让"同样的手"示教出不同的窗口。
    // 为什么用 min/max 包络而不是均值±方差：方差要累加平方（成本高、现场难解释）；包络只要
    //   比较 + 选择，而且上下限能**分别**外扩（肤色分布本来就不对称）。
    // 资源：≈200 LUT6 / ≈75 FF / 0 ERAM / 0 DSP；TEACH_EN=0 时整段不综合（回到第 1 轮行为）。
    // ========================================================================
    wire              S_teach_apply;         // 窗末判定通过（1 拍脉冲）
    wire signed [8:0] S_teach_d1_lo, S_teach_d1_hi;
    wire signed [8:0] S_teach_d2_lo, S_teach_d2_hi;

    generate
    if (TEACH_EN != 0) begin : g_teach

        // ---- 采样区判据：按"字号"判一次即可 ----------------------------------
        // 中央区左右边界都落在 4 像素字边界上（320 = 4×80、959 = 4×239+3），所以按字号判
        // 一次就够（每个字号只取它最后那一个像素，见下面"采样密度"）。
        wire [10:0] S_t_xg0 = TEACH_X0 >> 2;
        wire [10:0] S_t_xg1 = TEACH_X1 >> 2;
        wire        S_t_zone = (S_y_pos >= TEACH_Y0) && (S_y_pos <= TEACH_Y1) &&
                               (S_x_grp >= S_t_xg0) && (S_x_grp <= S_t_xg1);

        // ---- 宽松前置门 ------------------------------------------------------
        function F_teach_pre;
            input signed [8:0] I_d1, I_d2;
            begin
                F_teach_pre = (I_d1 >= TEACH_PRE_D1_LO) && (I_d1 <= TEACH_PRE_D1_HI) &&
                              (I_d2 >= TEACH_PRE_D2_LO) && (I_d2 <= TEACH_PRE_D2_HI);
            end
        endfunction

        // 4 级延迟线（skew buffer）：一拍进一个采样像素，末级就是"4 个有效拍之前"那个。
        // 只在 I_raw_tvalid 拍推进、也只在 tvalid 拍合并 → 每个**被采样的**像素恰好并一次，
        // 不需要相位计数器 / FSM（它只是把"比较"和"并进包络"错开 4 拍，不改变吞进去的样本）。
        reg signed [8:0] S_k1_d1, S_k2_d1, S_k3_d1, S_k4_d1;
        reg signed [8:0] S_k1_d2, S_k2_d2, S_k3_d2, S_k4_d2;
        reg              S_k1_ok, S_k2_ok, S_k3_ok, S_k4_ok;
        reg              S_k1_mv, S_k2_mv, S_k3_mv, S_k4_mv;   // "这个像素所在块在动"跟数据一起延
        reg              S_blk_mv;                             // 本块"在动"（样本拍刷新，本块共用）

        reg               S_t_win;                       // 采样窗开着
        reg [7:0]         S_t_frm;                       // 窗内已经采到的帧数
        reg signed [8:0]  S_t_d1lo, S_t_d1hi;
        reg signed [8:0]  S_t_d2lo, S_t_d2hi;
        reg [11:0]        S_t_cnt;                       // 进包络的**样本**数（12 位饱和）
        reg [7:0]         S_t_flash;                     // 窗末起的"闪叠加"倒计时（帧）

        // ======================================================================
        // 采样密度（2026-09-29 压缩；上板验收之前做的）：**每 4 列取 1 列** —— 取字号里最后一个像素
        // （列 = 4·x_grp+3，即列 3、7、…、959）。
        //
        // 为什么：一拍 4 个像素的 min/max 树 ≈110 LUT6，是这一整块最大的一笔；改成"一拍只并
        // 一个像素"后，每拍只要 1 组比较/选择（≈20 LUT6 + 76 FF 的延迟线）。
        //
        // ⚠ **不是"语义不变"**（我们的抽样点是 4 像素/拍，所以一拍只并 1 个 = 每 4 列取 1），
        //   差两处，写清楚免得误读：
        //   ① 密度：每帧只统计 160 列 × 360 行 = 5.76 万样本（原来 23 万）。门限仍按"真实
        //      像素"解释 —— 比较用 TEACH_MIN_PIX>>2，所以 2000 还是"2000 个真实像素"的意思
        //      （内部计数是样本数，约 1/4）。包络只会差"相邻列那几个 LSB"。
        //   ② 窗边界最多差 4 个像素：开窗那一拍延迟线里还残留开窗前的 4 个像素（会被并进新
        //      包络，无害）；窗末那一拍还有 4 个像素没来得及并（判定少看这 4 个）。
        //      相对 60 帧 × 5.76 万样本，是 1e-7 量级。
        // ======================================================================
        // 喂进延迟线的那一个像素：在中央区 ∧ 过宽松前置门 才算"算数"（标志跟着数据一起延）
        wire S_t_in_ok = S_t_zone && F_teach_pre(S_d1_3, S_d2_3);

        // ---- 块级帧差门：只让"在动"的像素进包络（2026-09-30，方案 B）----------------
        // 为什么：上板实测"手完全拿开、只对着桌面"也能学出一大片红 —— 前置门里全是背景像素。
        //   示教时手在动、背景不动，所以再叠一道"这块相对上一帧变过"的门：静态背景一个块都不动
        //   → 一个样本都进不来 → 样本数不够 → 直接拒绝（根本学不到背景）。
        // 结构：中央区按 16×16 分块 = 40×23 = **920 块 → 1 块 ERAM**（1024×8）。每块每帧只采一个
        //   样本像素（就是本模块用的那个：列 4·x_grp+3、块内第一行），存进 ERAM；下一帧同位置比较，
        //   差 > TEACH_MOT_TH 就认为"这块在动"，本块其余像素共用这个结论。
        // 时序：地址用"**下一个**采样列所在的块"→ **样本拍的前一拍**读出的正好是上一帧的块样本
        //   （eram_spram 读延迟 1 拍）；写只在样本拍 → 同一地址不会同拍既读又写（它的硬性要求）。
        wire [10:0] S_col4   = {S_x_grp, 2'b00} + 11'd7;      // 采样列 + 4 = 4·x_grp + 7
        wire [6:0]  S_bc4    = S_col4[10:4] - 7'd20;          // 块列 0..39（区外会取值越界，只用不写）
        wire [5:0]  S_br     = S_y_pos[9:4] - 6'd11;          // 块行 0..22（区外回绕，无害）
        wire [10:0] S_bsum   = {S_br, 5'b0} + {S_br, 3'b0};   // 块行 × 40
        wire [10:0] S_baddr  = S_bsum + {4'b0, S_bc4};
        wire [7:0]  S_bq;                                      // ERAM 读出的"上一帧块样本"
        // 采样行 = 块内第一行（中央区首行 180 不是 16 的倍数，所以单独放行一次）
        wire S_smp_row = (S_y_pos[3:0] == 4'd0) || (S_y_pos == TEACH_Y0);
        // 样本拍：在中央区、采样行、块内第一个采样列（列 ≡ 3 mod 16）——每块每帧正好一次
        wire S_blk_smp = I_raw_tvalid && S_t_zone && S_smp_row && (S_x_grp[1:0] == 2'd0);
        wire [7:0] S_bd = (S_y3 >= S_bq) ? (S_y3 - S_bq) : (S_bq - S_y3);
        wire       S_blk_mv_now = (S_bd > TEACH_MOT_TH);
        // 样本拍用"刚算出来"的结论；本块其余像素用锁存（S_blk_mv）的那个结论
        wire       S_px_mv = S_blk_smp ? S_blk_mv_now : S_blk_mv;

        eram_spram #(.DATA_WIDTH(8), .ADDR_WIDTH(10)) u_teach_blk (
            .I_clk  (I_clk),
            .I_we   (S_blk_smp),                  // 只在样本拍写（地址当拍正好是"下一个采样列所在块"=本块）
            .I_addr (S_baddr[9:0]),               // 920 块 < 1024，够；区外的越界值只读不写
            .I_wdata(S_y3),
            .O_rdata(S_bq)
        );

        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n) begin
                S_t_win  <= 1'b0;     S_t_frm  <= 8'd0;
                S_t_d1lo <= 9'sd0;    S_t_d1hi <= 9'sd0;
                S_t_d2lo <= 9'sd0;    S_t_d2hi <= 9'sd0;
                S_t_cnt  <= 12'd0;
                S_t_flash <= 8'd0;
                S_k1_d1 <= 9'sd0;  S_k2_d1 <= 9'sd0;  S_k3_d1 <= 9'sd0;  S_k4_d1 <= 9'sd0;
                S_k1_d2 <= 9'sd0;  S_k2_d2 <= 9'sd0;  S_k3_d2 <= 9'sd0;  S_k4_d2 <= 9'sd0;
                S_k1_ok <= 1'b0;   S_k2_ok <= 1'b0;   S_k3_ok <= 1'b0;   S_k4_ok <= 1'b0;
                S_k1_mv <= 1'b0;   S_k2_mv <= 1'b0;   S_k3_mv <= 1'b0;   S_k4_mv <= 1'b0;
                S_blk_mv <= 1'b0;                      // 复位后先按"没动"处理（保守：不并）
            end
            // 帧边界收到请求 → 开（或重开）采样窗：清包络（min 置 +255 / max 置 −256）
            else if(I_raw_tuser && S_teach_req) begin
                S_t_win  <= 1'b1;     S_t_frm  <= 8'd0;
                S_t_d1lo <= 9'h0FF;   S_t_d1hi <= 9'h100;
                S_t_d2lo <= 9'h0FF;   S_t_d2hi <= 9'h100;
                S_t_cnt  <= 12'd0;
                S_t_flash <= 8'd0;                        // 新一轮采样期间不闪
            end
            else begin
                // (1) 延迟线：每个有效拍推进一级（与窗口无关 —— 窗末停在线上的那 4 个就不并了）
                if(I_raw_tvalid) begin
                    S_k1_d1 <= S_d1_3;     S_k1_d2 <= S_d2_3;     S_k1_ok <= S_t_in_ok;  S_k1_mv <= S_px_mv;
                    S_k2_d1 <= S_k1_d1;    S_k2_d2 <= S_k1_d2;    S_k2_ok <= S_k1_ok;    S_k2_mv <= S_k1_mv;
                    S_k3_d1 <= S_k2_d1;    S_k3_d2 <= S_k2_d2;    S_k3_ok <= S_k2_ok;    S_k3_mv <= S_k2_mv;
                    S_k4_d1 <= S_k3_d1;    S_k4_d2 <= S_k3_d2;    S_k4_ok <= S_k3_ok;    S_k4_mv <= S_k3_mv;
                    // 块级帧差：样本拍刷新本块结论（ERAM 的写在 u_teach_blk 那一拍完成）
                    if(S_blk_smp) S_blk_mv <= S_blk_mv_now;
                end
                // (2) 包络合并：窗内 + 末级样本算数 + **本块在动** → 一拍一次 min/max
                //     用 tvalid 一起闸住是为了**行间空隙不重复并同一个像素**（否则计数会虚高）
                if(S_t_win && I_raw_tvalid && S_k4_ok && S_k4_mv) begin
                    S_t_d1lo <= (S_k4_d1 < S_t_d1lo) ? S_k4_d1 : S_t_d1lo;
                    S_t_d1hi <= (S_k4_d1 > S_t_d1hi) ? S_k4_d1 : S_t_d1hi;
                    S_t_d2lo <= (S_k4_d2 < S_t_d2lo) ? S_k4_d2 : S_t_d2lo;
                    S_t_d2hi <= (S_k4_d2 > S_t_d2hi) ? S_k4_d2 : S_t_d2hi;
                    if(S_t_cnt != 12'hFFF) S_t_cnt <= S_t_cnt + 12'd1;
                end
                // (3) 帧计数：采够 TEACH_WIN_FRAMES 帧就关窗（窗末判定见下面的 S_t_last）
                if(I_raw_tuser && S_t_win) begin
                    if((S_t_frm + 8'd1) >= TEACH_WIN_FRAMES) S_t_win <= 1'b0;
                    else                                     S_t_frm <= S_t_frm + 8'd1;
                end
                // (4) 【第 4 轮】闪叠加：窗末那一拍点亮 TEACH_FLASH_FRAMES 帧，到点自己灭。
                // 条件与上面的关窗**同一个**（都用旧值判断），所以判定过不过都会闪 2 s。
                if(I_raw_tuser) begin
                    if(S_t_win && ((S_t_frm + 8'd1) >= TEACH_WIN_FRAMES))
                        S_t_flash <= TEACH_FLASH_FRAMES;
                    else if(S_t_flash != 8'd0)
                        S_t_flash <= S_t_flash - 8'd1;
                end
            end
        end

        // ---- 窗末判定 --------------------------------------------------------
        // 包络非空时 span = hi − lo ≥ 0；空包络（一个样本都没进）时这两个数没意义，
        // 但那时样本数门限必然不通过。
        wire [9:0] S_t_d1span = {S_t_d1hi[8], S_t_d1hi} - {S_t_d1lo[8], S_t_d1lo};
        wire [9:0] S_t_d2span = {S_t_d2hi[8], S_t_d2hi} - {S_t_d2lo[8], S_t_d2lo};
        // 外扩量 = (span>>3)+(span>>6) ≈ 14%；span ≤ 511 → 外扩量 ≤ 70，7 位够
        wire [6:0] S_t_exp1 = {1'b0, S_t_d1span[8:3]} + {4'b0, S_t_d1span[8:6]};
        wire [6:0] S_t_exp2 = {1'b0, S_t_d2span[8:3]} + {4'b0, S_t_d2span[8:6]};

        // 外扩（9 位有符号不会溢出：前置门已把包络限在 d1∈[−115,−2]、d2∈[2,80]，外扩量足够小）
        // + **安全带**（2026-09-30 上板实测"手拿开也学会背景"之后加的）：教出来的 4 个数钳在
        // [TEACH_CLP_*] 里 —— 比前置门宽一点，但不允许跑到离谱的地方。
        wire signed [8:0] S_x1_lo = S_t_d1lo - {2'b0, S_t_exp1};
        wire signed [8:0] S_x1_hi = S_t_d1hi + {2'b0, S_t_exp1};
        wire signed [8:0] S_x2_lo = S_t_d2lo - {2'b0, S_t_exp2};
        wire signed [8:0] S_x2_hi = S_t_d2hi + {2'b0, S_t_exp2};
        assign S_teach_d1_lo = (S_x1_lo < TEACH_CLP_D1_LO) ? TEACH_CLP_D1_LO : S_x1_lo;
        assign S_teach_d1_hi = (S_x1_hi > TEACH_CLP_D1_HI) ? TEACH_CLP_D1_HI : S_x1_hi;
        assign S_teach_d2_lo = (S_x2_lo < TEACH_CLP_D2_LO) ? TEACH_CLP_D2_LO : S_x2_lo;
        assign S_teach_d2_hi = (S_x2_hi > TEACH_CLP_D2_HI) ? TEACH_CLP_D2_HI : S_x2_hi;

        // 样本门限：计数口径是"每 4 列取 1 列"，所以拿 TEACH_MIN_PIX>>2 去比 —— TEACH_MIN_PIX
        // 仍按**真实像素数**解释（2000 → 500 个样本）。取 [13:2] 是 >>2 且不产生位宽截断告警
        // （要求 TEACH_MIN_PIX < 16384）。
        wire [11:0] S_t_min = TEACH_MIN_PIX[13:2];

        // 窗末那一拍（＝第 60 帧的帧首）：样本够 + d2 跨度够 才写。
        // 同一拍又来了新请求就先满足新请求（不写旧结果，直接重开窗）。
        wire S_t_last = S_t_win && ((S_t_frm + 8'd1) >= TEACH_WIN_FRAMES);
        // 自保（2026-09-30）：包络只要**贴着前置门的边**（= 背景把整个框填满了）→ 直接拒绝、不写窗口
        wire S_t_edge = (S_t_d1lo == TEACH_PRE_D1_LO) || (S_t_d1hi == TEACH_PRE_D1_HI) ||
                        (S_t_d2lo == TEACH_PRE_D2_LO) || (S_t_d2hi == TEACH_PRE_D2_HI);
        wire S_t_ok   = (S_t_cnt >= S_t_min) && (S_t_d2span >= TEACH_MIN_D2SPAN) && !S_t_edge;
        assign S_teach_apply = I_raw_tuser && S_t_last && S_t_ok && !S_teach_req;
        // 闪叠加指示灯：窗末起（含"新请求抢在窗末同一拍"的情况）高 ~2 s，给 isp_top 用
        assign O_teach_flash = (S_t_flash != 8'd0);

    end
    else begin : g_teach_off
        // TEACH_EN=0：窗口寄存器只剩复位值（= 交付默认），采样/判定逻辑一个门都不占
        // （上面那几拍事件检测仍然在，代价约 6 FF）
        assign S_teach_apply = 1'b0;
        assign O_teach_flash = 1'b0;
        assign S_teach_d1_lo = 9'sd0;   assign S_teach_d1_hi = 9'sd0;
        assign S_teach_d2_lo = 9'sd0;   assign S_teach_d2_hi = 9'sd0;
    end
    endgenerate
    // 判据实际用的 4 个边界（档 8/9 走常量，其余走运行时寄存器）
    wire signed [8:0] S_f_d1_lo = (S_cfg == 4'd8) ? D1_MIN : S_win_d1_lo;
    wire signed [8:0] S_f_d1_hi = (S_cfg == 4'd8) ? D1_MAX : S_win_d1_hi;
    wire signed [8:0] S_f_d2_lo = (S_cfg == 4'd8) ? D2_MIN :
                                 ((S_cfg == 4'd9) ? 9'sd5 : S_win_d2_lo);
    wire signed [8:0] S_f_d2_hi = (S_cfg == 4'd8) ? D2_MAX : S_win_d2_hi;

    // 判据 v1：d1/d2 矩形（Y 由档位决定：档 8 用旧 S_gray，其余用真 luma）。
    function F_skin_px;
        input signed [8:0] I_d1, I_d2;   // d1 = B−Y、d2 = R−Y
        begin
            F_skin_px = (I_d1 >= S_f_d1_lo) && (I_d1 <= S_f_d1_hi) &&
                        (I_d2 >= S_f_d2_lo) && (I_d2 <= S_f_d2_hi);
        end
    endfunction

    // 判据 v2（打磨②）：饱和度门 + 亮度窗 + 暖色差（与 Y 的绝对值无关）
    function F_skin2_px;
        input [7:0] I_r, I_g, I_b, I_y;
        reg [7:0] S_hi, S_lo, S_rg, S_rb;
        begin
            S_hi = (I_r >= I_g) ? ((I_r >= I_b) ? I_r : I_b) : ((I_g >= I_b) ? I_g : I_b);
            S_lo = (I_r <= I_g) ? ((I_r <= I_b) ? I_r : I_b) : ((I_g <= I_b) ? I_g : I_b);
            // 差值必须先判大小再减，否则 8 位减法会回绕成一个大正数
            S_rg = (I_r >= I_g) ? (I_r - I_g) : 8'd0;
            S_rb = (I_r >= I_b) ? (I_r - I_b) : 8'd0;
            F_skin2_px = ((S_hi - S_lo) >= SAT_MIN) && (I_y >= Y_MIN) && (I_y <= Y_MAX) &&
                         (S_rg >= RG_MIN) && (S_rb >= RB_MIN);
        end
    endfunction

    // 判据 v3（M2.2 修正，用户提议）：**按亮度归一化**的肤色判据 —— 用比例代替绝对值窗。
    //   d2/Y ∈ [2^-NORM_LO_SH, 2^-NORM_HI_SH]、|d1|/Y 同区间。边界由 Y 右移得到，不用乘除。
    //   注意 d2 必须为正（皮肤是 R > Y）：负 d2 零扩展后是个大正数，会被上界自然挡掉。
    function F_skin_norm_px;
        input signed [8:0] I_d1, I_d2;   // d1 = B−Y、d2 = R−Y
        input [7:0]        I_y;          // 真 luma
        reg [8:0] S_l, S_h, S_a1;
        begin
            // 下界 ≈ (Y>>4) − (Y>>6) ≈ Y/21.3（不用乘法）；再钳到 ≥1 防极暗退化
            S_l  = {5'b0, I_y[7 : NORM_LO_SH]} - {7'b0, I_y[7 : NORM_LO_SUB]};
            S_l  = (S_l <= 9'd1) ? 9'd1 : S_l;
            S_h  = {1'b0, I_y[7 : NORM_HI_SH]};                   // Y >> NORM_HI_SH（默认 Y/4）
            S_a1 = I_d1[8] ? (~I_d1 + 9'd1) : I_d1;               // |d1|
            // ★ 2026-10-11 补的关键条件：d1 = B−Y **必须为负**（皮肤比 Y 更暖，B 小于 Y）。
            //   第一版漏了它、只比 |d1| 的幅度 → 偏冷/中性的表面也满足比例窗 → **整屏变红**。
            //   注意 d2 的正负不用单独判：d2 < 0 时零扩展是个大正数，必然超过上界 S_h。
            // 上界再加 M1 的老硬帽（min(Y/4, 硬帽)）：比例界挡"亮暖桌面"，硬帽挡"特别亮的杂光"。
            F_skin_norm_px = I_d1[8] &&                       // d1 < 0（B < Y）
                             (S_a1 >= S_l) && (S_a1 <= S_h) &&
                             (S_a1 <= NORM_D1_HARD) &&
                             ({1'b0, I_d2} >= S_l) && ({1'b0, I_d2} <= S_h) &&
                             ({1'b0, I_d2} <= NORM_D2_HARD);
        end
    endfunction

    // 掩码 bit 序与 S_edge_mask 一致：bit0 = 字内最左像素 [95:72]。
    wire [3:0] S_skin_mask = {F_skin_px(S_d1_3, S_d2_3),
                              F_skin_px(S_d1_2, S_d2_2),
                              F_skin_px(S_d1_1, S_d2_1),
                              F_skin_px(S_d1_0, S_d2_0)};

    wire [3:0] S_skin_norm_mask = {F_skin_norm_px(S_d1_3, S_d2_3, S_gray3),
                                   F_skin_norm_px(S_d1_2, S_d2_2, S_gray2),
                                   F_skin_norm_px(S_d1_1, S_d2_1, S_gray1),
                                   F_skin_norm_px(S_d1_0, S_d2_0, S_gray0)};

    wire [3:0] S_skin2_mask = {F_skin2_px(S_raw_pix3[23:16], S_raw_pix3[15:8], S_raw_pix3[7:0], S_gray3),
                               F_skin2_px(S_raw_pix2[23:16], S_raw_pix2[15:8], S_raw_pix2[7:0], S_gray2),
                               F_skin2_px(S_raw_pix1[23:16], S_raw_pix1[15:8], S_raw_pix1[7:0], S_gray1),
                               F_skin2_px(S_raw_pix0[23:16], S_raw_pix0[15:8], S_raw_pix0[7:0], S_gray0)};

    // 最终使用的肤色掩码（编译期常量选择，没选中的判据会被综合裁掉）
    wire [3:0] S_skin_use = (SKIN_RULE2 != 0) ? S_skin2_mask :
                            ((SKIN_NORM != 0)  ? S_skin_norm_mask : S_skin_mask);

    // ========================================================================
    // M1 Step 2：背景帧（80x45 灰度）+ 运动掩码 → 融合掩码 = 肤色 ∩ 运动
    //
    // 为什么要背景差分而不是帧间差分：帧间差分只能发现"这一帧和上一帧不一样"，
    // 手停住就不动了；背景差分是"和背景不一样"，静止的手照样是前景。前提是背景
    // 更新必须带 quiet 门控（见下），否则静止的手会慢慢被吸进背景。
    //
    // 几何：块 = 16x16 像素，80x45 = 3600 块，每块 1 字节灰度参考值。
    //   块列 = x[10:4] = 行内字号 >> 2（一拍 4 像素不跨 16 像素边界），
    //   块行 = y[9:4]，地址 = 块行*80 + 块列（80 = 64+16，纯移位加法）；
    //   → 每块每行只读一次背景，同一块内 4 拍的像素共用这个值。
    //
    // 采样（背景更新的依据）：块内第 BG_SAMPLE_ROW 行的**前 8 个像素**的均值
    //   （2 拍 × 4 像素，>>3）。在 phase==1 算完、phase==2 写回。不用整块 256 像素
    //   均值的原因：那要么给 80 个块各配一个 12 位部分和（≈960 FF），要么再开一块
    //   ERAM 当暂存；而背景值只是"参考"，8 像素均值已经能压掉单像素噪声。
    //
    // ERAM 读写时序（eram_spram = 单口 + 1 拍读延迟，同一拍不能既读又写）：
    //   phase 0/1：地址 = 本块，读（phase==0 直接用读出的数据，phase 1~3 用寄存副本）
    //   phase 2  ：地址 = 本块，we = 更新决策（这一拍是"只写"）
    //   phase 3  ：地址 = **下一块**（地址预取），读 → 数据正好在下一块 phase==0 有效
    //   所以 4 拍里读/写各占各的槽，既没有冲突也不需要场消隐期的额外地址生成器。
    //   行尾（块列 79）的下一块是本块行第 0 列（下一行的同一个块行），地址要回卷。
    //
    // 背景更新（quiet 门控 + 限速蠕变，规划 §3 M1）：
    //   * |样本 − 背景| < QUIET_TH 才允许动（QUIET_TH < MOTION_TH 形成滞回）；
    //   * 每块每 64 帧最多动 1 个 LSB（"帧计数低位 == 块地址低位"挑帧，3600 块里
    //     每帧约 56 块有更新机会）；60 fps 下等效时间常数几十秒；
    //   * 复位后前 BOOT_FRAMES 帧例外：每块无条件装载样本值（自举），否则背景全是
    //     0，运动掩码恒 1、融合退化成纯肤色。**开机时画面里别放手**。
    //
    // 延迟：0 拍（背景值在每块第一拍就已经拿到，与像素同拍比较）。跨域：不跨。
    //       SDC：不需要额外约束（ERAM 与像素流同一时钟域）。
    // 资源：2 块 ERAM + ≈60 FF + ≈150~250 LUT6，0 DSP。
    // ========================================================================
    wire [3:0] S_motion_mask;

    // 当前像素所在块的背景灰度（g_motion 里赋值；调试图与 DIAG_CHROMA 统计共用）
    wire [7:0] S_bg_cur;

    generate
    if (MASK_SRC == 2 && (SKIN_ONLY == 0)) begin : g_motion

        // 行内字号 S_x_grp / 行号 S_y_pos 现在在模块顶部统一维护（ROI/准星也要用）
        wire [1:0] S_phase = S_x_grp[1:0];          // 块内第几拍（0..3）
        wire [6:0] S_blk_x = S_x_grp[6:2];          // 行内块列 0..79
        wire [5:0] S_band  = S_y_pos[9:4];          // 块行 0..44
        // 采样拍：BG_SAMPLE2=1 时用第二个采样行（两个采样行都采齐了 S_sample 才有效）
        wire       S_smp_beat_a = (S_y_pos[3:0] == BG_SAMPLE_ROW)  && (S_phase == 2'd1);
        wire       S_smp_beat_b = (S_y_pos[3:0] == BG_SAMPLE_ROW2) && (S_phase == 2'd1);
        wire       S_sample_row = (BG_SAMPLE2 != 0) ? S_smp_beat_b : S_smp_beat_a;

        wire [11:0] S_row_base  = {S_band, 6'b0} + {S_band, 4'b0};   // 块行*80
        wire [11:0] S_addr_cur  = S_row_base + {{5{1'b0}}, S_blk_x};
        // 预取地址 = **扫描顺序的下一个块**（不是"本行首块"）。原来的写法在每块行最后一个块上
        // 回卷到本行首块，于是"每块行的第一个块（图像最左 16 像素）"用的是上一行首块的背景
        // → 最左边一条 16 像素宽的永久竖线（很可能就是用户 2026-09-25 看到的"两条竖线"里的一条）。
        wire [11:0] S_addr_next = (S_addr_cur == 12'd3599) ? 12'd0 : (S_addr_cur + 12'd1);

        // ---- 背景帧存储：2 块 ERAM（各 2048x8，够放 3600 个块）------------------
        // 单口 + 1 拍读延迟：地址在上一块 phase==3 发出（预取）→ 本块 phase==0 有效。
        // 地址 bit11 选片子；读出数据的片选要用**上一拍**的地址位，所以打一拍。
        wire [11:0] S_bg_addr;
        wire        S_bg_we;
        wire [7:0]  S_bg_wdata;
        reg  [11:0] S_bg_addr_d1;
        wire [7:0]  S_bg_q0, S_bg_q1;
        wire [7:0]  S_bg_rdata = S_bg_addr_d1[11] ? S_bg_q1 : S_bg_q0;

        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n) S_bg_addr_d1 <= 12'd0;
            else         S_bg_addr_d1 <= S_bg_addr;
        end

        eram_spram #(.DATA_WIDTH(8), .ADDR_WIDTH(11)) u_bg_mem0 (
            .I_clk  (I_clk),
            .I_we   (S_bg_we & ~S_bg_addr[11]),
            .I_addr (S_bg_addr[10:0]),
            .I_wdata(S_bg_wdata),
            .O_rdata(S_bg_q0)
        );

        eram_spram #(.DATA_WIDTH(8), .ADDR_WIDTH(11)) u_bg_mem1 (
            .I_clk  (I_clk),
            .I_we   (S_bg_we &  S_bg_addr[11]),
            .I_addr (S_bg_addr[10:0]),
            .I_wdata(S_bg_wdata),
            .O_rdata(S_bg_q1)
        );

        // ---- 帧计数：只用来"挑帧"（每块每 64 帧一次更新机会）-------------------
        // 8 位帧号：低 2 位当"每 4 帧"节拍，整字节还当锁存时间戳用。
        reg [7:0] S_frame_cnt;
        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n)         S_frame_cnt <= 8'd0;
            else if(I_raw_tuser) S_frame_cnt <= S_frame_cnt + 8'd1;
        end
        wire S_boot = (S_frame_cnt < BOOT_FRAMES);
        // ---- 一键重新基线化：提交字 bit[19:16]（teach_cnt）一变就再自举一次 ----------
        // M1 还没有"示教"功能，先借用这个事件做"背景重建"（等效于重开机那 32 帧）。
        // 现场长按 KEY4 就会发 teach 请求 → 背景重建，可用来验证"是不是背景错了"。
        reg [5:0] S_reboot;
        reg [3:0] S_teach_seen;
        wire      S_teach_evt = (S_mode_word[19:16] != S_teach_seen);
        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n) begin
                S_reboot     <= 6'd0;
                S_teach_seen <= 4'd0;
            end
            else if(I_raw_tuser) begin
                if((REBASE_ON_TEACH != 0) && S_teach_evt) begin
                    S_reboot     <= BOOT_FRAMES;
                    S_teach_seen <= S_mode_word[19:16];
                end
                else if(S_reboot != 6'd0) begin
                    S_reboot <= S_reboot - 6'd1;
                end
            end
        end
        wire S_boot_eff = S_boot || (S_reboot != 6'd0);

        // 自举完成标志：自举期内（含"重建背景"窗口）锁存一律算"没动过"。
        reg S_bg_ready;
        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n)         S_bg_ready <= 1'b0;
            else if(I_raw_tuser) S_bg_ready <= ~S_boot_eff;
        end

        // ---- 采样：本块采样行的前 8 像素均值（BG_SAMPLE2=1 时取两个采样行 = 16 像素）----
        // 为什么加密：一个 16x16 块只采 8 个像素 = 块面积的 3%。灯斑/反光在块内本来就不均匀，
        // 块背景取不到亮处 → 亮的那部分**永久**和"块背景"差十几二十，一直判成"在动"。
        // 两个采样行 = 16 像素（6.25%）。成本 8 FF + 约 20 LUT。
        wire [9:0] S_sum4 = {2'b0, S_gray0} + {2'b0, S_gray1} +
                            {2'b0, S_gray2} + {2'b0, S_gray3};
        reg [9:0] S_row_acc;
        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n)          S_row_acc <= 10'd0;
            else if(I_raw_tvalid) S_row_acc <= (S_phase == 2'd0) ? S_sum4
                                                                 : (S_row_acc + S_sum4);
        end
        // phase==1 时 S_row_acc 已经是第 0 拍的和，加上当拍就是 8 像素和 → >>3 取均值
        wire [10:0] S_sum8    = {1'b0, S_row_acc} + {1'b0, S_sum4};
        wire [7:0]  S_smp_now = S_sum8[10:3];

        // 第一个采样行的均值先存下来，等第二个采样行到了再一起平均
        reg [7:0] S_smp_a;
        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n)                          S_smp_a <= 8'd0;
            else if(I_raw_tvalid && S_smp_beat_a) S_smp_a <= S_smp_now;
        end
        wire [8:0] S_smp_2  = {1'b0, S_smp_a} + {1'b0, S_smp_now};      // 两行均值之和 <= 510
        wire [7:0] S_sample = (BG_SAMPLE2 != 0) ? S_smp_2[8:1] : S_smp_now;

        // ---- 背景读数据：phase==0 用直通（预取刚回来），其余用寄存副本 ----------
        reg [7:0] S_bg_reg;
        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n) S_bg_reg <= 8'd0;
            // phase==3 那拍数据来自"phase==2 的写访问"，对单口 RAM 没有意义，不能收
            else if(I_raw_tvalid && (S_phase != 2'd3)) S_bg_reg <= S_bg_rdata;
        end
        wire [7:0] S_bg_use = (S_phase == 2'd0) ? S_bg_rdata : S_bg_reg;
        assign S_bg_cur = S_bg_use;     // 调试图出口

        // ---- 打磨③：帧粗均值 → 全局漂移检测（GLB_COMP=1 时生效）--------------
        // Σgray 用 28 位：921600 × 253 = 2.33e8 < 2^28 ✓。粗均值取 Σ>>20（≈真实均值
        // ×0.879，做相对比较够用，省掉除法器）。
        // 资源：≈28 FF + ≈80 LUT，0 ERAM / 0 DSP；GLB_COMP=0 时整段被综合裁掉。
        wire [9:0] S_beat_sum = {2'b0, S_gray0} + {2'b0, S_gray1} +
                                {2'b0, S_gray2} + {2'b0, S_gray3};
        reg  [27:0] a_gsum;
        reg  [7:0]  S_mean_ref;
        reg  signed [8:0] S_glb_delta;
        reg         S_glb_upd;

        // 刚结束这一帧的粗均值与基准之差（9 位有符号：−255..255）
        wire signed [8:0] S_mean_last = {1'b0, a_gsum[27:20]} - {1'b0, S_mean_ref};
        wire S_glb_need = (GLB_COMP != 0) &&
                          ((S_mean_last > GLOBAL_TH) || (S_mean_last < -GLOBAL_TH));

        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n) begin
                a_gsum      <= 28'd0;
                S_mean_ref  <= 8'd0;
                S_glb_delta <= 9'sd0;
                S_glb_upd   <= 1'b0;
            end
            else if(I_raw_tuser) begin
                S_glb_delta <= S_mean_last;      // 下一帧按这个差值整体平移
                S_glb_upd   <= S_glb_need;
                if(S_glb_need) S_mean_ref <= a_gsum[27:20];
                a_gsum      <= 28'd0;
            end
            else if(I_raw_tvalid) begin
                a_gsum <= a_gsum + {18'b0, S_beat_sum};
            end
        end

        // 整块平移：bg + delta，钳到 0..255（用 10 位补码位型相加，避开混合符号的坑）
        function [7:0] F_shift8;
            input [7:0] I_bg;
            input signed [8:0] I_d;
            reg [9:0] S_t;
            begin
                S_t = {2'b0, I_bg} + {I_d[8], I_d};
                F_shift8 = (S_t[9:8] == 2'b00)  ? S_t[7:0] :      // 0..255 正常
                           (S_t[9]    ? 8'd0 : 8'd255);           // 负数→0，>255→255
            end
        endfunction

        // ---- 更新决策：自举装载 / 全局平移 / 自愈趋近 / (旧) quiet 蠕变 -----------
        // **2026-09-26 第二步的核心**：旧的 quiet 门是个**单向棘轮** —— 只有 |diff| < QUIET_TH(4)
        // 的块才允许蠕变，误差 >=4 的块永远冻结；而出错的恰恰是这些块。于是光照一变，亮区残差
        // 就永久留着（"灯照亮的桌面一直高亮"的直接原因）。自愈把这条棘轮拆掉。
        // 锁存模式必须让背景 = "上一帧的采样"（否则算出来的不是帧差）
        wire S_fd = (LATCH_MODE != 0) || (FRAME_DIFF != 0);
        wire signed [8:0] S_bg_diff  = {1'b0, S_sample} - {1'b0, S_bg_use};
        wire [8:0]        S_abs_diff = S_bg_diff[8] ? (~S_bg_diff + 9'd1) : S_bg_diff;
        wire S_quiet = (S_bg_diff > -QUIET_TH) && (S_bg_diff < QUIET_TH);

        // "轮到这一块"的自查：自愈模式每 16 帧一次机会（旧行为每 64 帧）
        wire [5:0] S_turn_sel = (BG_HEAL != 0) ? {2'b0, S_frame_cnt[3:0]} : S_frame_cnt;
        wire       S_turn     = (S_turn_sel == S_addr_cur[5:0]);

        // 自愈步长：|diff|>>3，钳在 1..8（BG_HEAL=0 时恒为 1，就是旧的 ±1 蠕变）
        wire [4:0] S_step_raw = S_abs_diff[7:3];
        wire [3:0] S_step     = (BG_HEAL == 0) ? 4'd1
                              : ((S_step_raw == 5'd0) ? 4'd1
                                                      : ((S_step_raw > 5'd8) ? 4'd8
                                                                             : S_step_raw[3:0]));
        wire S_heal_ok = (S_abs_diff <= HEAL_MAX) && (S_abs_diff != 9'd0);

        wire S_upd   = (S_phase == 2'd1) && S_sample_row &&
                       ((S_fd ? 1'b1 :
                        (S_boot_eff ? 1'b1 :
                         (S_glb_upd  ? 1'b1 :
                          ((BG_HEAL != 0) ? (S_turn && S_heal_ok)
                                          : (S_turn && S_quiet && (S_bg_diff != 9'sd0)))))));

        wire [8:0] S_bg_p = {1'b0, S_bg_use} + {5'b0, S_step};
        wire [8:0] S_bg_m = {1'b0, S_bg_use} - {5'b0, S_step};
        wire [7:0] S_up_v = (S_bg_p > 9'd255) ? 8'd255 : S_bg_p[7:0];
        wire [7:0] S_dn_v = S_bg_m[8] ? 8'd0 : S_bg_m[7:0];
        wire [7:0] S_new = (S_fd || S_boot_eff) ? S_sample
                         : S_glb_upd ? F_shift8(S_bg_use, S_glb_delta)
                                     : (S_bg_diff[8] ? S_dn_v : S_up_v);

        // 决策在 phase==1 产生、写发生在 phase==2，所以打一拍
        reg       S_upd_d1;
        reg [7:0] S_new_d1;
        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n) begin
                S_upd_d1 <= 1'b0;
                S_new_d1 <= 8'd0;
            end
            else begin
                S_upd_d1 <= S_upd;
                S_new_d1 <= S_new;
            end
        end

        assign S_bg_addr  = (S_phase == 2'd3) ? S_addr_next : S_addr_cur;
        assign S_bg_we    = (S_phase == 2'd2) && S_upd_d1;
        assign S_bg_wdata = S_new_d1;

        // ---- 运动门：两套实现（LATCH_MODE 选）-----------------------------------
        // LATCH_MODE=0：旧的"逐像素和背景比"（保留做 A/B）。
        // LATCH_MODE=1：**帧差做活动检测 + 块级锁存**（默认，见下面的说明与参数）。
        wire signed [8:0] S_m0 = {1'b0, S_gray0} - {1'b0, S_bg_use};
        wire signed [8:0] S_m1 = {1'b0, S_gray1} - {1'b0, S_bg_use};
        wire signed [8:0] S_m2 = {1'b0, S_gray2} - {1'b0, S_bg_use};
        wire signed [8:0] S_m3 = {1'b0, S_gray3} - {1'b0, S_bg_use};

        function F_motion_lv1;
            input signed [8:0] I_d;
            input [7:0]        I_bg;
            reg   signed [8:0] S_a;
            begin
                S_a = I_d[8] ? (~I_d + 9'd1) : I_d;                  // |d|
                F_motion_lv1 = (S_a > MOTION_TH) &&
                               ((MOTION_REL == 0) || ({S_a, 3'b0} > {1'b0, I_bg}));
            end
        endfunction

        // ======================================================================
        // 块级"活动锁存"：3600 块 x 4 bit = 1800 B → **1 块 2048x8 ERAM**
        //   * 活动判据：这一块的采样均值相对**上一帧**变过门限（帧差 → 静态场景结构上就是 0）
        //   * 计数：动过置 LATCH_MAX，之后每 4 帧减 1（15 -> 约 1.0 s，手停住还兜得住）
        //   * 读：与背景 RAM 同一套预取（上一块 phase==3 发地址 → 本块 phase 0 有效），
        //         两块共用一个字节；写发生在 phase==2（地址=当前块，预取地址=下一块，不撞）。
        // ======================================================================
        wire [11:0] S_lat_blk  = (S_phase == 2'd3) ? S_addr_next : S_addr_cur;
        wire [10:0] S_lat_addr = S_lat_blk[11:1];
        wire [7:0]  S_lat_rdata;
        wire [3:0]  S_lat_old  = S_addr_cur[0] ? S_lat_rdata[7:4] : S_lat_rdata[3:0];
        assign S_lat_on = (LATCH_MODE != 0) && S_bg_ready && (S_lat_old != 4'd0);

        // 活动：本块采样均值相对上一帧的变化（LATCH_MODE=1 时背景就是上一帧的采样）
        wire signed [8:0] S_act_d   = {1'b0, S_sample} - {1'b0, S_bg_use};
        wire [8:0]        S_act_abs = S_act_d[8] ? (~S_act_d + 9'd1) : S_act_d;
        wire S_act_now = (S_act_abs > MOTION_TH) &&
                         ((MOTION_REL == 0) || ({S_act_abs, 3'b0} > {1'b0, S_bg_use}));
        wire S_act     = S_sample_row && S_act_now;      // 决策在采样那一拍
        reg  S_act_d1;
        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n) S_act_d1 <= 1'b0;
            else         S_act_d1 <= S_act;              // 写发生在下一拍（phase==2）
        end

        wire       S_lat_tick = (S_frame_cnt[1:0] == 2'd0);           // 每 4 帧一次
        wire [3:0] S_lat_dec  = (S_lat_old == 4'd0) ? 4'd0 : (S_lat_old - 4'd1);
        wire [3:0] S_lat_newv = S_boot_eff ? 4'd0
                              : (S_act_d1 ? LATCH_MAX
                                          : (S_lat_tick ? S_lat_dec : S_lat_old));
        wire       S_lat_chg   = (S_lat_newv != S_lat_old);
        wire [7:0] S_lat_wdata = S_addr_cur[0] ? {S_lat_newv, S_lat_rdata[3:0]}
                                               : {S_lat_rdata[7:4], S_lat_newv};
        wire       S_lat_we    = (S_phase == 2'd2) && S_lat_chg;

        eram_spram #(.DATA_WIDTH(8), .ADDR_WIDTH(11)) u_lat_mem (
            .I_clk  (I_clk),
            .I_we   (S_lat_we),
            .I_addr (S_lat_addr),
            .I_wdata(S_lat_wdata),
            .O_rdata(S_lat_rdata)
        );

        // bit0 = 字内最左像素，与肤色掩码同一 bit 序（否则融合会错位）
        // 预设 8/9（S_skin_only）：运动门**恒开** → 融合掩码退化成"只看肤色"。
        // 这一档专门回答："把运动门拿掉，灯照亮的桌面到底会不会被当成手。"
        assign S_motion_mask = S_skin_only ? 4'b1111 :
                               ((LATCH_MODE != 0) ? {4{S_lat_on}}
                                                  : { F_motion_lv1(S_m3, S_bg_use),
                                                      F_motion_lv1(S_m2, S_bg_use),
                                                      F_motion_lv1(S_m1, S_bg_use),
                                                      F_motion_lv1(S_m0, S_bg_use) });

    end
    else begin : g_nomotion
        // 不建运动支路时（MASK_SRC = 0/1）：融合掩码退化成肤色掩码，且 0 资源开销
        assign S_motion_mask = 4'b1111;
        assign S_bg_cur      = 8'd0;
        assign S_lat_on      = 1'b0;
    end
    endgenerate

    wire [3:0] S_fusion_mask = S_skin_use & S_motion_mask;
    // 块级"最近动过"（活动锁存）：g_motion 里给，g_nomotion（MASK_SRC=0/1）恒 0。
    // 声明放在模块级，因为 g_cent（软权重）要读它，而它与 g_motion 是两个 generate 分支。
    wire       S_lat_on;

    // ---- 掩码源选择（编译期常量 → 综合后没有 mux，也没有多余负载）------------
    wire [3:0] S_mask_sel = (MASK_SRC == 2) ? S_fusion_mask :
                            (MASK_SRC == 1) ? S_skin_mask   : S_edge_mask;

    // ---- mask_stats 的输出（Step 3 要用"上一帧"的包围盒/计数，先声明）---------
    wire [19:0] S_mcnt;
    wire [10:0] S_xmin, S_xmax, S_ymin, S_ymax;
    wire [30:0] S_sumx;
    wire [29:0] S_sumy;
    wire        S_empty;

    // ---- 质心（M1 收尾）-----------------------------------------------------
    // 由下面的 g_cent 产生：S_cent_x/S_cent_y = 上一帧掩码质心（列/行），
    // S_cent_valid = 这一帧质心可信。MASK_SRC=0（边缘自检回归）或 USE_CENTROID=0
    // 时走 g_cent_off，直接给常量 → 除法器整段不综合。
    wire [10:0] S_cent_x;
    wire [9:0]  S_cent_y;
    wire        S_cent_valid;
    wire [20:0] S_wsum_h;     // 上一帧 Σ权重（SOFT_TRACK=1 时用它判"命中"）
    // ROI 窗口边界（g_track 里维护，导出来给软权重"只在窗口内投票"用）
    wire [10:0] S_roi_x0_w, S_roi_x1_w;
    wire [9:0]  S_roi_y0_w, S_roi_y1_w;

    // ========================================================================
    // M1 收尾：质心 = Σ列 / Σ行 ÷ 掩码像素数（每帧一次串行除法）
    //
    // 为什么串行除法：A 线 DSP 配额是 0，组合除法器又会吃掉一整条关键路径；质心每帧
    // 只要一个值（60 Hz），27 拍 ≈ 0.46 µs @59 MHz，帧内绰绰有余。
    //
    // 被除数 = mask_stats 的 Σ列 / Σ行（各 >>4），除数 = 掩码像素数（>>4）：两边同移
    // 4 位商不变，除数缩到 16 位、迭代位也少 4 个。恢复余数法：R = R<<1 | A[i]，
    // R ≥ B 就减 B 并把该商位置 1。商寄存器只有 11/10 位——商一定 < 2048 (列) /
    // < 1024 (行)，27 次移入后高位的零自然移出，留下的就是有效商。
    //
    // **相位对齐（关键）**：除法启动在 tuser 的**下一拍**——tuser 当拍 mask_stats 刚
    // 把上一帧的 Σ 锁存进输出寄存器；跟踪器在下一次 tuser 读到的仍是这批 Σ 与包围盒，
    // 所以质心与包围盒来自**同一帧**，不引入额外滞后。（观测整体滞后 1~2 帧是
    // mask_stats"帧首锁存 + 帧首读取"的固有相位，两条路一致。）
    //
    // 几何修正：mask_stats 的列号按边缘流几何（列 4k−1..4k+2）算，而我们喂进去的是
    // RAW 几何（4k..4k+3）→ 算出来的列号比真实像素列小 1，所以结果 +1。
    //
    // 资源：≈70 LUT6 + ≈130 FF，0 ERAM / 0 DSP。
    // 注意：**不能**把 generate 嵌在 g_track 里（TD 报 "Verilog 2000 keyword
    // 'generate' used in incorrect context"），所以这一段放在模块级。
    // ========================================================================
    generate
    if ((MASK_SRC != 0) && (USE_CENTROID != 0)) begin : g_cent

        reg [10:0] S_cx_hold;      // 上一帧质心列（已做 +1 几何修正并钳范围）
        reg [9:0]  S_cy_hold;      // 上一帧质心行
        reg        S_cv_valid;     // 上一帧质心可信（像素数 ≥ MIN_CNT）

        reg        S_div_start;    // tuser 后一拍的单拍启动
        reg        S_div_run;
        reg [4:0]  S_div_i;        // 剩余迭代数（27 → 1）
        reg [26:0] S_div_ax;       // 被除数：Σ列 >>4
        reg [25:0] S_div_ay;       // 被除数：Σ行 >>4
        reg [15:0] S_div_b;        // 除数：掩码像素数 >>4（两轴共用）
        reg [15:0] S_div_rx, S_div_ry;   // 余数（恒 < B，16 位够）
        reg [10:0] S_div_qx;       // 商：列 0..1279
        reg [9:0]  S_div_qy;       // 商：行 0..719

        // 取被除数最高位、余数左移一位后与除数比较
        wire [16:0] S_rx_sh = {S_div_rx[15:0], S_div_ax[26]};
        wire [16:0] S_ry_sh = {S_div_ry[15:0], S_div_ay[25]};
        wire        S_rx_ge = (S_rx_sh >= {1'b0, S_div_b});
        wire        S_ry_ge = (S_ry_sh >= {1'b0, S_div_b});
        // 商的"本拍结束值"：最后一次迭代也要算进去（否则丢最低位）
        wire [10:0] S_qx_now = {S_div_qx[9:0], S_rx_ge};
        wire [9:0]  S_qy_now = {S_div_qy[8:0], S_ry_ge};

        // ---- 软权重：每像素 w = min(皮肤分 0..2, 运动分 0..2) -------------------
        // 皮肤分：暖色占优(R>G 且 R>B) 1 分 + 饱和度(max−min ≥ SAT_MIN) 1 分
        // 运动分：|本帧灰度 − 上一帧灰度| > MOTION_TH 1 分、> 2× 2 分；权重取两者的小者
        wire signed [8:0] S_th  = MOTION_TH;
        wire signed [8:0] S_th2 = MOTION_TH + MOTION_TH;

        function [1:0] F_w_rgb;
            input [7:0] I_r, I_g, I_b, I_gray;
            input       I_lat;            // 这一块"最近动过"（块级锁存）
            input       I_in_rect;        // 该像素在肤色矩形内（与掩码同一判据，调用侧传 S_skin_mask[i]）
            reg [7:0] S_hi, S_lo;
            reg [1:0] S_sk, S_mo;
            reg signed [8:0] S_d, S_da;
            begin
                S_hi = (I_r > I_g) ? ((I_r > I_b) ? I_r : I_b) : ((I_g > I_b) ? I_g : I_b);
                S_lo = (I_r < I_g) ? ((I_r < I_b) ? I_r : I_b) : ((I_g < I_b) ? I_g : I_b);
                // **2026-09-27：准星与掩码同源** —— 先过"肤色矩形"（与掩码同一个 F_skin_px，
                // 受档位 8/9/10/11/12 的 d2 窗口控制）；不在矩形内一律 0 分。
                // 原来只判"暖色占优 + 饱和"：桌面又暖又饱和但色度不在矩形内，照样拿满分，
                // 于是档 8 下准星被桌面拽走。加这道门，档 10/11/12 才量得到"准星有没有
                // 不再被桌面拽"，而不只是"掩码亮不亮"。
                S_sk = I_in_rect ? ({1'b0, ((I_r > I_g) && (I_r > I_b))} +
                                    {1'b0, ((S_hi - S_lo) >= SAT_MIN)}) : 2'd0;
                if(S_skin_only) begin
                    // 预设 8..12：运动分恒满 → 权重 = 肤色分（完全不要运动门）
                    S_mo = 2'd2;
                end
                else if(LATCH_MODE != 0) begin
                    // 锁存模式：运动分不再由"和背景比"给 —— 这一块最近动过就算"在动"，
                    // 权重仍然取 min(肤色, 运动) → 手整体高亮，静止场景权重为 0。
                    S_mo = I_lat ? 2'd2 : 2'd0;
                end
                else begin
                    S_d  = {1'b0, I_gray} - {1'b0, S_bg_cur};
                    S_da = S_d[8] ? (~S_d + 9'd1) : S_d;
                    if((S_da > S_th2) && ((MOTION_REL == 0) || ({S_da, 2'b0} > {1'b0, S_bg_cur})))
                        S_mo = 2'd2;
                    else if((S_da > S_th) && ((MOTION_REL == 0) || ({S_da, 3'b0} > {1'b0, S_bg_cur})))
                        S_mo = 2'd1;
                    else
                        S_mo = 2'd0;
                end
                F_w_rgb = (S_sk < S_mo) ? S_sk : S_mo;
            end
        endfunction

        wire [10:0] S_wc0 = {S_x_grp, 2'b00};
        wire [10:0] S_wc1 = S_wc0 + 11'd1;
        wire [10:0] S_wc2 = S_wc0 + 11'd2;
        wire [10:0] S_wc3 = S_wc0 + 11'd3;
        // **只在 ROI 窗口内投票**：否则画面里别处的"肤色+运动"（手臂/脸）会把质心拽到
        // 中间，表现就是"掩码看着干净、准星却跟不上手"。
        function F_w_inroi;
            input [10:0] I_x;
            input [9:0]  I_y;
            begin
                F_w_inroi = (I_x >= S_roi_x0_w) && (I_x <= S_roi_x1_w) &&
                            (I_y >= S_roi_y0_w) && (I_y <= S_roi_y1_w);
            end
        endfunction

        // ★ 2026-10-11（用户指出）：软权重（质心/准星的观测源）**必须与掩码同源** —— 原来这里喂的是
        //   `S_skin_mask`（老绝对窗），归一化打开后两条路判据不同：桌面可能不再被涂红、却仍把**准星**
        //   拽过去（M1 踩过同一个坑，结论就是"准星与掩码同源"）。改成 `S_skin_use` 即可。
        wire [1:0]  S_w0 = F_w_inroi(S_wc0, S_y_pos)
                           ? F_w_rgb(S_raw_pix0[23:16], S_raw_pix0[15:8], S_raw_pix0[7:0], S_gray0, S_lat_on, S_skin_use[0]) : 2'd0;
        wire [1:0]  S_w1 = F_w_inroi(S_wc1, S_y_pos)
                           ? F_w_rgb(S_raw_pix1[23:16], S_raw_pix1[15:8], S_raw_pix1[7:0], S_gray1, S_lat_on, S_skin_use[1]) : 2'd0;
        wire [1:0]  S_w2 = F_w_inroi(S_wc2, S_y_pos)
                           ? F_w_rgb(S_raw_pix2[23:16], S_raw_pix2[15:8], S_raw_pix2[7:0], S_gray2, S_lat_on, S_skin_use[2]) : 2'd0;
        wire [1:0]  S_w3 = F_w_inroi(S_wc3, S_y_pos)
                           ? F_w_rgb(S_raw_pix3[23:16], S_raw_pix3[15:8], S_raw_pix3[7:0], S_gray3, S_lat_on, S_skin_use[3]) : 2'd0;

        // w∈0..2：w·x = (w[0] ? x : 0) + (w[1] ? x<<1 : 0) —— 移位加法，不碰 DSP
        wire [11:0] S_wx0 = (S_w0[0] ? {1'b0,S_wc0} : 12'd0) + (S_w0[1] ? {S_wc0,1'b0} : 12'd0);
        wire [11:0] S_wx1 = (S_w1[0] ? {1'b0,S_wc1} : 12'd0) + (S_w1[1] ? {S_wc1,1'b0} : 12'd0);
        wire [11:0] S_wx2 = (S_w2[0] ? {1'b0,S_wc2} : 12'd0) + (S_w2[1] ? {S_wc2,1'b0} : 12'd0);
        wire [11:0] S_wx3 = (S_w3[0] ? {1'b0,S_wc3} : 12'd0) + (S_w3[1] ? {S_wc3,1'b0} : 12'd0);
        wire [10:0] S_wy0 = (S_w0[0] ? {1'b0,S_y_pos} : 11'd0) + (S_w0[1] ? {S_y_pos,1'b0} : 11'd0);
        wire [10:0] S_wy1 = (S_w1[0] ? {1'b0,S_y_pos} : 11'd0) + (S_w1[1] ? {S_y_pos,1'b0} : 11'd0);
        wire [10:0] S_wy2 = (S_w2[0] ? {1'b0,S_y_pos} : 11'd0) + (S_w2[1] ? {S_y_pos,1'b0} : 11'd0);
        wire [10:0] S_wy3 = (S_w3[0] ? {1'b0,S_y_pos} : 11'd0) + (S_w3[1] ? {S_y_pos,1'b0} : 11'd0);

        wire [13:0] S_wx_beat = S_wx0 + S_wx1 + S_wx2 + S_wx3;
        wire [12:0] S_wy_beat = S_wy0 + S_wy1 + S_wy2 + S_wy3;
        wire [3:0]  S_ws_beat = {2'b0,S_w0} + {2'b0,S_w1} + {2'b0,S_w2} + {2'b0,S_w3};

        reg [31:0] a_wx;   // Σ(w·列)：≤ 2×1279×921600 = 2.36e9 < 2^32
        reg [30:0] a_wy;   // Σ(w·行)：≤ 2×719×921600  = 1.33e9 < 2^31
        reg [20:0] a_ws;   // Σw：≤ 2×921600 = 1.84e6
        reg [31:0] h_wx;
        reg [30:0] h_wy;
        reg [20:0] h_ws;

        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n) begin
                a_wx <= 32'd0; a_wy <= 31'd0; a_ws <= 21'd0;
                h_wx <= 32'd0; h_wy <= 31'd0; h_ws <= 21'd0;
            end
            else if(I_raw_tuser) begin
                h_wx <= a_wx; h_wy <= a_wy; h_ws <= a_ws;
                a_wx <= 32'd0; a_wy <= 31'd0; a_ws <= 21'd0;
            end
            else if(I_raw_tvalid) begin
                a_wx <= a_wx + {18'b0, S_wx_beat};
                a_wy <= a_wy + {18'b0, S_wy_beat};
                a_ws <= a_ws + {17'b0, S_ws_beat};
            end
        end

        // 加权和 / 权重统一 >>5，正好落在既有"27 位被除数 / 16 位除数"口径上
        wire [26:0] S_dxa = (SOFT_TRACK != 0) ? h_wx[31:5] : S_sumx[30:4];
        wire [25:0] S_dya = (SOFT_TRACK != 0) ? h_wy[30:5] : S_sumy[29:4];
        wire [15:0] S_db  = (SOFT_TRACK != 0) ? h_ws[20:5] : S_mcnt[19:4];
        wire        S_dok = (SOFT_TRACK != 0) ? ((h_ws >= MIN_WSUM) && (h_ws[20:5] != 16'd0))
                                              : ((S_mcnt >= MIN_CNT) && (S_mcnt[19:4] != 16'd0));
        wire [11:0] S_cor = (SOFT_TRACK != 0) ? 12'd0 : 12'd1;   // 几何修正只给"硬门"那条

        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n) begin
                S_cx_hold   <= 11'd0;
                S_cy_hold   <= 10'd0;
                S_cv_valid  <= 1'b0;
                S_div_start <= 1'b0;
                S_div_run   <= 1'b0;
                S_div_i     <= 5'd0;
                S_div_ax    <= 27'd0;
                S_div_ay    <= 26'd0;
                S_div_b     <= 16'd0;
                S_div_rx    <= 16'd0;
                S_div_ry    <= 16'd0;
                S_div_qx    <= 11'd0;
                S_div_qy    <= 10'd0;
            end
            else begin
                S_div_start <= I_raw_tuser;

                if(S_div_start) begin
                    // 抓这一帧（mask_stats 刚锁存的 Σ / 像素数）
                    S_div_ax   <= S_dxa;
                    S_div_ay   <= S_dya;
                    S_div_b    <= S_db;
                    S_div_rx   <= 16'd0;
                    S_div_ry   <= 16'd0;
                    S_div_qx   <= 11'd0;
                    S_div_qy   <= 10'd0;
                    S_div_i    <= 5'd27;
                    // 像素数不够 / 除数被截成 0（<16 像素）时不算：本帧标记不可信，
                    // 跟踪器自动退回"包围盒中心"。
                    S_div_run  <= S_dok;
                    S_cv_valid <= 1'b0;
                end
                else if(S_div_run) begin
                    S_div_ax <= {S_div_ax[25:0], 1'b0};
                    S_div_ay <= {S_div_ay[24:0], 1'b0};
                    S_div_rx <= S_rx_ge ? (S_rx_sh[15:0] - S_div_b) : S_rx_sh[15:0];
                    S_div_ry <= S_ry_ge ? (S_ry_sh[15:0] - S_div_b) : S_ry_sh[15:0];
                    S_div_qx <= S_qx_now;
                    S_div_qy <= S_qy_now;
                    if(S_div_i == 5'd1) begin
                        S_div_run  <= 1'b0;
                        // +1 = 上面说的几何修正；再钳一次范围防越界
                        S_cx_hold  <= (({1'b0, S_qx_now} + S_cor) > 12'd1279)
                                          ? 11'd1279 : ({1'b0, S_qx_now} + S_cor);
                        S_cy_hold  <= (S_qy_now > 10'd719) ? 10'd719 : S_qy_now;
                        S_cv_valid <= S_div_run;   // 本次运行有效
                    end
                    S_div_i <= S_div_i - 5'd1;
                end
            end
        end

        assign S_cent_x     = S_cx_hold;
        assign S_cent_y     = S_cy_hold;
        assign S_cent_valid = S_cv_valid;
        assign S_wsum_h     = h_ws;

    end
    else begin : g_cent_off
        assign S_cent_x     = 11'd0;
        assign S_cent_y     = 10'd0;
        assign S_cent_valid = 1'b0;
        assign S_wsum_h     = 21'd0;
    end
    endgenerate

    // ========================================================================
    // M2.1（2026-10-11）：挥手方向 —— 左挥 / 右挥 / 下劈
    //
    // 观测源：x 用 M1 的**质心**（S_cent_x），y 用 M1 的**掩码最高行**（S_ymin，11 位全精度，
    //   mask_stats 现成输出）。都是每帧一个值、帧首锁存，不新增像素级统计。
    //   相位：质心除法器在帧首后 27 拍出结果并保持整帧 → tuser 那一拍读到的是上一帧质心；
    //   y_min 由 mask_stats 在 tuser 那一拍锁存 → 该拍读到的是再上一帧的 y_min（比质心晚一拍）。
    //   所以下面用"cx1/cx2 两级 + ym1 一级"的采样前沿，把两条路**对齐到同一对帧 (k−1,k−2)**。
    //
    // 算法（只有减法/比较，无乘法、无除法、无加法树 → DSP 增量 0）：
    //   1) 每帧位移：dx = 质心列差、dy = **掩码最高行差**（不是质心 y！见下方"为什么换 y"）。
    //   2) **动作段状态机**（这一条是 2026-10-11 用户实测反馈后加的）：
    //        已武装 → 某帧 |位移| > GEST_START_TH = 动作开始（记起点 cx1/ymin）→ 动作中；
    //        动作中 → 连续 GEST_QUIET_FRAMES 帧安静（|位移| ≤ GEST_QUIET_TH）= 动作结束；
    //                 或到 GEST_SEG_MAX 帧强制结算（防场景一直动）。
    //        → **一个动作只结算一次**，所以不会再出现"一个动作连出三条颜色"。
    //   3) 结算时按**整段净位移**（终点 − 起点）一次性定性，余量写死：
    //        左挥 / 右挥：|ΔX| > GEST_X_TH 且 |ΔX| > 2·|ΔY|；
    //        下劈（向下）：ΔY > GEST_Y_TH 且 |ΔX| < GEST_Y_XMAX（横向几乎没动）。
    //      两条都不满足但整段位移大于 GEST_NOISE_TH → 闪**青色**（"看到动作、方向够不上"），
    //      小于噪声就完全不闪（掩码抖两下不算动作）。
    //
    // 为什么把下劈的 y 从"质心"换成"掩码最高行"（2026-10-11）：质心是**面积中心**，横向挥手
    //   时手臂进/出 ROI、掩码形状一变它就上下漂；横挥到两端一减速，|Δy| 常常大于 |Δx|，
    //   于是误报下劈（上板实测"横挥出蓝条"）。手往下劈时**最高行**明显下移、横向挥手时它基本
    //   不动 —— 这才是"手在哪儿"的干净信号（M1 老参数 TRACK_Y_FROM_TOP 就是拿它贴指尖的）。
    //
    // 方向编码 S_gest_dir：0 = 无事件，1 = 左挥，2 = 右挥，3 = 下劈，4 = 动作结束但方向不明确。
    //   左右按**图像坐标**（x 增大 = 右）；显示器若相对真实场景是镜像的，GEST_FLIP_X=1 对调即可。
    //
    // GEST_DBG=1 时把 DBG 的 P/Q/R 三个字段借来观测（M1 的原始含义见 CHANGELOG）：
    //   P = {整段 ΔX 8 位, 整段 ΔY 8 位}  钳 ±127 后 +128（0x80 = 0；动作中看它定标门限）
    //   Q = {方向[2:0], 事件计数[10:0]}  读成 0x0DCC：D = 方向、CC = 事件数（饱和/不清零）
    //   R = {每帧 dx 6 位, 每帧 dy 6 位}  钳 ±31 后 +32（0x20 = 0；已锁存，逐帧可信）
    // 交付口径（GEST_DBG=0）下 P/Q/R 一个字节都不变，仍是 M1 的掩码像素数与包围盒。
    //
    // 资源：2 个 12 位减法 ×2（帧间 + 整段）+ 绝对值/比较 + 采样寄存器 + 段状态机，
    //   ≈150~180 LUT6 + ≈90 FF，0 ERAM / 0 DSP（上板实测数字见 CHANGELOG）。
    // ========================================================================
    wire        S_gest_left, S_gest_right, S_gest_down;   // 单帧事件脉冲
    wire [2:0]  S_gest_dir;      // 最近一次结算的方向：1=左 2=右 3=下 4=方向不明确（0=还没有过）
    wire [10:0] S_gest_cnt;      // 事件总数（饱和，不清零）
    wire signed [11:0] S_gest_sx;    // 动作中：整段 ΔX（定标用；空闲恒 0）
    wire signed [11:0] S_gest_sy;    // 动作中：整段 ΔY（定标用；空闲恒 0）
    wire signed [11:0] S_gest_dx;    // 每帧 dx（已锁存，不可信帧记 0）
    wire signed [11:0] S_gest_dy;    // 每帧 dy（用掩码最高行算）
    wire        S_gest_flash;   // 挥手事件后 ~0.4 s 高（并进 isp_top 的叠加使能）
    wire [2:0]  S_gest_vis;     // 闪条色码：0=不闪、3=左(红)、4=右(绿)、6=下(蓝)

    generate
    if ((GEST_EN != 0) && (MASK_SRC != 0) && (USE_CENTROID != 0)) begin : g_gest

        // ---- 帧间量（2026-10-11 修正）：x 用质心，y 用**掩码最高行 y_min** -----------
        // y_min = 掩码最上面一行（≈指尖/手顶）：手往下劈时它明显下移，横向挥手时基本不动。
        // 上一版拿**质心 y** 判下劈 —— 质心是"面积中心"，横向挥手时手臂进/出 ROI、掩码形状
        // 一变它就上下漂；横挥到两端一减速，|Δy| 常常大于 |Δx|，于是误报下劈（用户实测的
        // "横挥出蓝条"）。S_ymin 是 mask_stats 现成的 11 位全精度输出（M1 的 TRACK_Y_FROM_TOP
        // 就是拿它当"贴指尖"用的），换它几乎不花资源。
        // 相位对齐：y_min 在 tuser 那一拍锁存，所以该拍**读到**的是再上一帧的值（比质心晚一
        // 拍）；这里用"上一拍采样的 y_min"与"再上一拍"作差，正好和质心的 (k−1,k−2) 帧对严格
        // 对齐（质心要 cx1/cx2 两级，y_min 只要一级）。
        reg [10:0] S_gcx1, S_gcx2;   // 质心列（前 1 / 前 2 拍采样）
        reg [10:0] S_gym1;           // y_min（前 1 拍采样）
        reg        S_gv1, S_gv2;     // 前 1 / 前 2 拍采样时"掩码可信"（= 上一帧有手）
        wire S_gok = S_cent_valid && S_gv1 && S_gv2;

        wire signed [11:0] S_gfx = S_gok ? ({1'b0, S_gcx1} - {1'b0, S_gcx2}) : 12'sd0;
        wire signed [11:0] S_gfy = S_gok ? ({1'b0, S_ymin} - {1'b0, S_gym1}) : 12'sd0;
        wire [11:0] S_gax = S_gfx[11] ? (~S_gfx + 12'd1) : S_gfx;   // |每帧 dx|
        wire [11:0] S_gay = S_gfy[11] ? (~S_gfy + 12'd1) : S_gfy;   // |每帧 dy(手顶)|

        // ---- 相对动作起点的位移（整段峰值口径，见下面"为什么不用终点"）------------
        wire signed [11:0] S_gex  = {1'b0, S_gcx1} - {1'b0, S_gx0};   // 横向偏离起点（带符号）
        wire signed [11:0] S_gey  = {1'b0, S_ymin} - {1'b0, S_gy0};   // 纵向偏离起点（+ = 向下）
        wire [11:0] S_gaex = S_gex[11] ? (~S_gex + 12'd1) : S_gex;    // |横向偏离|
        wire [11:0] S_gaey = S_gey[11] ? (~S_gey + 12'd1) : S_gey;    // |纵向偏离|

        // 整段峰值：横向最大幅度（带符号定左右）、纵向最大幅度、**向下**最大幅度
        reg signed [11:0] S_gxpk;
        reg [11:0]        S_gaxm, S_gaym, S_gdym;

        // ---- 动作段状态机（一个动作只结算一次 → 直接消灭"三色连出"）----------------
        //   已武装 → 每帧 |位移| > START_TH = 动作开始（记起点）→ 动作中
        //   动作中 → 连续 QUIET_FRAMES 帧安静 = 动作结束 → **按整段净位移一次性定性**
        //            （或 SEG_MAX 帧到点强制结算，防场景一直动）
        reg        S_gact;           // 0 = 已武装（等动作）/ 1 = 动作中
        reg [10:0] S_gx0, S_gy0;     // 动作起点（口径与帧对一致：cx1 / ymin）
        reg [3:0]  S_gqc;            // 连续安静帧数
        reg [7:0]  S_glen;           // 本段已持续帧数（超时保护）
        reg [7:0]  S_gflash;         // 提示条倒计时
        reg [2:0]  S_gdir;           // 1=左 2=右 3=下 4=动作结束但方向不明确
        reg [10:0] S_gcnt;           // 事件计数（只数真事件）

        wire S_gmove = S_gok && ((S_gax > GEST_START_TH) || (S_gay > GEST_START_TH));
        wire S_gstop = !S_gok || ((S_gax <= GEST_QUIET_TH) && (S_gay <= GEST_QUIET_TH));
        wire S_gend  = S_gact && ((S_gstop && (S_gqc >= GEST_QUIET_FRAMES)) ||
                                  (S_glen >= GEST_SEG_MAX));

        // ---- 判据：全部用**整段峰值**，余量写死（不再"大一点就算"）------------------
        // 为什么不用"终点 − 起点"：人的"挥一下"常常是**来回摆**（挥出去再收回来），终点≈
        //   起点 → ΔX≈0，剩下的纵向分量（手臂摆动 + 掩码最高行被 ROI 重裁）就把动作判成
        //   下劈 —— 这就是上板实测"横挥出蓝条"的根因。峰值口径下左挥的横向峰值是几百像素，
        //   "下劈要求横向峰值 < GEST_Y_XMAX"结构上不可能成立（判据互斥，不是调门限）。
        wire S_ghx = (S_gaxm > GEST_X_TH) && ({1'b0, S_gaxm} > {1'b0, S_gaym, 1'b0});
        wire S_ghy = (S_gdym > GEST_Y_TH) && (S_gaxm < GEST_Y_XMAX);
        // "看到了动作但够不上任何一条"：只有整段幅度明显大于噪声才打青色提示，
        // 否则掩码抖两下也会算一段、没完没了地闪
        wire S_gbig  = (S_gaxm > GEST_NOISE_TH) || (S_gaym > GEST_NOISE_TH);
        wire S_ghevt = S_gend && (S_ghx || S_ghy);              // 真事件（红/绿/蓝）
        wire S_ghunk = S_gend && !S_ghx && !S_ghy && S_gbig;    // 方向不明确（青）
        // 右 = 横向峰值朝正（图像坐标）；GEST_FLIP_X=1 时对调
        wire S_gright = (GEST_FLIP_X != 0) ? ~S_gxpk[11] : S_gxpk[11];

        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n) begin
                S_gcx1 <= 11'd0; S_gcx2 <= 11'd0; S_gym1 <= 11'd0;
                S_gv1  <= 1'b0;  S_gv2  <= 1'b0;
                S_gact <= 1'b0;  S_gx0 <= 11'd0;  S_gy0 <= 11'd0;
                S_gqc  <= 4'd0;  S_glen <= 8'd0;
                S_gxpk <= 12'sd0; S_gaxm <= 12'd0; S_gaym <= 12'd0; S_gdym <= 12'd0;
                S_gdir <= 3'd0;  S_gcnt <= 11'd0; S_gflash <= 8'd0;
            end
            else if(I_raw_tuser) begin
                if(S_gflash != 8'd0) S_gflash <= S_gflash - 8'd1;

                // 整段峰值更新（动作中每帧都算，含结算那一拍，这样最后一帧不丢）
                if(S_gact) begin
                    if(S_gaex > S_gaxm) begin S_gaxm <= S_gaex; S_gxpk <= S_gex; end
                    if(S_gaey > S_gaym) S_gaym <= S_gaey;
                    if((S_gey[11] == 1'b0) && (S_gey > {1'b0, S_gdym})) S_gdym <= S_gey[11:0];
                end

                if(S_gend) begin
                    // 动作结束：一次性定性 + 出提示条（一个动作只出一次）
                    if(S_ghevt) begin
                        S_gdir   <= S_ghx ? (S_gright ? 3'd2 : 3'd1) : 3'd3;
                        S_gcnt   <= (S_gcnt == 11'h7FF) ? 11'h7FF : (S_gcnt + 11'd1);
                        S_gflash <= GEST_FLASH_FRAMES;
                    end
                    else if(S_ghunk) begin
                        S_gdir   <= 3'd4;                     // 青色：动作看到了、方向够不上
                        S_gflash <= GEST_FLASH_FRAMES >> 1;   // 短一半，和真事件区分
                    end
                    S_gact <= 1'b0;
                end
                else if(!S_gact) begin
                    if(S_gmove) begin
                        S_gact <= 1'b1;
                        // 起点 = 检测到动作那一步的**后**一个采样 → "掩码突变一格"不算整段位移
                        S_gx0  <= S_gcx1;
                        S_gy0  <= S_ymin;
                        S_gqc  <= 4'd0;
                        S_glen <= 8'd0;
                        S_gxpk <= 12'sd0;   // 峰值从起点重新开始
                        S_gaxm <= 12'd0;    // （这三个同时是"上一段"的定标读数，见 DBG P）
                        S_gaym <= 12'd0;
                        S_gdym <= 12'd0;
                    end
                end
                else begin
                    S_glen <= (S_glen == 8'hFF) ? 8'hFF : (S_glen + 8'd1);
                    S_gqc  <= S_gstop ? ((S_gqc == 4'hF) ? 4'hF : (S_gqc + 4'd1))
                                      : 4'd0;
                end

                // 采样推进（放最后：上面用到的都是"上一拍采样值"）
                S_gcx2 <= S_gcx1;
                S_gcx1 <= S_cent_x;
                S_gym1 <= S_ymin;
                S_gv2  <= S_gv1;
                S_gv1  <= S_cent_valid;
            end
        end

        assign S_gest_left  = S_ghevt &  S_ghx & ~S_gright;
        assign S_gest_right = S_ghevt &  S_ghx &  S_gright;
        assign S_gest_down  = S_ghevt & ~S_ghx;
        assign S_gest_dir   = S_gdir;
        assign S_gest_cnt   = S_gcnt;
        // DBG P：**上一段的整段峰值幅度**（横向 / 向下），一直留到下一段开始 —— 所以
        // 挥完之后再读日志就能看到"这一挥到底走了多少像素"，用来定门限（不用盯着实时值）。
        assign S_gest_sx    = S_gaxm;
        assign S_gest_sy    = S_gdym;
        assign S_gest_dx    = S_gfx;                     // DBG R：每帧 dx / dy（手顶）
        assign S_gest_dy    = S_gfy;
        // 挥手提示：方向 → 颜色（左红 3 / 右绿 4 / 下蓝 6 / 不明确青 7）；GEST_VIS=0 时恒 0
        assign S_gest_vis = ((GEST_VIS == 0) || (S_gflash == 8'd0)) ? 3'd0 :
                            ((S_gdir == 3'd1) ? 3'd3 :
                            ((S_gdir == 3'd2) ? 3'd4 :
                            ((S_gdir == 3'd3) ? 3'd6 : 3'd7)));
        assign S_gest_flash = (GEST_VIS != 0) && (S_gflash != 8'd0);

    end
    else begin : g_gest_off
        // GEST_EN=0 / MASK_SRC=0 / USE_CENTROID=0：一段都不综合
        assign S_gest_left  = 1'b0;
        assign S_gest_right = 1'b0;
        assign S_gest_down  = 1'b0;
        assign S_gest_dir   = 3'd0;
        assign S_gest_cnt   = 11'd0;
        assign S_gest_sx    = 12'sd0;
        assign S_gest_sy    = 12'sd0;
        assign S_gest_dx    = 12'sd0;
        assign S_gest_dy    = 12'sd0;
        assign S_gest_flash = 1'b0;
        assign S_gest_vis   = 3'd0;
    end
    endgenerate

    assign O_gest_flash = S_gest_flash;

    // ---- 诊断：帧内 (d1,d2) 极值（DIAG_CHROMA=1 时 Q/R 上报它，不再报包围盒）----
    // 帧内全部像素一起取极值（不做门控），用来量出手的真实色度范围：
    //   手伸进画面读一行 DBG，手拿开再读一行，两组 Q/R 一减就知道手落在哪。
    wire [15:0] S_ch_word_x;      // {d1_min+128, d1_max+128}
    wire [15:0] S_ch_word_y;      // {d2_min+128, d2_max+128}
    wire [15:0] S_ch_mot;         // 运动像素数 >>4（DIAG_CHROMA=1 时喂给 DBG 的 P）

    generate
    if (DIAG_CHROMA != 0) begin : g_chroma
        // ---- 帧平均 R/G/B（Σ>>20 ≈ 真实均值×0.879；921600 像素，省掉除法器）----
        wire [9:0] S_sum_r_beat = {2'b0, S_raw_pix0[23:16]} + {2'b0, S_raw_pix1[23:16]} +
                                  {2'b0, S_raw_pix2[23:16]} + {2'b0, S_raw_pix3[23:16]};
        wire [9:0] S_sum_g_beat = {2'b0, S_raw_pix0[15:8]} + {2'b0, S_raw_pix1[15:8]} +
                                  {2'b0, S_raw_pix2[15:8]} + {2'b0, S_raw_pix3[15:8]};
        wire [9:0] S_sum_b_beat = {2'b0, S_raw_pix0[7:0]} + {2'b0, S_raw_pix1[7:0]} +
                                  {2'b0, S_raw_pix2[7:0]} + {2'b0, S_raw_pix3[7:0]};
        reg [27:0] a_sr, a_sg, a_sb;
        reg [7:0]  h_r, h_g, h_b;

        // ---- d2 = R−Y 的帧极值（换算肤色阈值用）------------------------------
        wire signed [8:0] S_n01 = (S_d2_0 < S_d2_1) ? S_d2_0 : S_d2_1;
        wire signed [8:0] S_n23 = (S_d2_2 < S_d2_3) ? S_d2_2 : S_d2_3;
        wire signed [8:0] S_b_d2min = (S_n01 < S_n23) ? S_n01 : S_n23;
        wire signed [8:0] S_p01 = (S_d2_0 > S_d2_1) ? S_d2_0 : S_d2_1;
        wire signed [8:0] S_p23 = (S_d2_2 > S_d2_3) ? S_d2_2 : S_d2_3;
        wire signed [8:0] S_b_d2max = (S_p01 > S_p23) ? S_p01 : S_p23;

        reg signed [8:0] a_d2min, a_d2max;
        reg [7:0] h_d2m, h_d2M;

        function [7:0] F_bias;
            input signed [8:0] I_v;
            reg signed [9:0] S_t;
            begin
                S_t = I_v + 10'sd128;
                F_bias = (S_t < 10'sd0) ? 8'd0 : ((S_t > 10'sd255) ? 8'd255 : S_t[7:0]);
            end
        endfunction

        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n) begin
                a_sr <= 28'd0; a_sg <= 28'd0; a_sb <= 28'd0;
                h_r  <= 8'd0;  h_g  <= 8'd0;  h_b  <= 8'd0;
                a_d2min <=  9'sd127; a_d2max <= -9'sd128;
                h_d2m <= 8'd0; h_d2M <= 8'd0;
            end
            else if(I_raw_tuser) begin
                h_r  <= a_sr[27:20]; h_g <= a_sg[27:20]; h_b <= a_sb[27:20];
                h_d2m <= F_bias(a_d2min); h_d2M <= F_bias(a_d2max);
                a_sr <= 28'd0; a_sg <= 28'd0; a_sb <= 28'd0;
                a_d2min <=  9'sd127; a_d2max <= -9'sd128;
            end
            else if(I_raw_tvalid) begin
                a_sr <= a_sr + {18'b0, S_sum_r_beat};
                a_sg <= a_sg + {18'b0, S_sum_g_beat};
                a_sb <= a_sb + {18'b0, S_sum_b_beat};
                if(S_b_d2min < a_d2min) a_d2min <= S_b_d2min;
                if(S_b_d2max > a_d2max) a_d2max <= S_b_d2max;
            end
        end

        assign S_ch_word_x = {h_b, 8'h00};      // Q = {平均B, 00}
        assign S_ch_word_y = {h_d2m, h_d2M};    // R = {d2_min+128, d2_max+128}
        assign S_ch_mot    = {h_r, h_g};        // P = {平均R, 平均G}
    end
    else begin : g_chroma_off
        assign S_ch_word_x = 16'd0;
        assign S_ch_word_y = 16'd0;
        assign S_ch_mot    = 16'd0;
    end
    endgenerate
    // ========================================================================
    // M1 Step 3：ROI 门控 + α-β 平滑 + 丢失保持 / 重锁
    //
    // 目标：把"每帧一张掩码"变成"一个稳定的准星"。
    //   * ROI 门控：锁定后只在上一帧包围盒 ±ROI_MARGIN 的窗口内统计（窗口外的干扰
    //     被物理隔离）；丢了又没锁定时回到全帧重搜。
    //   * α-β 滤波：位置一阶修正 α=1/2^ALPHA_SHIFT，速度项 β=1/2^BETA_SHIFT，
    //     跟手平滑不抖；全部用移位实现，**不做除法**。
    //   * 丢失保持：打不中就按速度外推，连续 HOLD_FRAMES 帧打不中才判丢失；
    //     重新看到目标要连续 LOCK_FRAMES 帧命中才重新锁定（防抖）。
    // 全部在相机帧首更新一次（60 Hz），CSI 域、不跨域。
    // 资源：≈120~180 LUT6 + ≈90 FF，0 ERAM / 0 DSP。
    // ========================================================================
    wire [3:0]  S_mask_gated;
    wire [10:0] S_trk_x;
    wire [9:0]  S_trk_y;
    wire        S_trk_locked;
    wire [11:0] S_ovl_sel;
    // M2.2：指尖/手型（g_track 里产生；给叠加画点 + DBG 借用，见参数 M2_*）
    wire [15:0] S_m2_dbg_p;      // {峰数[3:0], 2'b0, 指尖行[9:0]}
    wire [13:0] S_m2_dbg_q;      // {手型[2:0], 指尖列[10:0]}
    wire        S_m2_dbg_on;

    generate
    if (MASK_SRC != 0) begin : g_track

        // 像素列：一拍 4 像素，bit0 对应最左像素 → 列 = 4*x_grp + j
        wire [10:0] S_col0 = {S_x_grp, 2'b00};
        wire [10:0] S_col1 = S_col0 + 11'd1;
        wire [10:0] S_col2 = S_col0 + 11'd2;
        wire [10:0] S_col3 = S_col0 + 11'd3;

        reg [10:0] S_roi_x0, S_roi_x1;
        reg [9:0]  S_roi_y0, S_roi_y1;

        function F_in_roi;
            input [10:0] I_x;
            input [9:0]  I_y;
            begin
                F_in_roi = (I_x >= S_roi_x0) && (I_x <= S_roi_x1) &&
                           (I_y >= S_roi_y0) && (I_y <= S_roi_y1);
            end
        endfunction

        // ---- 形态学去噪 ①a：水平 3 点开运算（腐蚀→膨胀）-----------------------
        // 开运算 = 先腐蚀再膨胀：先去掉孤立/毛刺像素，再把目标尺寸恢复回来。
        // 只用同一个 96 位字里的水平邻居（j-1 / j / j+1），所以**不引入任何拍延迟**、
        // 不破坏与像素和坐标的对齐、也不占 ERAM；列首/列尾没有外侧邻居时用自身近似。
        // 代价：宽度 ≤2 像素的细窄结构会被抹掉（对手部掩膜是有益的去噪）。
        wire [3:0] S_m_erode, S_m_open;
        assign S_m_erode[0] = S_mask_sel[0] &  S_mask_sel[1];
        assign S_m_erode[1] = S_mask_sel[1] &  S_mask_sel[0] & S_mask_sel[2];
        assign S_m_erode[2] = S_mask_sel[2] &  S_mask_sel[1] & S_mask_sel[3];
        assign S_m_erode[3] = S_mask_sel[3] &  S_mask_sel[2];
        assign S_m_open[0]  = S_m_erode[0]  |  S_m_erode[1];
        assign S_m_open[1]  = S_m_erode[1]  |  S_m_erode[0] | S_m_erode[2];
        assign S_m_open[2]  = S_m_erode[2]  |  S_m_erode[1] | S_m_erode[3];
        assign S_m_open[3]  = S_m_erode[3]  |  S_m_erode[2];

        // 注意：喂给 mask_stats 的掩码在下面"打磨①"那一段里给（跟踪态要读 S_locked，
        // 所以那一段放在帧首状态机之后）。

        // ---- 帧首：命中/丢失计数、锁定状态机、α-β、ROI 窗口 ------------------
        reg               S_locked;
        reg [3:0]         S_hit_cnt, S_miss_cnt;
        reg signed [12:0] S_pos_x, S_pos_y;
        reg signed [12:0] S_vel_x, S_vel_y;

        // ---- 观测值：质心（默认）或上一帧包围盒中心（A/B 回退）-----------------
        // 位宽提醒：S_xmin/S_xmax 各 11 位，直接相加会按 11 位回绕（目标到画面右侧
        // 就算错中心），所以先扩宽再 >>1；y 同理（10 → 11 位）。
        wire [11:0] S_bx_sum = {1'b0, S_xmin} + {1'b0, S_xmax};
        wire [10:0] S_by_sum = {1'b0, S_ymin} + {1'b0, S_ymax};
        wire [10:0] S_obs_x_raw = S_bx_sum[11:1];   // 包围盒中心（列）
        // 纵向回退路径：TRACK_Y_FROM_TOP=1 时取包围盒上缘（旧的"贴指尖"近似）
        wire [9:0]  S_obs_y_raw = TRACK_Y_FROM_TOP ? S_ymin[9:0] : S_by_sum[10:1];
        // 质心由模块级 generate 块 g_cent / g_cent_off 产生（见下面"质心 ÷ 像素数"
        // 那一段）；质心不可信（像素数不够 / USE_CENTROID=0）时退回包围盒中心。
        // S1：观测源统一 —— 始终用**质心**（质心无效时保持上一帧有效值，不再跳去包围盒中心）
        wire [10:0] S_obs_x = S_cent_x;
        wire [9:0]  S_obs_y = S_cent_y;
        // 目标门控：像素数够 + 包围盒够大 + 不细长（挡掉唇膏/笔/碎噪声这类非手目标）
        wire [10:0] S_w     = S_xmax - S_xmin;
        wire [10:0] S_h     = S_ymax - S_ymin;
        // 命中判定：软权重模式下只看 Σw（尺寸门/细长比已实测无用，整段删掉）。
        // ---- S2：跟踪柔和档（档 9 切换，方便同板 A/B）--------------------------
        //   α = 1/2^S_ashift、β = 1/2^S_bshift、死区 = S_db
        //   档 9 = 柔和（α=1/4, β=1/16, 死区 5）；其余 = 原参数（α=1/2, β=1/8, 死区 2）
        wire [2:0]        S_ashift = (S_cfg == 4'd9) ? 3'd2 : 3'd1;
        wire [2:0]        S_bshift = (S_cfg == 4'd9) ? 3'd4 : 3'd3;
        wire signed [12:0] S_db    = (S_cfg == 4'd9) ? 13'sd5 : 13'sd2;
        // ---- S3：命中滞回（进入 2000 / 锁定后保持 1200）-----------------------

        // ---- M2.2：最大尺寸门 + 形状门（2026-10-11 用户提议；治"桌面自锁 + 把准星拽走"）----
        // 桌面误检的判据分开不了（d2/Y 只差 0.05），但形状差得远：又大又扁就不是手。
        // 命中不了 → 不更新位置、丢锁；叠加里也不涂红（见 F_ovl_view 的 S_gate_bad）。
        wire [10:0] S_gate_w = S_xmax - S_xmin;
        wire [10:0] S_gate_h = S_ymax - S_ymin;
        wire        S_gate_bad = (GATE_EN != 0) &&
                                 ((S_mcnt > MAX_MASK_PX) ||                       // ① 太大
                                  (S_gate_w > (S_gate_h << GATE_AR_SHIFT)) ||    // ② 又宽又扁（桌子）
                                  (S_gate_h > (S_gate_w << GATE_AR_SHIFT)));     // ③ 又高又窄
        wire        S_hit   = ((SOFT_TRACK != 0)
                            ? ((S_wsum_h >= MIN_WSUM) ||
                               (S_locked && (S_wsum_h >= MIN_WSUM_HOLD)))
                                                : (S_mcnt >= MIN_CNT)) && !S_gate_bad;

        // 观测误差 + 死区：|err| ≤ DEADBAND 时按 0 处理（噪声抖动不再推动准星）
        wire signed [12:0] S_err_raw_x = {2'b0, S_obs_x} - S_pos_x;
        wire signed [12:0] S_err_raw_y = {2'b0, S_obs_y} - S_pos_y;
        wire [12:0] S_aerr_x = S_err_raw_x[12] ? (~S_err_raw_x + 13'd1) : S_err_raw_x;
        wire [12:0] S_aerr_y = S_err_raw_y[12] ? (~S_err_raw_y + 13'd1) : S_err_raw_y;
        wire signed [12:0] S_err_x = (S_aerr_x > S_db) ? S_err_raw_x : 13'sd0;
        wire signed [12:0] S_err_y = (S_aerr_y > S_db) ? S_err_raw_y : 13'sd0;
        wire signed [12:0] S_pos_nx = S_pos_x + (S_err_x >>> S_ashift) + S_vel_x;
        wire signed [12:0] S_pos_ny = S_pos_y + (S_err_y >>> S_ashift) + S_vel_y;
        wire signed [12:0] S_vel_nx = S_vel_x + (S_err_x >>> S_bshift);
        wire signed [12:0] S_vel_ny = S_vel_y + (S_err_y >>> S_bshift);
        wire signed [12:0] S_pos_hx = S_pos_x + S_vel_x;   // 丢失时按速度外推
        wire signed [12:0] S_pos_hy = S_pos_y + S_vel_y;

        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n) begin
                S_roi_x0 <= 11'd0;    S_roi_x1 <= 11'd1279;
                S_roi_y0 <= 10'd0;    S_roi_y1 <= 10'd719;
                S_locked <= 1'b0;     S_hit_cnt <= 4'd0;  S_miss_cnt <= 4'd0;
                S_pos_x  <= 13'sd640; S_pos_y  <= 13'sd360;
                S_vel_x  <= 13'sd0;   S_vel_y  <= 13'sd0;
            end
            else if(I_raw_tuser) begin
                // (1) 命中/丢失计数与锁定状态
                if(S_hit) begin
                    S_miss_cnt <= 4'd0;
                    S_hit_cnt  <= (S_hit_cnt == 4'hF) ? 4'hF : (S_hit_cnt + 4'd1);
                    if(!S_locked && (S_hit_cnt >= LOCK_FRAMES)) S_locked <= 1'b1;
                end
                else begin
                    S_hit_cnt  <= 4'd0;
                    S_miss_cnt <= (S_miss_cnt == 4'hF) ? 4'hF : (S_miss_cnt + 4'd1);
                    if(S_locked && (S_miss_cnt >= HOLD_FRAMES)) S_locked <= 1'b0;
                end

                // (2) α-β 滤波：命中→按观测修正；**丢失→冻结**（不再按速度外推：
                //     噪声会让速度非零，外推会把准星自己推走 —— 用户看到的"静止时乱动"）
                if(S_hit) begin
                    S_pos_x <= S_pos_nx;
                    S_pos_y <= S_pos_ny;
                    S_vel_x <= S_vel_nx;
                    S_vel_y <= S_vel_ny;
                end
                else begin
                    S_vel_x <= 13'sd0;      // 丢失即清速度，避免残留速度继续推
                    S_vel_y <= 13'sd0;
                end

                // (3) ROI 窗口：命中→按新包围盒外扩；丢失且未锁定→回全帧重搜
                if(S_hit) begin
                    S_roi_x0 <= (S_xmin > ROI_MARGIN) ? (S_xmin - ROI_MARGIN) : 11'd0;
                    S_roi_x1 <= (S_xmax > (11'd1279 - ROI_MARGIN)) ? 11'd1279
                                                                  : (S_xmax + ROI_MARGIN);
                    S_roi_y0 <= (S_ymin > ROI_MARGIN) ? (S_ymin[9:0] - ROI_MARGIN[9:0]) : 10'd0;
                    S_roi_y1 <= (S_ymax > (10'd719 - ROI_MARGIN[9:0])) ? 10'd719
                                                                       : (S_ymax + ROI_MARGIN[9:0]);
                end
                else if(!S_locked) begin
                    S_roi_x0 <= 11'd0;    S_roi_x1 <= 11'd1279;
                    S_roi_y0 <= 10'd0;    S_roi_y1 <= 10'd719;
                end
            end
        end

        // ---- 打磨①：锁定态"核心区内只认肤色"（FUSE_CORE_SKIN=1 时才综合）------
        // 核心区 = 上一帧包围盒 ± CORE_MARGIN。位宽：x 用 11/12 位（xmax+CORE 最大
        // 1327 < 4096）、y 用 10/11 位（ymax+CORE 最大 767 < 2048），都不会回绕。
        wire [10:0] S_core_xl = (S_xmin > CORE_MARGIN) ? (S_xmin - CORE_MARGIN) : 11'd0;
        wire [11:0] S_core_xh = {1'b0, S_xmax} + {1'b0, CORE_MARGIN};
        wire [9:0]  S_core_yl = (S_ymin > CORE_MARGIN) ? (S_ymin[9:0] - CORE_MARGIN[9:0])
                                                       : 10'd0;
        wire [10:0] S_core_yh = {1'b0, S_ymax} + {1'b0, CORE_MARGIN[9:0]};

        function F_in_core_x;          // 列判据；行对所有像素一样，下面判一次即可
            input [10:0] I_x;
            begin
                F_in_core_x = (I_x >= S_core_xl) && ({1'b0, I_x} <= S_core_xh);
            end
        endfunction

        wire S_core_y = (S_y_pos >= S_core_yl) && ({1'b0, S_y_pos} <= S_core_yh);
        wire [3:0] S_in_core = { S_core_y && F_in_core_x(S_col3),
                                 S_core_y && F_in_core_x(S_col2),
                                 S_core_y && F_in_core_x(S_col1),
                                 S_core_y && F_in_core_x(S_col0) };

        // 肤色单独做一次同样的水平 3 点开运算（跟踪态用；没人消费时会被综合裁掉）
        wire [3:0] S_s_erode, S_s_open;
        assign S_s_erode[0] = S_skin_use[0] &  S_skin_use[1];
        assign S_s_erode[1] = S_skin_use[1] &  S_skin_use[0] & S_skin_use[2];
        assign S_s_erode[2] = S_skin_use[2] &  S_skin_use[1] & S_skin_use[3];
        assign S_s_erode[3] = S_skin_use[3] &  S_skin_use[2];
        assign S_s_open[0]  = S_s_erode[0]  |  S_s_erode[1];
        assign S_s_open[1]  = S_s_erode[1]  |  S_s_erode[0] | S_s_erode[2];
        assign S_s_open[2]  = S_s_erode[2]  |  S_s_erode[1] | S_s_erode[3];
        assign S_s_open[3]  = S_s_erode[3]  |  S_s_erode[2];

        // 运动掩码单独的开运算（跟手模式用；没人消费时会被综合裁掉）
        wire [3:0] S_o_erode, S_o_open;
        assign S_o_erode[0] = S_motion_mask[0] &  S_motion_mask[1];
        assign S_o_erode[1] = S_motion_mask[1] &  S_motion_mask[0] & S_motion_mask[2];
        assign S_o_erode[2] = S_motion_mask[2] &  S_motion_mask[1] & S_motion_mask[3];
        assign S_o_erode[3] = S_motion_mask[3] &  S_motion_mask[2];
        assign S_o_open[0]  = S_o_erode[0]  |  S_o_erode[1];
        assign S_o_open[1]  = S_o_erode[1]  |  S_o_erode[0] | S_o_erode[2];
        assign S_o_open[2]  = S_o_erode[2]  |  S_o_erode[1] | S_o_erode[3];
        assign S_o_open[3]  = S_o_erode[3]  |  S_o_erode[2];

        // 跟踪态掩码 = 原融合掩码 ∪（核心区内的肤色）；搜索态 / 关掉开关时就是原掩码
        wire [3:0] S_m_track = S_m_open | (S_s_open & S_in_core);
        // 跟手模式：搜索态只看运动（帧差）；锁定后并上核心区内的肤色（手停住也能兜住）
        wire [3:0] S_m_hand  = S_o_open | (S_s_open & S_in_core & {4{S_locked}});
        wire [3:0] S_m_pick  = (MASK_POLICY != 0) ? S_m_hand
                             : (((FUSE_CORE_SKIN != 0) && S_locked) ? S_m_track : S_m_open);

        // ---- 方案④：滑窗多数投票（8 像素窗，4 像素粒度）—— 抹掉桌面斑点 ----------------
        // 统计"这一拍 4 个 + 上一拍 4 个"里通过判据的个数：≥ VOTE_MIN 才保留这一拍，
        // 否则那一拍整组清零。桌面那种"几像素一团的斑点"过不了；手是连片的大块，照样过。
        reg [3:0] S_mv_h;          // 上一拍的同源掩码（4 像素）
        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n)                     S_mv_h <= 4'd0;
            else if(I_raw_tuser)             S_mv_h <= 4'd0;   // 帧首清零，不跨帧连
            else if(I_raw_tvalid)            S_mv_h <= S_m_pick;
        end
        wire [3:0] S_mv_cnt = {3'b0, S_m_pick[0]} + {3'b0, S_m_pick[1]} +
                              {3'b0, S_m_pick[2]} + {3'b0, S_m_pick[3]} +
                              {3'b0, S_mv_h[0]}   + {3'b0, S_mv_h[1]}   +
                              {3'b0, S_mv_h[2]}   + {3'b0, S_mv_h[3]};
        wire [3:0] S_m_pick_v = ((VOTE_EN != 0) && (S_mv_cnt < VOTE_MIN)) ? 4'd0 : S_m_pick;

        // 喂给 mask_stats 的就是这个"（选中的）开运算 + 多数投票 + ROI 门控"后的掩码
        assign S_mask_gated = S_m_pick_v &
                              { F_in_roi(S_col3, S_y_pos), F_in_roi(S_col2, S_y_pos),
                                F_in_roi(S_col1, S_y_pos), F_in_roi(S_col0, S_y_pos) };

        // ====================================================================
        // M2.2（2026-10-11）：指尖 + 手型（张开 / 握拳 / 未知）
        //   指尖 = **顶带里遇到的第一个掩码像素**（自顶向下、行内左→右扫）→ 锁存列/行；
        //   峰数 = 顶带内**逐行**数"进入掩码的连续段数"，取整帧最大 → 1 段 = 并指/握拳、
        //          ≥2 段 = 手指分开（张开）。逐行数**不需要任何轮廓存储** —— 规划里那块
        //          "1280 列（或 320 列）×10bit 轮廓记忆"ERAM 可以省掉。
        //   相位：扫描是"逐像素流水 + 帧首锁存"，叠加里画点用**上一帧**的指尖（h_m2_*），
        //         帧内稳定不抖；手型状态机用的是刚结束那一帧的整帧结果。
        //   滞回：连续 M2_LOCK_FRAMES 帧同类才改状态（照 M1 的 LOCK/HOLD 写法）。
        //   行边界：换行那一拍把"上一拍最右像素"作废，免得上一行右端和新行左端连起来
        //          多算一段（见 S_m2_prev_eff）。
        // 资源：≈100~120 LUT6 + ≈60 FF，0 ERAM / 0 DSP。
        // ====================================================================
        wire [10:0] S_m2_ylo = (S_ymin > {1'b0, M2_TOP_UP}) ? (S_ymin - {1'b0, M2_TOP_UP})
                                                             : 11'd0;
        wire [10:0] S_m2_yhi = S_ymin + {1'b0, M2_TOP_DN};
        wire       S_m2_band = ({1'b0, S_y_pos} >= S_m2_ylo) && ({1'b0, S_y_pos} <= S_m2_yhi);
        wire [3:0] S_m2_top  = S_mask_gated & {4{S_m2_band}};

        reg [10:0] a_m2_tx, a_m2_ty;    // 本帧指尖（列 / 行）
        reg        a_m2_got;            // 本帧找到指尖了吗
        reg [9:0]  a_m2_py;             // 上一拍的行（检测换行）
        reg        a_m2_prev;           // 上一拍最右像素在不在顶带
        reg [4:0]  a_m2_runs;           // 当前行的连续段数（饱和）
        reg [4:0]  a_m2_max;            // 本帧各行的最大段数
        reg [10:0] h_m2_tx, h_m2_ty;    // 上一帧结果（画点 / DBG 用）
        reg [4:0]  h_m2_max;
        reg [2:0]  S_m2_shape;          // 手型状态：0=未知 1=握拳 2=张开
        reg [3:0]  S_m2_agree;          // 连续同类帧数（滞回用）

        wire       S_m2_rownew   = (S_y_pos != a_m2_py);
        wire       S_m2_prev_eff = a_m2_prev & ~S_m2_rownew;   // 行边界当作"没在顶带"
        wire [3:0] S_m2_e;
        assign S_m2_e[0] = S_m2_top[0] & ~S_m2_prev_eff;
        assign S_m2_e[1] = S_m2_top[1] & ~S_m2_top[0];
        assign S_m2_e[2] = S_m2_top[2] & ~S_m2_top[1];
        assign S_m2_e[3] = S_m2_top[3] & ~S_m2_top[2];
        wire [2:0] S_m2_new    = {2'b0, S_m2_e[0]} + {2'b0, S_m2_e[1]} +
                                 {2'b0, S_m2_e[2]} + {2'b0, S_m2_e[3]};
        wire [4:0] S_m2_runs_n = (a_m2_runs > 5'd28) ? 5'd31 : (a_m2_runs + {2'b0, S_m2_new});
        // 手型原始类别（用刚结束那一帧的整帧结果）：0=未知 1=并指/握拳 2=张开
        wire [2:0] S_m2_raw = a_m2_got ? ((a_m2_max >= M2_OPEN_MIN) ? 3'd2 : 3'd1) : 3'd0;

        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n) begin
                a_m2_tx <= 11'd0; a_m2_ty <= 11'd0; a_m2_got <= 1'b0;
                a_m2_py <= 10'd0; a_m2_prev <= 1'b0;
                a_m2_runs <= 5'd0; a_m2_max <= 5'd0;
                h_m2_tx <= 11'd0; h_m2_ty <= 11'd0; h_m2_max <= 5'd0;
                S_m2_shape <= 3'd0; S_m2_agree <= 4'd0;
            end
            else if(I_raw_tuser) begin
                // 帧首：锁存这一帧的结果（画点/DBG 用），并清零累加器
                h_m2_tx  <= a_m2_tx;  h_m2_ty <= a_m2_ty;  h_m2_max <= a_m2_max;
                a_m2_tx  <= 11'd0;    a_m2_ty <= 11'd0;    a_m2_got <= 1'b0;
                a_m2_py  <= 10'd0;    a_m2_prev <= 1'b0;
                a_m2_runs <= 5'd0;    a_m2_max <= 5'd0;

                // 手型滞回：连续 M2_LOCK_FRAMES 帧同类才改状态
                if(S_m2_raw != S_m2_shape) begin
                    if((S_m2_agree + 4'd1) >= M2_LOCK_FRAMES) begin
                        S_m2_shape <= S_m2_raw;
                        S_m2_agree <= 4'd0;
                    end
                    else S_m2_agree <= S_m2_agree + 4'd1;
                end
                else S_m2_agree <= 4'd0;
            end
            else if(I_raw_tvalid) begin
                if(S_m2_rownew) begin
                    // 换行：先把上一行的段数并进本帧最大值，再从新行重新数
                    if(a_m2_runs > a_m2_max) a_m2_max <= a_m2_runs;
                    a_m2_runs <= {2'b0, S_m2_new};
                    a_m2_py   <= S_y_pos;
                    a_m2_prev <= 1'b0;
                end
                else begin
                    a_m2_runs <= S_m2_runs_n;
                    a_m2_prev <= S_m2_top[3];
                end

                // 指尖：本帧顶带里遇到的第一个像素（最上那一行的最左一个）
                if(!a_m2_got && (|S_m2_top)) begin
                    a_m2_got <= 1'b1;
                    a_m2_ty  <= {1'b0, S_y_pos};
                    a_m2_tx  <= S_m2_top[0] ? S_col0 : (S_m2_top[1] ? S_col1 :
                                (S_m2_top[2] ? S_col2 : S_col3));
                end
            end
        end

        // 给叠加画点用（上一帧结果，帧内稳定）
        wire [10:0] S_m2_tx = h_m2_tx;
        wire [10:0] S_m2_ty = h_m2_ty;
        // DBG 借用：P = {峰数[3:0], 2'b0, 指尖行[9:0]}、Q = {手型[2:0], 指尖列[10:0]}
        assign S_m2_dbg_p  = { h_m2_max[3:0], 2'b0, h_m2_ty[9:0] };
        assign S_m2_dbg_q  = { S_m2_shape, h_m2_tx };
        assign S_m2_dbg_on = (M2_EN != 0) && (M2_DBG != 0);

        // ROI 边界导出（软权重在 g_cent 里"只在窗口内投票"）
        assign S_roi_x0_w = S_roi_x0;
        assign S_roi_x1_w = S_roi_x1;
        assign S_roi_y0_w = S_roi_y0;
        assign S_roi_y1_w = S_roi_y1;

        // ---- 准星位置（钳到画面内，给调试图用）-------------------------------
        assign S_trk_x = (S_pos_x < 13'sd0)    ? 11'd0
                                               : ((S_pos_x > 13'sd1279) ? 11'd1279 : S_pos_x[10:0]);
        assign S_trk_y = (S_pos_y < 13'sd0)    ? 10'd0
                                               : ((S_pos_y > 13'sd719)  ? 10'd719  : S_pos_y[9:0]);
        assign S_trk_locked = S_locked;

        // ---- 运行时视图叠加 ---------------------------------------------------
        // 视图号 S_view = 提交字 recog_algo[15:12]（**运行时**，串口 `W 08 000X` 切换，不用重编译）。
        // 这是 M1 打磨期的主要调试手段：一次编译，串口切视图。
        //   0 / 1 = 融合掩码 + 准星（正常交付视图；0 号在 DIAG_MODE_SEL=0 时不叠加）
        //   2     = 背景帧预览（isp_top 接管画面，这里给融合掩码）
        //   3     = AWB 之前视图（同上）
        //   4     = **只看运动门**（绿）——查"亮区/桌面一直高亮"是不是运动门误报
        //   5     = **只看肤色门**（红）——查是不是肤色门误判
        //   6     = ROI 边框（蓝）+ 融合掩码
        //   7     = 三色诊断（红=只肤色 / 绿=只运动 / 黄=两者都过 / 蓝=ROI 边框）
        // 喂给 4/5/7 的是**原始**肤色/运动位（不经开运算、不经 ROI 门控）；
        // 喂给 0/1/6 的是 ROI 门控后的融合掩码。
        // 色码（3 bit）：0=原像素 1=掩码红 2=准星黄 3=只肤色红 4=只运动绿
        //                5=两者都过黄 6=ROI 边框蓝 7=准星青（保留）
        // 资源：准星 4 个 + ROI 边框 4 个比较器 × 4 个像素通道，≈60 LUT6 / 0 ERAM / 0 DSP。
        wire [3:0] S_view = (DIAG_OVL != 0) ? 4'd7 : S_mode_word[15:12];

        function [2:0] F_ovl_view;
            input [10:0] I_x;
            input [9:0]  I_y;
            input        I_fuse;      // 融合掩码（ROI 门控 + 开运算后）
            input        I_skin;      // 原始肤色门
            input        I_motion;    // 原始运动门
            input [2:0]  I_gest;      // M2.1 挥手提示色码（0 = 不闪）
            reg S_x_on, S_y_on, S_x_th, S_y_th, S_bx, S_by, S_border;
            begin
                // 臂长 ±CROSS_LEN、线宽 ±CROSS_TH（十字两个方向各一条粗线）
                S_x_on = (I_x + CROSS_LEN >= S_trk_x) && (I_x <= S_trk_x + CROSS_LEN);
                S_y_on = (I_y + CROSS_LEN >= S_trk_y) && (I_y <= S_trk_y + CROSS_LEN);
                S_x_th = (I_x + CROSS_TH  >= S_trk_x) && (I_x <= S_trk_x + CROSS_TH);
                S_y_th = (I_y + CROSS_TH  >= S_trk_y) && (I_y <= S_trk_y + CROSS_TH);
                // ROI 窗口边框：2 像素粗
                S_bx = ((I_x + 2 >= S_roi_x0) && (I_x <= S_roi_x0 + 1)) ||
                       ((I_x + 2 >= S_roi_x1) && (I_x <= S_roi_x1 + 1));
                S_by = ((I_y + 2 >= S_roi_y0) && (I_y <= S_roi_y0 + 1)) ||
                       ((I_y + 2 >= S_roi_y1) && (I_y <= S_roi_y1 + 1));
                S_border = (S_bx && (I_y >= S_roi_y0) && (I_y <= S_roi_y1)) ||
                           (S_by && (I_x >= S_roi_x0) && (I_x <= S_roi_x1));
                // M2.1 挥手提示：**画在对应屏幕边缘**（位置 + 颜色双重编码）
                if(((I_gest == 3'd3) && (I_x < GEST_VIS_W)) ||                            // 左挥：左边缘
                   ((I_gest == 3'd4) && (I_x > (11'd1279 - GEST_VIS_W))) ||               // 右挥：右边缘
                   ((I_gest == 3'd6) && (I_y > (10'd719 - GEST_VIS_W[9:0]))) ||           // 下劈：底边缘
                   ((I_gest == 3'd7) && (I_y < GEST_VIS_UNK_Y)))                          // 不明确：顶部细条
                    F_ovl_view = I_gest;
                // M2.2 指尖方点：颜色 = 手型（黄 = 张开、红 = 握拳；手型未知就不画）
                else if((S_m2_shape != 3'd0) &&
                        (I_x + {7'b0, M2_TIP_R} >= S_m2_tx) &&
                        (I_x <= S_m2_tx + {7'b0, M2_TIP_R}) &&
                        (I_y + {6'b0, M2_TIP_R} >= S_m2_ty[9:0]) &&
                        (I_y <= S_m2_ty[9:0] + {6'b0, M2_TIP_R}))
                    F_ovl_view = (S_m2_shape == 3'd2) ? 3'd5 : 3'd3;
                else if((S_x_on && S_y_th) || (S_y_on && S_x_th))
                    F_ovl_view = 3'd2;                  // 准星（黄）：所有视图都画
                else if(S_view == 4'd4)
                    F_ovl_view = I_motion ? 3'd4 : (S_border ? 3'd6 : 3'd0);
                else if(S_view == 4'd5)
                    F_ovl_view = I_skin   ? 3'd3 : (S_border ? 3'd6 : 3'd0);
                else if(S_view == 4'd7) begin
                    if(I_skin && I_motion) F_ovl_view = 3'd5;   // 两者都过（黄）
                    else if(I_skin)        F_ovl_view = 3'd3;   // 只过肤色（红）
                    else if(I_motion)      F_ovl_view = 3'd4;   // 只过运动（绿）
                    else                   F_ovl_view = S_border ? 3'd6 : 3'd0;
                end
                else if(S_view == 4'd6)
                    F_ovl_view = S_border ? 3'd6 : (I_fuse ? 3'd1 : 3'd0);
                else
                    // 0/1/2/3：正常融合视图。**形状门不过时不涂红**（否则门只挡跟踪、屏幕上桌面
                    // 仍然是红的 —— 用户看到的就是"桌面高亮"）。宁可画面干净，也不误导。
                    F_ovl_view = (I_fuse && !S_gate_bad) ? 3'd1 : 3'd0;
            end
        endfunction

        wire [11:0] S_ovl_rt = { F_ovl_view(S_col3, S_y_pos, S_mask_gated[3], S_skin_use[3], S_motion_mask[3], S_gest_vis),
                                 F_ovl_view(S_col2, S_y_pos, S_mask_gated[2], S_skin_use[2], S_motion_mask[2], S_gest_vis),
                                 F_ovl_view(S_col1, S_y_pos, S_mask_gated[1], S_skin_use[1], S_motion_mask[1], S_gest_vis),
                                 F_ovl_view(S_col0, S_y_pos, S_mask_gated[0], S_skin_use[0], S_motion_mask[0], S_gest_vis) };

        assign S_ovl_sel = S_ovl_rt;

    end
    else begin : g_notrack
        // MASK_SRC=0（边缘自检回归）时不要 ROI/平滑，保持 M0 的行为
        assign S_mask_gated = S_mask_sel;
        assign S_trk_x      = 11'd640;
        assign S_trk_y      = 10'd360;
        assign S_trk_locked = 1'b0;
        assign S_m2_dbg_p   = 16'd0;
        assign S_m2_dbg_q   = 14'd0;
        assign S_m2_dbg_on  = 1'b0;
        assign S_roi_x0_w   = 11'd0;
        assign S_roi_x1_w   = 11'd1279;
        assign S_roi_y0_w   = 10'd0;
        assign S_roi_y1_w   = 10'd719;
        assign S_ovl_sel    = 12'd0;
    end
    endgenerate

    // ---- 掩码统计器的输入流选择 ---------------------------------------------
    wire       S_ms_valid = (MASK_SRC == 0) ? I_edge_tvalid : I_raw_tvalid;
    wire       S_ms_user  = (MASK_SRC == 0) ? I_edge_tuser  : I_raw_tuser;
    wire       S_ms_last  = (MASK_SRC == 0) ? I_edge_tlast  : I_raw_tlast;

    // 调试图出口：把"ROI 门控后的实时掩码"和 Step 3 的跟踪结果引出去
    // （不改统计、不跨域；只有 isp_top 的 MASK_PREVIEW 调试图会消费）
    assign O_mask_px      = S_mask_gated;
    assign O_track_x      = S_trk_x;
    assign O_track_y      = S_trk_y;
    assign O_track_locked = S_trk_locked;
    assign O_ovl_sel      = S_ovl_sel;
    assign O_bg_px        = S_bg_cur;

    // ---- 掩码统计器（M0 建好，M1 起换掩码源、M1 Step 3 起吃 ROI 门控后的掩码）---
    mask_stats u_mask_stats (
        .I_clk  (I_clk),
        .I_rst_n(I_rst_n),
        .I_mask (S_mask_gated),
        .I_valid(S_ms_valid),
        .I_user (S_ms_user),
        .I_last (S_ms_last),
        .O_cnt  (S_mcnt),
        .O_xmin (S_xmin),
        .O_xmax (S_xmax),
        .O_ymin (S_ymin),
        .O_ymax (S_ymax),
        .O_sumx (S_sumx),
        .O_sumy (S_sumy),
        .O_empty(S_empty)
    );

    // ---- M2.1：GEST_DBG=1 时把 P/Q/R 借给"挥手方向"观测 ------------------------
    // 编码见上面 g_gest 的段落注释：P = {Σdx,Σdy}（±127 钳位 +128）、
    // Q = {方向, 事件计数}、R = {本帧 dx, 本帧 dy}（±31 钳位 +32）。
    // GEST_DBG=0（交付口径）时下面三行与 M1 逐字节一致。
    function [7:0] F_gest_sat8;     // 12 位有符号 → 钳 ±127 后 +128（0x80 = 0）
        input signed [11:0] I_v;
        begin
            if(I_v > 12'sd127)        F_gest_sat8 = 8'hFF;
            else if(I_v < -12'sd127)  F_gest_sat8 = 8'h01;
            else                      F_gest_sat8 = I_v[7:0] + 8'd128;
        end
    endfunction

    function [5:0] F_gest_sat6;     // 12 位有符号 → 钳 ±31 后 +32（0x20 = 0）
        input signed [11:0] I_v;
        begin
            if(I_v > 12'sd31)         F_gest_sat6 = 6'd63;
            else if(I_v < -12'sd31)   F_gest_sat6 = 6'd1;
            else                      F_gest_sat6 = I_v[5:0] + 6'd32;
        end
    endfunction

    wire S_gest_dbg_on = (GEST_EN != 0) && (GEST_DBG != 0) &&
                         (MASK_SRC != 0) && (USE_CENTROID != 0);

    // M2.2 先借：P = {峰数[3:0], 2'b0, 指尖行[9:0]}、Q = {手型[2:0], 指尖列[10:0]}（见 M2_* 参数）
    assign O_mask_cnt_shift = S_m2_dbg_on ? S_m2_dbg_p
                            : S_gest_dbg_on
                              ? { F_gest_sat8(S_gest_sx), F_gest_sat8(S_gest_sy) }
                              : ((DIAG_CHROMA != 0) ? S_ch_mot : (S_mcnt >> 4));
    // DIAG_CHROMA=1 时 Q/R 改报帧内 (d1,d2) 极值（调试用，见参数说明）
    assign O_bbox_x         = S_m2_dbg_on ? S_m2_dbg_q
                            : S_gest_dbg_on
                              ? { S_gest_dir, S_gest_cnt }
                              : ((DIAG_CHROMA != 0) ? S_ch_word_x
                                                    : {S_xmin[10:4], S_xmax[10:4]});
    assign O_bbox_y         = S_gest_dbg_on
                              ? { F_gest_sat6(S_gest_dx), F_gest_sat6(S_gest_dy) }
                              : ((DIAG_CHROMA != 0) ? S_ch_word_y
                                                    : {S_ymin[9:4],  S_ymax[9:4]});


    // 用边沿流（比 raw 流晚 2 拍）的帧首翻 toggle：此刻 tap 计数与掩码统计都已锁存
    // （肤色源在 raw tuser 那一拍就锁存完了，比这早 2 拍，数据先稳定、toggle 后翻转，
    // 正是"发送侧数据先于 toggle 稳定"的跨域约定）。同样**不能闸在 tvalid 上**——
    // 理由见上面 tap 计数器那段的注释。
    always @(posedge I_clk or negedge I_rst_n) begin
        if(!I_rst_n)
            O_status_toggle <= 1'b0;
        else if(I_edge_tuser)
            O_status_toggle <= ~O_status_toggle;
    end

    // 说明：S_sumx / S_sumy / S_empty 在 M0 里没有消费者（会综合掉），M1 接质心与
    // 丢失判定时自然回来——接口先冻结，省得 M1 再改一次模块端口。

    // ---- CTRL_SYNC 上行：M0 原样回传收到的字（往返自检）-----------------------
    assign O_ctrl_tx_data  = I_ctrl_rx_data;
    assign O_ctrl_tx_valid = I_ctrl_rx_valid;

endmodule
