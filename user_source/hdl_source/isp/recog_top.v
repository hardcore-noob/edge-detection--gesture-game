    output reg         O_status_toggle,

    // 实时掩码（每拍 4 bit，bit0 = 字内最左像素 [95:72]）：**只给调试图用**
    // （isp_top 的 MASK_PREVIEW 把它涂红叠在 RAW 画面上看效果），统计/跨域都不用它。
    // 与 I_raw_tdata 严格同拍。
    output wire [3:0]  O_mask_px,

    // Step 3 跟踪结果 + 叠加选择：目前只有 isp_top 的 MASK_PREVIEW 调试图消费，
    // 正规交付路径（MASK_PREVIEW=0）里整段会被综合消掉，画面不受任何影响。
    output wire [10:0] O_track_x,        // α-β 平滑后的准星列（0..1279）
    output wire [9:0]  O_track_y,        // 平滑后的准星行（0..719）
    output wire        O_track_locked,   // 已锁定（连续命中 ≥ LOCK_FRAMES）
    // 背景帧当前块的灰度（调试图：isp_top 的"背景帧预览"模式直接拿它当像素显示）
    output wire [7:0]  O_bg_px,
    // 每像素 3 bit（低 12 位共 4 像素）：0=原像素 1=掩码高亮(红) 2=准星(黄)
    //                                  3/4/5=诊断色(只肤色/只运动/两者) 6=ROI 边框 7=诊断准星
    output wire [11:0] O_ovl_sel,

    // 【第 4 轮】一键示教的"2 秒闪叠加"指示：一次采样窗结束（**不论判定过不过**）后拉高
    // ~120 帧（≈2 s）。isp_top 把它并进叠加使能 S_ovl_en → 示教完立刻在画面上看"手有没有
    // 被掩码点亮"（判定不通过时画面照旧会闪 2 s，"没点亮 = 没采到，重来"）。平时恒 0。
    output wire        O_teach_flash,
    // 【M2.1】挥手事件指示（≈0.4 s 高）：isp_top 把它并进叠加使能，于是"挥手 = 屏幕上立刻
    // 出现一条按方向着色的横条"，不用串口、不用按键。平时恒 0；GEST_VIS=0 时恒 0（被裁掉）。
    output wire        O_gest_flash
);

    // ---- 模式提交字锁存（同域，无需两级同步）--------------------------------
    // M0.1 只锁存不消费——综合会把没人用的寄存器裁掉，等 M1 真正用它时才产生资源。
    // ========================================================================
    // 运行时预设档（2026-09-27）：直接看提交字 recog_algo[15:12]，串口 `W 08 000X` 切，
    // **不用重编译**。PARAM_BUS（A 段 0x40~0x7F）还没通，先拿视图号当预设档顶着。
